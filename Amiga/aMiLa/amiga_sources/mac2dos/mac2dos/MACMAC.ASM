CLRBOX	MACRO	;BOX ID,COLOR,OPT=FULL
	IFEQ	NARG-2
	MOVE.W	#\1_LE+2,D0
	SWAP	D0
	MOVE.W	#\1_TE+1,D0
	MOVE.W	#\1_WD-4,D1
	SWAP	D1
	MOVE.W	#\1_HT-2,D1
	MOVEQ	#\2,D2
	ENDC
	IFNE	NARG-2
	MOVE.W	#\1,D0
	SWAP	D0
	MOVE.W	#\2,D0
	MOVE.W	#\3,D1
	SWAP	D1
	MOVE.W	#\4,D1
	MOVEQ	#\5,D2
	ENDC
	JSR	CLEAR_BOX
	ENDM

