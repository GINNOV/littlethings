	 INCLUDE "D2DMAC.ASM"

	XREF	_LVODebug,_LVOSignal

	XREF	DISK_INIT,DISK_LOG,DISK_EXIT,DR_BASE,D2D_TASK
	XREF	LIST_DIR,LIST_AD_DIR
	XREF	A.,TMP.,A_FNAME.,M_FNAME.,NAME.
	XREF	OPEN_FILE,NEW_FILE,READ_CLUSTER,WRITE_CLUSTER,CLOSE_FILE
	XREF	EXPAND_MD_WILD,FIND_FIRST,FIND_NEXT
	XREF	FIND_FIRST_AD,FIND_NEXT_AD
	XREF	OPEN_AD_FILE,CREATE_AD_FILE,CLOSE_AD_FILE
	XREF	READ_AD_FILE,WRITE_AD_FILE
	XREF	ERR_CODE,BYTCNT,FILEHANDLE,DISK_TYPE,DRIVE_SEL
	XREF	KBD_INPUT,FORMAT_DISK,GET_CHAR,MOTOR_OFF
	XREF	CHANGE_AD_DIR,SEARCH_PATH,MOVE_CHARS
	XREF	DELETE_FILE,DELETE_AD_FILE
	XREF	STRIP_CR,ADD_CR
	XREF	WILD_FLAG,LOCK,DIRPTR
	XREF	MSG_PORT,DOUBLE_STEP,OriginalDir

	XDEF	INPBUFF,INPBUF.,GETCMD
	XDEF	STDIN,STDOUT,LIBRARY_BASE,GRAPHICS_BASE
	XDEF	MD_DRV.,MD_PATH.,AD_DRV.,TMP_PATH.,IS_3.5,ATARI_FLAG

INPBUF_SIZE	EQU	80	;80-CHAR TEXT BUFFER
DeviceList	EQU	$15E	;OFFSET TO EXEC DEVICE LIST FROM SYSBASE
DOSSignature	EQU	$F8001C ;DOS SIGNATURE IN ROM AREA
TaskPort	EQU	$5C	;offset to task's port
LINSIZ		EQU	100	;max size of test during type

GO:
	MOVE.L  A7,initialSP		;initial task stack pointer
	MOVEA.L 4,A6
	MOVE.L  A6,SysBase
	LEA     DosName,A1
	ZAP	D0
	CALLSYS	OpenLibrary		;OPEN DOS LIBRARY
	MOVE.L  D0,LIBRARY_BASE
	ZAPA	A1
	CALLSYS	FindTask
	MOVE.L	D0,D2D_TASK		;save ptr for msg ports
	MOVEA.L D0,A4
	TST.L   $AC(A4)			;invoked from cli?
	BNE.S	COMMON			;yes...not WB
FROM_WB:
	LEA     TaskPort(A4),A0
	CALLSYS	WaitPort
	LEA     TaskPort(A4),A0
	CALLSYS	GetMsg
	MOVE.L	D0,WBenchMsg		;save WBench msg for reply
	MOVE.L	D0,A2
	MOVE.L	28(A2),D0		;NUMBER OF PARAMS
	MOVE.L	36(A2),A2		;PTR TO PARAM LIST
2$:	MOVE.L	(A2),D1			;GET BPTR TO LOCK
	IFZL	LIBRARY_BASE,COMMON		;ADOS version error, from WB
	CALLSYS	CurrentDir,LIBRARY_BASE
COMMON:	IFZL	LIBRARY_BASE,EXIT_TO_DOS

	LEA	GRAPHICS_NAME,A1
	ZAP	D0
	CALLSYS	OpenLibrary,SysBase
	MOVE.L	D0,GRAPHICS_BASE
	BEQ	ABORT
	MOVE.L	#WIN,D1
	MOVE.L	#NEW,D2
	CALLSYS	Open,LIBRARY_BASE
	MOVE.L	D0,STDIN
	MOVE.L	D0,STDOUT
	BEQ	ABORT
	CRLF.
	CALL	DISK_INIT	;INIT SOME PARAMS + ALLOC CHIP MEM
	ERROR	NO_MEM		;CANT GET CHIP MEMORY
	DISP.	GREET

	IFEQ	DEMO-2		;IF AN EVAL, SAY SO
	CRLF.
	DISP.	EVAL.
	ENDC

	IFEQ	DEMO-1		;IF A DEMO, SAY SO
	BSR	Dispdemo
	ENDC

	CLR.B	MD_DRV.		;IN CASE OF GARBAGE

AGAIN:
	MOVE.B	#1,MD_PATH.
	MOVE.B	#'\',MD_PATH.+1 ;SET UP DEFAULT INITIAL PATH
1$:	CRLF.
	PROMPT. WHICH_DRIVE.	;ASK WHICH DRIVE FOR MS_DOS
	CALL	KBD_INPUT	;GET REPLY
	STRIP_LB. INPBUF.	;CLEAN UP REPLY
	UCASE.	INPBUF.
	IFZ	INPBUF.,4$	;NEED A DRIVE
	RIGHT.	INPBUF.,#1,TMP. ;CHECK FOR TRAILING COLON
	MOVE.B	TMP.+1,D0	;GET CHAR
	CMP.B	#':',D0		;IS IT?
	BEQ	2$		;YES...DONT NEED ONE
	ACHAR.	#':',INPBUF.	;ELSE ADD A COLON
2$:	MOVE.B	#$77,D0
	IFEQ.	DF0.,INPBUF.,3$	;DRIVE 0
	MOVE.B	#$6F,D0
	IFEQ.	DF1.,INPBUF.,3$ ;DRIVE 1
	MOVE.B	#$5F,D0
	IFEQ.	DF2.,INPBUF.,3$ ;DRIVE 2
	MOVE.B	#$3F,D0
	IFEQ.	DF3.,INPBUF.,3$ ;DRIVE 3
4$:	DISP.	DRV_ERR.	;ELSE TELL OP HE MUST ENTER A DRIVE
	BRA	1$

3$:	MOVE.B	D0,DRIVE_SEL	;STORE DRIVE SELECT CODE
	MOVE.	INPBUF.,MD_DRV. ;NOW HAVE PROPER DRIVE CODE
	CALL	CHECK_DRIVE_TYPE ;NOW SEE IF DRIVE EXISTS ON THIS CONFIG
	NOERROR 5$		;OK
	CRLF.
	MOVE.	NO_DRV1.,TMP.	;CANT FIND IT...MUST BE NON-AMIGA 5.25"
	APPEND.	MD_DRV.,TMP.
	ACHAR.	#'.',TMP.
	DISP.	TMP.
	DISP.	NO_DRV2.	;WARN THE OPERATOR
5$:	CALL	INHIBIT_ACCESS	;TRY TO STOP DOS ACCESS
	IFNE.	MD_DRV.,DF0.,6$ ;NOT USING DF0
	CRLF.
	DISP.	USERAM1.	;WARNING TO USE RAM:
	DISP.	USERAM2.
6$:	CRLF.
	DISP.	HOW_TO.
GETCMD:
	CRLF.
	CALL	MOTOR_OFF	;TURN MS-DOS DRIVE MOTOR OFF
	PROMPT. D2D.		;ISSUE COMMAND PROMPT
	CALL	KBD_INPUT	;GET OPERATOR INPUT INTO INPBUF.

* DECODE THE COMMAND IN THE BUFFER

	UCASE.	INPBUF.		 ;WORK IN UPPER CASE ONLY
	SCAN.	INPBUF.,A.		;GET COMMAND TOKEN
	STRIP_LB. A.			;ALLOW LEADING BLANKS
	STRIP_LB. INPBUF.		;FIX UP REST OF COMMAND, IF ANY
	LEFT.	A.,#3,TMP.		;USE UP TO 3 CHARS
	IFEQ.	TMP.,COPY.,CPYFIL
	IFEQ.	TMP.,TYPE.,TYPFIL
	IFEQ.	TMP.,DIR.,DIRECTORY
	IFEQ.	TMP.,FORMAT.,FMAT
	IFEQ.	TMP.,CD.,CHGDIR
	IFEQ.	TMP.,CHG.,CHGDIR
	IFEQ.	TMP.,QUES.,HELP
	IFEQ.	TMP.,HELP.,HELP
	IFEQ.	TMP.,H.,HELP
	IFEQ.	TMP.,EXIT.,EXIT
	IFEQ.	TMP.,X.,EXIT
	IFEQ.	TMP.,DELETE.,DELFIL
	IFEQ.	TMP.,RSTART.,RESTART
	DISP.	BAD_CMD.
	BRA	GETCMD

HELP:	WRITEFILE STDOUT,#HLPTEXT,#HLPTEXTLEN
	BRA	GETCMD

TYPFIL:
	CLR.B	MS_FLAG		;Not from MS-DOS
	MOVE.	INPBUF.,A.	;GET_DRIVE WORKS WITH A.
	IFZ	A.,BAD_ARGS	;NEED DRIVE AND FILE
	CALL	GET_DRIVE	;NEXT 4 CHARS MUST BE DRIVE CODE
	BEQ	1$		;MS-DOS DRIVE CODE
	CALL	FIX_AD_NAME	;SCAN AD FILENAME INTO A.
	MOVE.	A.,A_FNAME.
	CALL	OPEN_AD_FILE	;TRY TO FIND THE FILE
	ERROR	NO_FILE	 	;CANT FIND IT
	BRA.S	2$

* COME HERE TO TYPE AN MS-DOS FILE.

1$:	SETF	MS_FLAG
	CALL	FOLLOW_PATH	;BUILD AND SEARCH PATH, FIND FILE
	ERROR	NO_FILE		;DIDN'T FIND IT
	CALL	CHECK_SUBDIR	;SPECIFIED A SUBDIR?
	ERROR	NO_FILE		;YEAH, THE TURKEY
	CALL	OPEN_FILE	;OPEN IT AND GET READY TO READ

* Type text from file 1 line at a time

2$:	CLR.W	BYTCNT		;START WITH EMPTY BUFFER
	CLR.B	LINCNT
3$:	CMP.B	#21,LINCNT	;DISPLAYED ENOUGH?
	BLS.S	4$		;NO...
	BSR	WAIT_MORE	;ELSE WARN AND WAIT
	ERROR	7$		;OP WANTS TO BAIL OUT
4$:	BSR	READ_LINE	;FILL LINE BUFFER
	ERROR	6$		;EOF
	BSR	WRITE_LINE	;WRITE LINE BUFFER TO SCREEN
	BRA.S	3$		;LOOP
6$:	BSR	WAIT_EOF	;END OF FILE
7$:	CALL	CLOSE_AD_FILE	;THATS ALL
	BRA	GETCMD

READ_LINE:
	LEA	LINBUF,A1
	MOVE.L	A1,LINPTR
	MOVE.W	#LINSIZ,LBCNT	;MAX SIZE OF 1 LINE IN CHARS
5$:	IFZ	MS_FLAG,1$	;1=FROM MS-DOS, 0=FROM AMIGA
	CALL	GET_CHAR	;GET NEXT MS-DOS CHAR
	ERROR	8$
	BRA.S	2$
1$:	CALL	GET_AD_CHAR	;ELSE GET NEXT ADOS CHAR
2$:	ERROR	9$		;READ ERROR...ABORT
	CMP.B	#32,D0		;IN ASCII RANGE?
	BCC.S	4$		;YES
	CMP.B	#10,D0		;NO...LF?
	BEQ.S	4$		;YES...KEEP IT
	CMP.B	#9,D0		;TAB?
	BNE.S	5$		;NO...IGNORE CHAR
	MOVE.B	#32,D0
4$:	MOVE.L	LINPTR,A1
	MOVE.B	D0,(A1)+	;INTO BUFFER
	MOVE.L	A1,LINPTR
	CMP.B	#10,D0		;IS IT END OF LINE?
	BEQ.S	8$		;YES...STOP HERE
	DECB	LBCNT
	BNE.S	5$
8$:	MOVE.L	A1,D0		;CALC BYTES IN LINBUF
	SUB.L	#LINBUF,D0	;LEAVE IN D0
	BNE.S	9$
	STC
9$:	RTS

GET_AD_CHAR:
	MOVE.L	FILEHANDLE,D1
	MOVE.L	#INPBUF.,D2
	MOVEQ	#1,D3
	CALLSYS	Read,LIBRARY_BASE
	TST.L	D0
	BEQ.S	8$
	MOVE.B	INPBUF.,D0
	RTS
8$:	STC
	RTS

WRITE_LINE:
	MOVE.L	STDOUT,D1
	MOVE.L	#LINBUF,D2
	MOVE.L	D0,D3
	CALLSYS	Write,LIBRARY_BASE
	INCB	LINCNT
	RTS

WAIT_EOF:
	LEA	EOF.,A0		;EOF MSG
	BSR.S	PRINT_WIN
	BRA.S	WAIT_COM

WAIT_MORE:
	LEA	PMORE.,A0	;PRESS SPACE FOR MORE
	BSR.S	PRINT_WIN
	CLR.B	LINCNT

WAIT_COM:
	READFILE STDOUT,#INPBUFF,#INPBUF_SIZE
	LEA	CLEAN.,A0
	BSR.S	PRINT_WIN
	CMP.B	#27,INPBUFF	;ESCAPE?
	BNE.S	9$		;NO...'MORE'
	STC			;EOF
	RTS
9$:	CLC
	RTS

* WRITES TEXT STRING WITH LEADING COUNT IN A0 TO SPECIAL WINDOW.

PRINT_WIN:
	ZAP	D3
	MOVE.B	(A0)+,D3	;GET MSG LEN
	MOVE.L	A0,D2		;PTR TO STRING
	MOVE.L	STDOUT,D1
	CALLSYS	Write,LIBRARY_BASE
	RTS

* DELETE FILE FROM DISK

DELFIL:
	MOVE.	INPBUF.,A.	;GET_DRIVE WORKS WITH A.
	IFZ	A.,BAD_ARGS	;NEED DRIVE AND FILE
	CALL	GET_DRIVE	;NEXT 4 CHARS MUST BE DRIVE CODE
	BEQ	3$		;MS-DOS DRIVE CODE
	CALL	FIX_AD_NAME	;SCAN AD FILENAME INTO A.
	MOVE.	A.,A_FNAME.
	CALL	OPEN_AD_FILE	;TRY TO FIND THE FILE
	ERROR	NO_FILE	 ;CANT FIND IT
	CALL	CLOSE_AD_FILE
	CALL	DELETE_AD_FILE
	BRA	GETCMD

* COME HERE TO DELETE AN MS-DOS FILE.

3$:	CALL	FOLLOW_PATH	;BUILD AND SEARCH PATH, FIND FILE
	ERROR	NO_FILE	 ;DIDN'T FIND IT
	CALL	CHECK_SUBDIR	;SUBDIRECTORY?
	ERROR	NO_FILE
	CALL	OPEN_FILE	;OPEN IT AND GET READY TO READ
	CALL	DELETE_FILE
	BRA	GETCMD

* COPIES A FILE FROM ONE FORMAT TO THE OTHER.

	IFNE	DEMO-1

CPYFIL:
	CLR.B	ASCII_FLAG
	CLR.B	REPLACE_FLAG
	CLR.B	WILD_FLAG
	CALL	SCAN_OPTIONS	;FIND AND REMOVE -A AND -R OPTIONS

* FIRST CHECK OUT SOURCE DRIVE, FILE, ETC.

	IFZ	INPBUF.,BAD_ARGS ;COPY COMMAND FORMAT ERROR
	MOVE.	INPBUF.,TMP.	;LEAVE INPBUF. INTACT FOR A-TO-M
	SCAN.	TMP.,A.
	CALL	GET_DRIVE	;TRY TO EXTRACT SOURCE DRIVE
	ERROR	CPY_A_M	 ;NO DRIVE...ASSUME AMIGADOS TO MS-DOS
	BNE	CPY_A_M	 ;AMIGA DOS DRIVE CODE--AMIGADOS TO MS-DOS

* COPY FROM MS-DOS TO AMIGA-DOS

	SCAN.	INPBUF.,A.	;M-TO-A, GET SOURCE STRING
	CALL	FOLLOW_PATH	;BUILD AND SEARCH PATH, FIND FILE
21$:	ERROR	NO_FILE	 ;CANT FIND FILE
	CALL	CHECK_SUBDIR	;SUBDIRECTORY?
	NOERROR 22$		;NO
	CALL	FIND_NEXT	;ELSE TRY FOR NEXT FILE
	BRA.S	21$
22$:	CALL	OPEN_FILE	;NOW TRY TO OPEN IT

*	NOW CHECK OUT DESTINATION DRIVE, FILE, ETC.

2$:	CALL	FIX_AD_NAME	;CHECK FOR AD QUOTED FILENAME, MOVE TO A.
	CLR.B	AD_PREFIX.	;START WITH NO PREFIX
	IFZ	A.,3$		;NO DEST SPECIFIED...USE DEFAULTS
	MOVE.	A.,AD_PREFIX.	;DRIVE AND POSSIBLE DIRECTORY
	CALL	GET_DRIVE	;SEE IF WE GOT A DRIVE CODE
	ERROR	4$		;NO DRIVE...ASSUME A. HAS IT ALL
	BEQ	DUP_DRV	 ;OOPS...CANT SPECIFY MS-DOS DRIVE AGAIN
	RIGHT.	A.,#1,TMP.	;GET LAST CHAR
	MOVE.B	TMP.+1,D0
	CMP.B	#':',D0		;DRIVE ONLY?
	BEQ.S	3$		;YES...NEED FILE NAME
	CMP.B	#'/',D0		;DRIVE AND DIRECTORY?
	BEQ.S	3$		;YES
4$:	IFZ	WILD_FLAG,5$	;NO WILD CARDS...DONT USE SOURCE NAME
3$:	MOVE.	AD_PREFIX.,A.	;ELSE USE PREFIX TO BUILD FULL NAME
	IFZ	A.,1$		;DONT PUT '/' ON EMPTY PREFIX
	RIGHT.	A.,#1,TMP.	;GET TRAILING CHAR
	MOVE.B	TMP.+1,D0	;CHECK IT OUT
	CMP.B	#':',D0
	BEQ.S	1$		;DONT NEED (OR WANT) SLASH AFTER COLON
	CMP.B	#'/',D0
	BEQ.S	1$		;OR TWO SLASHES, FOR THAT MATTER
	ACHAR.	#'/',A.
1$:	APPEND. NAME.,A.	;ADD NAME FROM MS-DOS FILE
5$:	MOVE.	A.,A_FNAME.	;THIS IS FINAL NAME TO USE
	CALL	OPEN_AD_FILE	;DOES IT ALREADY EXIST?
	ERROR	20$		;NO
	MOVE.	A_FNAME.,TMP.
	CALL	DUP_QUERY	;YES...ASK WHAT TO DO
	ERROR	7$		;OP SAYS BAIL OUT
	CALL	CLOSE_AD_FILE	;ELSE, UNLOCK IT
20$:	CALL	CREATE_AD_FILE	;OPEN NEW AMIGADOS FILE
	ERROR	OPEN_ERR	;OOPS...SOMETHING IS WRONG
	IFZ	WILD_FLAG,6$	;NO WILD CARD OP
	PROMPT. CPYING.
	DISP.	NAME.
6$:	CALL	READ_CLUSTER	;HERE WE GO...READ SOMETHING IN
	ERROR	10$		;ERROR READING DISK
	TST.W	BYTCNT		;GOT ANYTHING?
	BEQ.S	7$		;NO...TREAT AS EOF
	IFZ	ASCII_FLAG,8$	;NO CONVERSION
	CALL	STRIP_CR	;ELSE GET RID OF CR'S
8$:	CALL	WRITE_AD_FILE	;WRITE IT OUT TO AMIGA FILE
	ERROR	10$		;WRITE FAILURE
	BRA.S	6$		;LOOP FOR ALL OF FILE
7$:	CALL	CLOSE_AD_FILE	;THATS ALL FOLKS!
9$:	IFZ	WILD_FLAG,GETCMD
	CALL	FIND_NEXT	;TRY FOR ANOTHER FILE
	ERROR	GETCMD		;NONE
	CALL	CHECK_SUBDIR	;IS IT A SUBDIR?
	ERROR	9$		;IT IS...DONT COPY IT
	CALL	OPEN_FILE
	BRA	3$
10$:	CALL	CLOSE_AD_FILE
	BRA	GETCMD

* COPY FROM AMIGA-DOS TO MS-DOS

CPY_A_M:
	CALL	FIX_AD_NAME	;CHECK FOR AD QUOTED NAME, MOVE TO A.
	MOVE.	A.,A_FNAME.	;THIS IS THE FILE NAME
	CALL	FIND_FIRST_AD	;TRY TO FIND AND OPEN THE FILE
	ERROR	NO_FILE	 ;CANT FIND IT
	CLR.B	MD_PREFIX.	;START WITH NO PREFIX
	SCAN.	INPBUF.,A.	;GET DEST STRING
	IFZ	A.,10$		;NO STRING...USE EXISTING PATH + DEFAULTS
	CALL	GET_DRIVE	;CHECK FOR MS-DOS DRIVE
	ERROR	5$		;MISSING DEST DRIVE CODE
	BNE	5$		;TOO BAD...DIDN'T GIVE US A DRIVE
	CLIP.	#4,A.		;GET RID OF DRIVE CODE
	IFZ	A.,10$		;NOTHING LEFT...USE FULL PATH AND DEFAULT
	CMP.B	#'\',A.+1	;LEADING '\'?
	BEQ.S	4$		;YES...DONT USE CURRENT PATH
10$:	MOVE.	MD_PATH.,TMP.	;NO...SET UP FULL PATH STRING
	CMP.B	#1,MD_PATH.	;SINGLE SLASH?
	BNE.S	11$		;NO
	CMP.B	#'\',MD_PATH.+1
	BEQ.S	4$		;YES...DONT ADD ANOTHER
11$:	ACHAR.	#'\',TMP.
	APPEND. A.,TMP.
	MOVE.	TMP.,A.
4$:	RIGHT.	A.,#1,TMP.	;SEE IF STRING ENDS IN '\'
	CMP.B	#'\',TMP.+1	;DOES IT?
	BNE.S	12$		;NO...OP GAVE US FULL STRING...USE IT
	MOVE.	A.,MD_PREFIX.	;ELSE MAKE THIS THE ENTIRE PREFIX
9$:	CALL	VALIDATE_AD_NAME ;VERIFY VALID NAME OR GET ANOTHER
	MOVE.	MD_PREFIX.,A.
	APPEND. NAME.,A.	;DEFAULT TO AMIGA-DOS FILE NAME
12$:	MOVE.	A.,M_FNAME.
	CALL	SEARCH_PATH	;LOAD SUBDIR, IF ANY
	ERROR	24$		;PROBLEM WITH PATH...CLOSE AD FILE AND EXIT
	MOVE.	M_FNAME.,A.	;WHATS LEFT IS REAL FILE NAME
	CALL	VALIDATE_NAME	;CHECK FOR VALID CHARS (MAY BE REDUNDANT)
	ERROR	8$		;CANT TAKE THE NAME
	CALL	EXPAND_MD_WILD	;PUT INTO 11-CHAR FORMAT W/BLANK FILL
	CALL	FIND_FIRST	;DOES IT ALREADY EXIST?
	ERROR	2$		;NO...THATS OKAY
	MOVE.	M_FNAME.,TMP.
	CALL	DUP_QUERY	;YES...ASK WHAT TO DO
	ERROR	8$		;OP SAYS BAIL OUT
	CALL	OPEN_FILE	;SET UP BASE CLUSTER
	CALL	DELETE_FILE	;ELSE GET RID OF SUCKER
2$:	IFZ	WILD_FLAG,22$	;NO WILD CARD OP
	PROMPT. CPYING.
	DISP.	M_FNAME.
22$:	CALL	NEW_FILE	;OPEN A NEW MS-DOS FILE
	ERROR	24$		;NO DIRECTORY SPACE, ETC.
3$:	IFZ	ASCII_FLAG,20$	;NO ASCII CONVERSION
	CALL	ADD_CR		;CHAR-BY-CHAR ASCII CONVERSION
	ERROR	24$		;DISK FULL OR OTHER ERROR
	BRA.S	7$		;DONE
20$:	CALL	READ_AD_FILE	;READ IN A CLUSTER
	ERROR	24$
	TST.W	BYTCNT		;GOT ANYTHING?
	BEQ.S	7$		;NO...TREAT AS EOF
	CALL	WRITE_CLUSTER	;ELSE WRITE OUT TO MS_DOS
	ERROR	24$
	BRA.S	3$		;LOOP
5$:	DISP.	DRV_ERR.	;DEST DRIVE CODE MISSING
	BRA	GETCMD
6$:	DISP.	DUP_FILE.	;DUPLICATE FILE NAME
	BRA.S	8$
7$:	CALL	CLOSE_FILE	;FINISH UP MS-DOS FILE
8$:	CALL	CLOSE_AD_FILE	;AND AMIGA-DOS FILE
	IFZ	WILD_FLAG,25$	;UNLOCK
	CALL	FIND_NEXT_AD	;TRY FOR ANOTHER FILE
	NOERROR 9$
	BRA	25$
24$:	CALL	CLOSE_AD_FILE	;MS-DOS ERROR, CLEAN UP
25$:	MOVE.L	LOCK,D1
	MOVE.L	LIBRARY_BASE,A6
	CALLSYS	UnLock		;UNLOCK DIRECTORY
	BRA	GETCMD

	ENDC

	IFEQ	DEMO-1
CPYFIL:
	BSR.S	Dispdemo
	BRA	GETCMD

Dispdemo:
	CRLF.
	DISP.	DMO1.
	DISP.	DMO2.
	DISP.	DMO3.
	DISP.	DMO4.
	DISP.	DMO5.
	DISP.	DMO6.
	RTS

	ENDC

* CHECKS WHAT TO DO IF DEST FILE ALREADY EXISTS.  IF REPLACE_FLAG SET,
* REPLYS CY=0.  OTHERWISE ASKS OP WHAT TO DO, AND SETS CY=1 IF ABORT.

DUP_QUERY:
	IFNZ	REPLACE_FLAG,1$ ;REPLACE OPTION ON
	PROMPT. DUP1.		;TELL OP ABOUT IT
	PROMPT. TMP.		;WHICH FILE
	PROMPT. DUP2.
	BSR.S	YES_OR_NO
	ERROR	DUP_QUERY
	CMP.B	#'Y',D0
	BEQ.S	1$
	STC
1$:	RTS

YES_OR_NO:
	CALL	KBD_INPUT	;GET OP ANSWER
	IFZ	INPBUF.,2$	;NO INPUT
	UCASE.	INPBUF.	 ;UPPER CASE
	MOVE.B	INPBUF.+1,D0
	CMP.B	#'Y',D0	 ;YES?
	BEQ.S	1$		;OKAY
	CMP.B	#'N',D0	 ;NO?
	BEQ.S	3$		;OKAY
2$:	DISP.	PAYN.		;PLEASE ANSWER YES OR NO
3$:	STC
1$:	RTS

DIRECTORY:
	SCAN.	INPBUF.,A.	;GET DRIVE, IF ANY
	IFZ	A.,1$		;ASSUME AD IF NO DRIVE
	CALL	GET_DRIVE	;CHECK IT OUT
	ERROR	1$		;NO DRIVE...ASSUME AD
	BNE	1$		;AMIGA DOS DISK
	CALL	BUILD_PATH	;CHECK OUT POSSIBLE PATH
	ACHAR.	#'\',M_FNAME.
	CALL	SEARCH_PATH	;SEE IF WE CAN FIND DIR
	ERROR	GETCMD		;BAD PATH
	CALL	LIST_DIR
	BRA	GETCMD

1$:	CALL	LIST_AD_DIR
	BRA	GETCMD

FMAT:
	CLR.B	DOUBLE_STEP
	CLR.B	ATARI_FLAG	;NOT ATARI
	MOVE.	INPBUF.,A.
	CALL	GET_DRIVE	;SPECIFIED A DRIVE?
	ERROR	1$		;NO
	BNE	BAD_ARGS	;CANT SPECIFY AMIGA-DOS DRIVE
	CLIP.	#4,INPBUF.	;GET RID OF MS-DOS DRIVE CODE
1$:	SCAN.	INPBUF.,A.	;GET PARAMS, IF ANY
	IFNZ	IS_3.5,5$	;3.5-INCH, USE DIFFERENT DECODING
	MOVE.B	#$FC,D6		;DISK TYPE
	IFZ	A.,3$		;NOTHING...ASSUME DSDD
	IFEQ.	A.,F1.,7$	;S9
	IFEQ.	A.,F8.,4$	;D8
	IFEQ.	A.,F18.,2$	;S8
	IFEQ.	A.,F81.,2$	;S8 WITH PARAMS REVERSED
	BRA	BAD_ARGS

4$:	INCB	D6
2$:	INCB	D6
3$:	INCB	D6
	BRA.S	7$
5$:	MOVE.B	#$F9,D6		;ASSUME IBM 720KB FORMAT
	IFZ	A.,7$		;NO PARAMS...IBM OK
	IFNE.	A.,F40.,6$	;not 5.25-in 80-track in 40-track mode
	MOVE.B	#$FD,D6		;assume DSDD mode
	SETF	DOUBLE_STEP
	BRA.S	7$
6$:	MOVE.B	D6,ATARI_FLAG
	MOVE.B	#$F7,D6		;ATARI FORMAT DISK
	IFEQ.	A.,ATARI2.,7$	;ASSUME DOBLE-SIDED ATARI
	MOVE.B	#$F8,ATARI_FLAG	;SINGLE-SIDED ATARI
	IFNE.	A.,ATARI1.,BAD_ARGS
7$:	MOVE.B	D6,DISK_TYPE	;SAVE CODE FOR FAT ENTRY
	MOVE.	FMSG1.,A.	;FORMAT MSG
	APPEND. MD_DRV.,A.	;APPEND MS-DOS DRIVE
	DISP.	A.
	DISP.	FMSG2.,NOCR	;PRESS RETURN TO START
	CALL	KBD_INPUT	;WAIT TO START
	IFNZ	INPBUF.,BAD_ARGS ;TYPED SOME TEXT...ABORT
	DISP.	FMSG3.
	CALL	FORMAT_DISK	;NOW DO IT
	BRA	GETCMD

CHGDIR:
	MOVE.	INPBUF.,A.
	CALL	GET_DRIVE	;WHICH DRIVE?
	ERROR	5$
	BNE	5$		;AMIGA-DOS
	CLIP.	#4,A.		;GET RID OF DRIVE CODE
	STRIP_LB. A.
	IFNZ	A.,1$
	DISP.	MD_PATH.
	BRA	GETCMD
1$:	MOVE.B	A.+1,D0	 ;CHECK FOR LEADING "\"
	CMP.B	#'\',D0	 ;IS IT?
	BEQ.S	2$		;YES...DONT TOUCH IT
	MOVE.	MD_PATH.,TMP.
	MOVE.B	MD_PATH.,D0
	CMP.B	#1,D0		;IS PATH ROOT ONLY '\'
	BEQ	3$		;YES...NO ADDED SLASH
	ACHAR.	#'\',TMP.
3$:	APPEND. A.,TMP.
	MOVE.	TMP.,A.	 ;NOW HAVE FULL PATH
2$:	MOVE.	A.,TMP_PATH.	;SAVE IN CASE IT WORKS
	ACHAR.	#'\',A.
	MOVE.	A.,M_FNAME.	;FOR PATH SCAN
	CALL	SEARCH_PATH	;TRY TO FIND IT
	ERROR	GETCMD
	MOVE.	TMP_PATH.,MD_PATH. ;MAKE SAVED PATH THE NEW PATH
	BRA	GETCMD
5$:	CALL	CHANGE_AD_DIR
	BRA	GETCMD

* BUILDS PATH, FINDS AND LOADS PROPER (SUB)DIR, ISOLATES FILENAME, CHECKS
* FILENAME AND TRIES TO FIND FILE IN (SUB)DIR.

FOLLOW_PATH:
	CALL	BUILD_PATH	;BUILD FULL PATH STRING
	CALL	SEARCH_PATH	;TRY TO FIND (SUB)DIRECTORY
	ERROR	9$
	MOVE.	M_FNAME.,A.	;USE REMAINDER AS FILE NAME
	CALL	CHECK_NAME	;CHECK OUT MS-DOS FILE NAME
	ERROR	9$
	CALL	FIND_FIRST	;TRY TO FIND IT
9$:	RTS

* CHECK OUT MS-DOS FILE NAME IN A.

CHECK_NAME:
	CALL	VALIDATE_NAME	;CHECK FOR ILLEGAL CHARS
	ERROR	9$		;TOO BAD...CANT TAKE IT
	CALL	EXPAND_MD_WILD	;EXPAND AND CONVERT TO WILD CARD FORM
	CLC
	RTS
9$:	DISP.	BAD_NAME.	;BAD FILE NAME
	STC
	RTS

* CHECKS FIRST 4 CHARS IN A. AS DRIVE CODE.	RETURNS CY=1 IF NOT VALID.
* RETURNS CY=0 IF VALID.	RETURNS Z=1 IF MS-DOS
* OR Z=0 IF AMIGA-DOS.	SETS AD_DRV. TO STRING.

GET_DRIVE:
	LEFT.	A.,#4,TMP.	;SCAN OFF POSSIBLE DRIVE CODE
	IFEQ.	TMP.,MD_DRV.,9$ ;MATCHES MS-DOS DRIVE CODE
	IFEQ.	TMP.,DF0.,1$	;DF0 MATCH
	IFEQ.	TMP.,DF1.,1$	;DF1 MATCH
	IFEQ.	TMP.,DF2.,1$	;DF2 MATCH
	IFEQ.	TMP.,DF3.,1$	;DF3 MATCH
	IFEQ.	TMP.,RAM.,1$	;RAM DISK
	IFEQ.	TMP.,DH0.,1$	;DH0
	IFEQ.	TMP.,DH1.,1$
	IFEQ.	TMP.,VD0.,1$
	IFEQ.	TMP.,JH0.,1$
	STC			;ERROR RETURN...NOT VALID DRIVE
	RTS
1$:	MOVE.	TMP.,AD_DRV.	;MAKE THIS THE CURRENT AD DRIVE
	MOVEQ	#1,D0		;CLEAR Z AND C
9$:	RTS			;WATCH IT! Z-BIT SET ON MS-DOS

* CHECKS FOR POSSIBLE PATH, AND PREFIXES CURRENT PATH, IF ANY '\' IN PATH.

BUILD_PATH:
	CLIP.	#4,A.		;STRIP OFF DRIVE CODE
BLD_PATH:			;DONT CLIP 4 IF ENTER HERE
	STRIP_LB. A.
	MOVE.	A.,M_FNAME.	;MAKE THIS THE FILE NAME
	MOVE.	A.,TMP_PATH.	;SAVE FOR DIR HEADER
	MOVE.B	#'\',D2
	LEA	A.,A0
	MOVE.B	(A0)+,D1	;GET LENGTH
	BEQ.S	3$		;NOTHING LEFT...BUILD A PATH
	CMP.B	(A0),D2	 ;LEADING BACKSLASH?
	BNE.S	3$		;NO, INSERT CURRENT PATH
	RTS
3$:	CLR.B	TMP.
	APPEND. MD_PATH.,TMP.
	MOVE.B	MD_PATH.,D0
	CMP.B	#1,D0		;ONLY 1 CHAR IN PATH (\)?
	BEQ	4$
	ACHAR.	D2,TMP.
4$:	APPEND. A.,TMP.
	MOVE.	TMP.,TMP_PATH.	;SAVE FOR DIR HEADER
	MOVE.	TMP.,M_FNAME.	;BUILD FULL PATH STRING
	RTS

* VALIDATES AMIGA-DOS NAME IN NAME. FOR POSSIBLE USE AS MS-DOS FILE NAME.
* REJECTS NAME IF IT HAS ILLEGAL CHARS OR IS TOO LONG.	ASKS OP FOR NEW
* NAME FOR FILE.

VALIDATE_AD_NAME:
	CALL	BACK_SCAN	;GET RID OF ANY AMIGA-DOS PATH GARBAGE
	MOVE.	NAME.,A.
	CALL	VALIDATE_NAME	;ANY BAD CHARS?
	ERROR	6$		;YES...GET ANOTHER
	CMP.B	#8,NAME.	;TOTAL 8 OR LESS?
	BLS.S	1$		;YES...ACCEPT IT
	CMP.B	#12,NAME.	;12 OR LESS?
	BHI.S	6$		;NO...DONT TAKE IT
	ZAP	D1
	LEA	NAME.,A0	;SCAN FOR '.'
	MOVE.B	(A0)+,D1	;MAX SIZE
	DECW	D1
	MOVE.B	#'.',D0
2$:	CMP.B	(A0)+,D0	;FIND '.'?
	BEQ	3$		;YES
	DBF	D1,2$		;NO...KEEP ON TRUCKIN'
	BRA.S	6$		;NEVER FOUND IT...CANT ACCEPT
3$:	CMP.B	#3,D1		;MORE THAN 3 CHARS AFTER '.'?
	BHI.S	6$		;YES...BAD FORMAT
1$:	RTS			;OKAY...WE CAN TAKE NAME
6$:	MOVE.	BAD_NAME.,TMP.
	ACHAR.	#':',TMP.
	ACHAR.	#32,TMP.
	APPEND. NAME.,TMP.
	DISP.	TMP.		;TELL OP ABOUT BAD NAME
7$:	PROMPT. NEW_NAME.	;AND ASK FOR ANOTHER
	CALL	KBD_INPUT	;GET REPLACEMENT
	IFZ	INPBUF.,7$
	STRIP_LB. INPBUF.	;CLEAN UP OPERATOR'S INPUT
	STRIP_TB. INPBUF.
	UCASE.	INPBUF.
	MOVE.	INPBUF.,NAME.
	BRA	VALIDATE_AD_NAME ;MAKE SURE NEW NAME IS OK

* SCANS NAME. FROM END LOOKING FOR '/', WHICH IS AD PATH INDICATOR.
* IF IT FINDS '/', MOVES UP WHATEVER REMAINS AS FILE NAME.
* NOTE:	THIS SUBR NOW APPEARS TO BE SUPERFLUOUS.

BACK_SCAN:
	ZAP	D1
	LEA	NAME.,A0
	MOVE.L	A0,A1		;FOR MOVING UP
	MOVE.B	(A0)+,D1	;LENGTH
	ADD.L	D1,A0		;POINT PAST LAST BYTE
	MOVE.B	#'/',D0
1$:	CMP.B	-(A0),D0	;GOT IT?
	BEQ.S	2$		;YES
	DBF	D1,1$		;ELSE LOOP
	RTS			;DONT CHANGE STRING...OKAY AS IS
2$:	INCL	A0		;POINT TO CHAR AFTER '/'
	ZAP	D0
	MOVE.B	NAME.,D0	;CALC NUMBER OF BYTES TO MOVE
	SUB.W	D1,D0		;NOTE D1 NOT INITIALLY DECREMENTED
	MOVE.B	D0,(A1)+	;STORE NEW LENGTH
3$:	CALL	MOVE_CHARS	;MOVE STRING UP IN BUFFER
	RTS

* CHECKS MS-DOS FILE NAME IN A. FOR LEGAL CHARS.  RETURNS CY=1 ON BAD NAME

VALIDATE_NAME:
	UCASE.	A.
	ZAP	D0
	MOVE.L	#A.,A0		;POINTER TO NAME TO CHECK
	MOVE.B	(A0)+,D0	;LENGTH TO CHECK
	BEQ.S	9$		;NOTHING TO CHECK
	DECW	D0		;ADJUST FOR DBF
1$:	LEA	CHAR_TBL,A1	;TABLE OF VALID CHARS
	MOVE.W	#CT_LEN-1,D1	;NUMBER OF BYTES TO CHECK-1
	MOVE.B	(A0)+,D2	;GET A BYTE TO VALIDATE
2$:	CMP.B	(A1)+,D2	;TABLE OF LEGAL CHARS
	BEQ.S	3$		;MATCH
	DBF	D1,2$		;ELSE LOOP
	STC			;OOPS...BAD CHAR IN NAME
	RTS
3$:	DBF	D0,1$		;OK...TRY NEXT CHAR IN STRING
9$:	CLC
	RTS

* SCANS INPBUF. LOOKING FOR -A AND -R OPTIONS, AND REMOVES THEM FROM THE
* BUFFER.

SCAN_OPTIONS:
	MOVE.	INPBUF.,TMP.	;WORK WITH TMP.
	LEA	TMP.,A0
	ZAP	D1
	MOVE.B	(A0)+,D1	;GET LENGTH
	BEQ	9$		;NOTHING TO DO
	DECW	D1
1$:	MOVE.B	(A0),D0	 ;GET A BYTE
	CMP.B	#32,D0		;BLANK?
	BNE	5$		;NO...KEEP IT
	CMPI.W	#2,D1		;ENOUGH ROOM LEFT FOR OPTION?
	BCS.S	5$		;NO...IGNORE IT
	CMPI.B	#'-',1(A0)	;NEXT CHAR A DASH?
	BNE	5$		;NO...IGNORE IT
	CMPI.B	#'A',2(A0)	;-A?
	BNE.S	2$		;NO
	SETF	ASCII_FLAG	;YES...FOUND ASCII OPTION
	BRA.S	3$		;NOW REMOVE IT
2$:	CMPI.B	#'R',2(A0)	;-R?
	BNE	5$		;NO
	SETF	REPLACE_FLAG	;YES...FOUND REPLACE OPTION
3$:	CLR.B	(A0)+		;ZAP THE 3 BYTES
	CLR.B	(A0)+
	CLR.B	(A0)		;LEAVE FINAL INC FOR BELOW
	SUBQ.W	#2,D1		;ACCOUNT FOR CHARS REMOVED
5$:	INCL	A0		;POINT TO NEXT CHAR
	DBF	D1,1$		;LOOP FOR ALL OF STRING
	LEA	TMP.,A0	 ;NOW COPY ALL BACK, EXCEPT FOR NULLS
	LEA	INPBUF.,A1
	CLR.B	(A1)+		;START WITH ZERO LENGTH
	ZAP	D1
	MOVE.B	(A0)+,D1	;GET LENGTH
	DECW	D1
6$:	MOVE.B	(A0)+,D0
	BEQ.S	7$		;NULL...DONT STORE IT
	MOVE.B	D0,(A1)+	;ELSE MOVE IT BACK TO INPBUF.
	INCB	INPBUF.
7$:	DBF	D1,6$		;LOOP FOR ALL OF ORIGINAL INPBUF.
9$:	RTS

* THIS SUBR PERFORMS THE SCAN. FUNCTION FOR AMIGA-DOS FILE NAMES, WHICH
* MAY HAVE EMBEDDED BLANKS IN THE FILE NAME (ENCLOSED IN QUOTES).
* STRIPS QUOTES, IF ANY, FROM AROUND AMIGA-DOS FILE NAME,
* AND STRIPS ** AND *", IF FOUND.  FILE NAME IN INPBUF.  RESULT TO A.

FIX_AD_NAME:
	CLR.B	QUOTE_FLAG	;NOT IN QUOTE
	STRIP_LB. INPBUF.	;MAKE SURE STRING IS CLEAN
	ZAP	D1
	LEA	INPBUF.,A0
	LEA	A.,A1		;RESULT GOES TO A.
	MOVE.B	D1,(A1)+	;ZAP A. LENGTH
	MOVE.B	(A0),D1	 ;GET INPBUF. LENGTH
	BEQ	19$		;NOTHING TO PROCESS
	CLR.B	(A0)+		;BUT ZAP IT FOR LATER
	DECW	D1
1$:	MOVE.B	(A0)+,D0
	CMP.B	#32,D0		;BLANK?
	BNE.S	4$		;NO
	IFNZ	QUOTE_FLAG,7$	;INSIDE QUOTED NAME...KEEP IT
	BRA	9$		;ELSE TREAT AS END OF FILENAME STRING
4$:	CMP.B	#'"',D0		;QUOTE?
	BNE.S	2$		;NO
	IFNZ	QUOTE_FLAG,9$	;END OF QUOTED NAME...ALL DONE
	SETF	QUOTE_FLAG	;ELSE WE NOW ARE IN QUOTED NAME
	BRA.S	8$		;DONT SAVE THE QUOTE
2$:	CMP.B	#'*',D0		;ASTERISK?
	BNE.S	7$		;NO...KEEP CHAR
	TST.W	D1		;ANY MORE TEXT?
	BEQ.S	7$		;NO...JUST KEEP IT
	CMPI.B	#'*',(A0)	;NEXT CHAR ALSO ASTERISK?
	BEQ.S	3$		;YES...KEEP ONLY 1
	CMPI.B	#'"',(A0)	;QUOTED QUOTE?
	BNE.S	7$		;NO...KEEP ASTERISK
3$:	DECW	D1
	CMP.W	#$FFFF,D1	;END OF STRING?
	BEQ.S	9$		;YES...OP ERROR
	MOVE.B	(A0)+,D0	;ELSE GET CHAR TO KEEP
7$:	MOVE.B	D0,(A1)+	;KEEP CHAR
	INCB	A.		;COUNT IT
8$:	DBF	D1,1$		;LOOP
	RTS			;ALL DONE...INPBUF. EMPTY
9$:	LEA	INPBUF.+1,A1	;A. NOW OK, FIX UP INPBUF.
	TST.W	D1
	BEQ.S	19$		;NOTHING LEFT ANYWAY
	DECW	D1
10$:	MOVE.B	(A0)+,(A1)+	;MOVE UP A BYTE
	INCB	INPBUF.
	DBF	D1,10$
19$:	RTS

* THESE ROUTINES CONTROL AMIGA-DOS ACCESS TO THE DS_DOS DISK DRIVE.
* CALLED AT INHIBIT TO STOP ACCESS, OR AT PERMIT TO ALLOW AGAIN.
* TO DRIVE NAME STRING IN MD_DRV.

PERMIT_ACCESS:
	MOVE.L	DEVICE_PTR,D0
	BEQ.S	9$
	MOVE.L	D0,A0
	MOVE.B	SAVED_BITS,$41(A0) ;RESTORE DRIVE SELECT BITS
9$:	RTS

* INHIBITS AMIGADOS ACCESS TO THE MS-DOS DISK DRIVE BY SAVING AND ZAPPING 
* THE ADOS DRIVER SELECT BITS, CAUSING DOS TO "FORGET" THE DRIVE.	
* PERMIT_ACCESS RESTORES THE SELECT BITS.

INHIBIT_ACCESS:
	CLR.L	DEVICE_PTR
	MOVE.L	4,A0
	LEA	DeviceList(A0),A0	;POINT TO LIST OF DEVICES
	MOVE.L	A0,DEVICE_PTR	;SEARCH TASK LIST
2$:	MOVE.L	DEVICE_PTR,A0
	MOVE.L	(A0),D0		;GET NEXT ENTRY
	MOVE.L	D0,DEVICE_PTR
	BEQ	8$		;END OF DEVICE LIST...DIDN'T FIND DISK?
	MOVE.L	D0,A0
	MOVE.L	10(A0),A1	;GET POINTER TO NAME
	CALL	CHECK_TD	;IS IT TRACK DISK?
	BNE.S	2$		;NO...KEEP ON GOING
	ZAP	D0
	MOVE.B	MD_DRV.+3,D0	;GET DRIVE NUMBER
	SUB.B	#'0',D0		;MAKE IT BINARY
	LSL.W	#2,D0		;MAKE IT INTO LONG INDEX
	MOVE.L	$24(A0,D0.W),DEVICE_PTR	;PICK UP POINTER TO DRIVER TASK DATA SEG
	BEQ.S	8$		;NOT DEFINED...DISK ISN'T KNOWN TO ADOS
	LEA	DOSSignature,A1	;POINT TO DOS IDENTIFIER
	CMP.L	#'MIGA',(A1)	;Check for V1.1 IDENT
	BNE.S	4$		;NOT V1.1
	SUB.L	#$1A,DEVICE_PTR	;ADJUST FOR V1.1
4$:	MOVE.L	DEVICE_PTR,A0
	DISABLE
	MOVE.B	$41(A0),D0	;GET MOTOR FLAG AND SELECT BITS
	BTST	#7,D0		;MOTOR OFF?
	BNE.S	5$		;YES...LETS GRAB THE DRIVE
	ENABLE
	MOVEQ	#25,D1		;ELSE WAIT A BIT
	MOVE.L	LIBRARY_BASE,A6
	CALLSYS	Delay		;WAIT FOR A BIT TO SEE IF DRIVE GETS FREE
	BRA.S	4$
5$:	MOVE.B	D0,SAVED_BITS	;SAVE SELECT CODE
	MOVE.W	#-1,$4C(A0)	;FORCE CURRENT TRACK TO BE UNKNOWN
	MOVE.B	#-1,$41(A0)	;AND FIX SELECT BITS
	ENABLE
8$:	RTS

* A1 POINTS TO NAME OF NODE.  THIS SUBR COMPARES TO 'trackdisk.device'.	
