	XREF	DR_BASE,D2D_TASK,MsdosHandle
	XREF	LIST_DIR,LIST_AD_DIR
	XREF	A.,TMP.,A_FNAME.,M_FNAME.,NAME.
	XREF	OPEN_FILE,NEW_FILE,READ_CLUSTER,WRITE_CLUSTER,CLOSE_FILE
	XREF	EXPAND_MD_WILD,FIND_FIRST,FIND_NEXT
	XREF	FIND_FIRST_AD,FIND_NEXT_AD
	XREF	OPEN_AD_FILE,CREATE_AD_FILE,CLOSE_AD_FILE
	XREF	READ_AD_FILE,WRITE_AD_FILE
	XREF	ERR_CODE,BytCnt,FILEHANDLE,DISK_TYPE,DRIVE_SEL
	XREF	KBD_INPUT,FORMAT_DISK,GET_CHAR,MOTOR_OFF
	XREF	CHANGE_AD_DIR,SEARCH_PATH,MOVE_CHARS
	XREF	DELETE_FILE,DELETE_AD_FILE
	XREF	STRIP_CR,ADD_CR
	XREF	WILD_FLAG,LOCK,DirPtr
	XREF	MSG_PORT,DOUBLE_STEP,OriginalDir
	XREF	TryMountlist,ScanColon
	XREF	UpdateDateTime
	XREF	AllocFixedBufs,FreeAllBufs
	XREF	CHECK_DRIVE_TYPE
	XREF	OpenFlop,CloseFlop
	XREF	OpenDev,CloseDev
	XREF	AMXlate,MAXlate

	XREF	D2Dver.
	XREF	CCS.
	XREF	EVAL.
	XREF	DMO1.
	XREF	DMO2.
	XREF	DMO3.
	XREF	DMO4.
	XREF	DMO5.
	XREF	DMO6.

	XREF	QuesTxt
	XREF	HLPTEXT
	XREF	HLPTEXTLEN
	XREF	QuesTxtLen

	XREF	CHIP_MEM.
	XREF	BAD_ARGS.
	XREF	DUP_DRV.
	XREF	DUP_FILE.
	XREF	DUP1.
	XREF	DUP2.
	XREF	NO_FILE.
	XREF	BAD_NAME.
	XREF	DRV_ERR.
	XREF	DEV_ERR.
	XREF	OPEN_ERR.
	XREF	BAD_CMD.
	XREF	NEW_NAME.
	XREF	PAYN.
	XREF	HOW_TO.
;;	XREF	USERAM1.
;;	XREF	USERAM2.
