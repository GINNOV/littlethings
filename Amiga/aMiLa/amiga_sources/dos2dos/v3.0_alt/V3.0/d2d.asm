* Clip drive code from string in A0.  Strips up to colon.

ClipColon:
	ZAP	D1
	MOVE.L	A0,A1			;save ptr to strart of string
	MOVE.B	(A0)+,D1		;GET ORIGINAL LENGTH
	BEQ.S	9$			;nothing in original string...
	CLR.B	(A1)			;nothing in string now...
	DECW	D1			;for DBF
1$:	MOVE.B	(A0)+,D0
	CMPI.B	#':',D0
	BEQ.S	2$			;found colon
	DBF	D1,1$
	BRA.S	9$			;oops...no colon in string
2$:	MOVE.B	D1,(A1)+		;store new length
	BEQ.S	9$			;nothing after colon
	DECW	D1			;account for colon
4$:	MOVE.B	(A0)+,(A1)+		;move up the remainder
	DBF	D1,4$
9$:	RTS

