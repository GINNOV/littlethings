	CALLSYS	CurrentDir,DosBase
1$:	IFZL	WBenchMsg,EXIT_TO_DOS	;no window to close
	MOVE.L	STDOUT,D1		;close the window
	BEQ.S	EXIT_TO_DOS
	CALLSYS	Close,DosBase

