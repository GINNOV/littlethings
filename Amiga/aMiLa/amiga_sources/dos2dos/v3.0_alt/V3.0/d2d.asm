	XREF	PMORE.
	XREF	EOF.
	XREF	WHICH_DRIVE.
	XREF	NO_DRV1.
	XREF	NO_DRV2.
	XREF	FMSG1.
	XREF	FMSG2.
	XREF	FormFail.
	XREF	FormComp.
	XREF	CPYING.
	XREF	BREAK.
	XREF	Deleting.
	XREF	YES.,NO.

	XREF	DirectoryBuf,FATBuf,ClusterBuf

	XDEF	INPBUFF,INPBUF.,GETCMD
	XDEF	STDIN,STDOUT,_SysBase,SysBase,DosBase,GraphicsBase
	XDEF	MD_DRV.,MD_PATH.,AD_DRV.,TMP_PATH.,IS_3.5,ATARI_FLAG
	XDEF	NotFlop,LC_FLAG,WSFlg

INPBUF_SIZE	EQU	80	;80-CHAR TEXT BUFFER
TaskPort	EQU	$5C	;offset to task's port
LINSIZ		EQU	100	;max size of test during type

GO:
	MOVE.L	A7,initialSP		;initial task stack pointer
	CLR.B	BatchFlg
	MOVE.L	A0,A2			;save CLI params, if any
	MOVE.L	D0,D2
	MOVE.L	4,A6	
	MOVE.L	A6,SysBase
	LEA	DosName,A1
	ZAP	D0
	CALLSYS	OpenLibrary		;OPEN DOS LIBRARY
	MOVE.L  D0,DosBase
	ZAPA	A1
	CALLSYS	FindTask
	MOVE.L	D0,D2D_TASK		;save ptr for msg ports
	MOVEA.L D0,A4
	TST.L   $AC(A4)			;invoked from cli?
	BEQ.S	FROM_WB			;no...from WB
	DECW	D2			;don't count line terminator
	BEQ.S	COMMON			;no params
	LEA	LINBUF,A0
	MOVEQ	#LINSIZ-1,D0
	CMP.W	D0,D2
	BLE.S	2$
	MOVE.W	D0,D2
2$:	MOVE.B	D2,(A0)+		;length
	DECW	D2
1$:	MOVE.B	(A2)+,(A0)+		;move a byte
	DBF	D2,1$
	STRIP_LB. LINBUF
	SCAN.	LINBUF,INPBUF.		;get drive param or '?'
	SETF	BatchFlg		;show this is batch run
	BRA.S	COMMON
FROM_WB:
	LEA     TaskPort(A4),A0
	CALLSYS	WaitPort
	LEA     TaskPort(A4),A0
	CALLSYS	GetMsg
	MOVE.L	D0,WBenchMsg		;save WBench msg for reply
	MOVE.L	D0,A2
	MOVE.L	28(A2),D0		;NUMBER OF PARAMS
	MOVE.L	36(A2),A2		;PTR TO PARAM LIST
2$:	MOVE.L	(A2),D1			;GET BPTR TO LOCK
	IFZL	DosBase,COMMON		;ADOS version error, from WB
	CALLSYS	CurrentDir,DosBase
COMMON:
	ZAP	D0
	MOVE.L	D0,DirectoryBuf
	MOVE.L	D0,FATBuf
	MOVE.L	D0,ClusterBuf
	JSR	AllocFixedBufs
	ERROR	NO_MEM			;CANT GET CHIP MEMORY
	IFZL	DosBase,EXIT_TO_DOS

	LEA	GraphicsName,A1
	ZAP	D0
	CALLSYS	OpenLibrary,SysBase
	MOVE.L	D0,GraphicsBase
	BEQ	ABORT
	LEA	IntuitionName,A1
	ZAP	D0
	CALLSYS	OpenLibrary
	MOVE.L	D0,IntuitionBase
	BEQ	ABORT
	IFZL	WBenchMsg,1$		;from CLI
	BSR	GetWindowSize
	ERROR	ABORT
	MOVE.L	#TMP.,D1
	MOVE.L	#NEW,D2
	CALLSYS	Open,DosBase
	MOVE.L	D0,STDIN
	MOVE.L	D0,STDOUT
	BEQ	ABORT
	BRA.S	2$
1$:	CALLSYS	Input,DosBase
	MOVE.L	D0,STDIN
	CALLSYS	Output
	MOVE.L	D0,STDOUT
	BEQ	ABORT
	IFZ	BatchFlg,2$
	IFNE.	QUES.,INPBUF.,2$	;Not '?'
	WRITEFILE STDOUT,#QuesTxt,#QuesTxtLen
	BRA	EXIT
2$:	CLR.B	MD_DRV.		;IN CASE OF GARBAGE
	IFNZ	BatchFlg,AGAIN
	CRLF.
	MOVE.	D2Dver.,TMP.
	APPEND.	CCS.,TMP.
	DISP.	TMP.

	IFEQ	DEMO-2		;IF AN EVAL, SAY SO
	CRLF.
	DISP.	EVAL.
	ENDC

	IFEQ	DEMO-1		;IF A DEMO, SAY SO
	BSR	Dispdemo
	ENDC


AGAIN:
	MOVE.B	#1,MD_PATH.
	MOVE.B	#'\',MD_PATH.+1		;SET UP DEFAULT INITIAL PATH
ASKDEV:	CLR.B	NotFlop
	CLR.L	MsdosHandle		;filehandle for MS-DOS file volume
	IFNZ	BatchFlg,2$
	CRLF.
	PROMPT. WHICH_DRIVE.		;ASK WHICH DRIVE FOR MS_DOS
	JSR	KBD_INPUT		;GET REPLY
2$:	STRIP_LB. INPBUF.		;CLEAN UP REPLY
	UCASE.	INPBUF.
	IFZ	INPBUF.,EXIT		;NO INPUT, JUST EXIT
	RIGHT.	INPBUF.,#1,TMP. 	;CHECK FOR TRAILING COLON
	MOVE.B	TMP.+1,D0		;GET CHAR
	CMP.B	#':',D0			;IS IT?
	BEQ.S	1$			;YES...got a drive code
	JSR	ScanColon		;try to open MSDOS file
	IFNZL	MsdosHandle,GOTDEV	;MSDOS file on AmigaDOS device
	ACHAR.	#':',INPBUF.		;else add colon and try as 
1$:	MOVE.B	#$77,D0
	IFEQ.	DF0.,INPBUF.,FLOP	;DRIVE 0
	MOVE.B	#$6F,D0
	IFEQ.	DF1.,INPBUF.,FLOP	;DRIVE 1
	MOVE.B	#$5F,D0
	IFEQ.	DF2.,INPBUF.,FLOP	;DRIVE 2
	MOVE.B	#$3F,D0
	IFEQ.	DF3.,INPBUF.,FLOP	;DRIVE 3
	JSR	TryMountlist		;not flop, check mountlist
	ERROR	BADDEV			;not in mountlist...wcant use it
	MOVE.	INPBUF.,MD_DRV.
	SETF	NotFlop			;device is not floppy disk
	JSR	OpenDev			;open the device
	NOERROR	GOTDEV

BADDEV:	DISP.	DEV_ERR.		;tell op we cant figure out device
	BRA	ASKDEV

FLOP:	MOVE.B	D0,DRIVE_SEL		;STORE DRIVE SELECT CODE
	MOVE.	INPBUF.,MD_DRV. 	;NOW HAVE PROPER DRIVE CODE
	JSR	CHECK_DRIVE_TYPE	;NOW SEE IF DRIVE EXISTS ON THIS CONFIG
	NOERROR 1$			;OK
	CRLF.
	MOVE.	NO_DRV1.,TMP.		;CANT FIND IT...MUST BE NON-AMIGA 5.25"
	APPEND.	MD_DRV.,TMP.
	ACHAR.	#'.',TMP.
	DISP.	TMP.
	DISP.	NO_DRV2.		;WARN THE OPERATOR
1$:	JSR	OpenFlop		;INIT SOME PARAMS + ALLOC CHIP MEM
	ERROR	ASKDEV
;;	IFNE.	MD_DRV.,DF0.,GOTDEV 	;NOT USING DF0
;;	IFNZ	BatchFlg,GOTDEV
;;	CRLF.
;;	DISP.	USERAM1.		;WARNING TO USE RAM:
;;	DISP.	USERAM2.
GOTDEV:	IFZ	BatchFlg,1$
	MOVE.	LINBUF,INPBUF.
	BRA.S	ProcessCmd
1$:	CRLF.
	DISP.	HOW_TO.

GETCMD:
	JSR	MOTOR_OFF		;TURN MS-DOS DRIVE MOTOR OFF
	IFNZ	BatchFlg,EXIT,L
	CRLF.
	PROMPT. D2D.			;ISSUE COMMAND PROMPT
	JSR	KBD_INPUT		;GET OPERATOR INPUT INTO INPBUF.

* DECODE THE COMMAND IN THE BUFFER

ProcessCmd:
	UCASE.	INPBUF.			;WORK IN UPPER CASE ONLY
	SCAN.	INPBUF.,A.		;GET COMMAND TOKEN
	STRIP_LB. A.			;ALLOW LEADING BLANKS
	STRIP_LB. INPBUF.		;FIX UP REST OF COMMAND, IF ANY
	LEFT.	A.,#3,TMP.		;USE UP TO 3 CHARS
	IFEQ.	TMP.,COPY.,CPYFIL
	IFEQ.	TMP.,TYPE.,TYPFIL
	IFEQ.	TMP.,DIR.,DIRECTORY
	IFEQ.	TMP.,FORMAT.,FMAT
	IFEQ.	TMP.,ChgD.,CHGDIR
	IFEQ.	TMP.,CHG.,CHGDIR
	IFEQ.	TMP.,QUES.,HELP
	IFEQ.	TMP.,HELP.,HELP
	IFEQ.	TMP.,H.,HELP
	IFEQ.	TMP.,EXIT.,EXIT
	IFEQ.	TMP.,X.,EXIT
	IFEQ.	TMP.,DELETE.,DELFIL
	IFEQ.	TMP.,RSTART.,RESTART
	DISP.	BAD_CMD.
	BRA	GETCMD

HELP:	WRITEFILE STDOUT,#HLPTEXT,#HLPTEXTLEN
	BRA	GETCMD

TYPFIL:
	CLR.B	MS_FLAG			;Not from MS-DOS
	MOVE.	INPBUF.,A.		;GET_DRIVE WORKS WITH A.
	IFZ	A.,BAD_ARGS		;NEED DRIVE AND FILE
	JSR	GET_DRIVE		;NEXT 4 CHARS MUST BE DRIVE CODE
	BEQ	1$			;MS-DOS DRIVE CODE
	JSR	FIX_AD_NAME		;SCAN AD FILENAME INTO A.
	MOVE.	A.,A_FNAME.
	JSR	OPEN_AD_FILE		;TRY TO FIND THE FILE
	ERROR	NO_FILE	 		;CANT FIND IT
	BRA.S	2$

* COME HERE TO TYPE AN MS-DOS FILE.

1$:	SETF	MS_FLAG
	BSR	FOLLOW_PATH		;BUILD AND SEARCH PATH, FIND FILE
	ERROR	NO_FILE			;DIDN'T FIND IT
	JSR	CHECK_SUBDIR		;SPECIFIED A SUBDIR?
	ERROR	NO_FILE			;YEAH, THE TURKEY
	CALL	OPEN_FILE		;OPEN IT AND GET READY TO READ

* Type text from file 1 line at a time

2$:	CLR.W	BytCnt		;START WITH EMPTY BUFFER
	CLR.B	LINCNT
3$:	CMP.B	#21,LINCNT	;DISPLAYED ENOUGH?
	BLS.S	4$		;NO...
	BSR	WAIT_MORE	;ELSE WARN AND WAIT
	ERROR	7$		;OP WANTS TO BAIL OUT
4$:	BSR	READ_LINE	;FILL LINE BUFFER
	ERROR	6$		;EOF
	BSR	WRITE_LINE	;WRITE LINE BUFFER TO SCREEN
	BRA.S	3$		;LOOP
6$:	BSR	WAIT_EOF	;END OF FILE
7$:	CALL	CLOSE_AD_FILE	;THATS ALL
	BRA	GETCMD

READ_LINE:
	LEA	LINBUF,A1
	MOVE.L	A1,LINPTR
	MOVE.B	#LINSIZ,LBCNT	;MAX SIZE OF 1 LINE IN CHARS
5$:	IFZ	MS_FLAG,1$	;1=FROM MS-DOS, 0=FROM AMIGA
	JSR	GET_CHAR	;GET NEXT MS-DOS CHAR
	ERROR	8$
	AND.W	#$FF,D0
	LEA	MAXlate,A0
	MOVE.B	0(A0,D0.W),D0
	BEQ.S	5$
	BRA.S	2$
1$:	BSR	GET_AD_CHAR	;ELSE GET NEXT ADOS CHAR
	ERROR	9$		;READ ERROR...ABORT
;	AND.W	#$FF,D0
;	LEA	AMXlate,A0
;	MOVE.B	0(A0,D0.W),D0
;	BEQ.S	1$
2$:	CMP.B	#32,D0		;IN ASCII RANGE?
	BCC.S	4$		;YES
	CMP.B	#10,D0		;NO...LF?
	BEQ.S	4$		;YES...KEEP IT
	CMP.B	#9,D0		;TAB?
	BNE.S	5$		;NO...IGNORE CHAR
	MOVE.B	#32,D0
4$:	MOVE.L	LINPTR,A1
	MOVE.B	D0,(A1)+	;INTO BUFFER
	MOVE.L	A1,LINPTR
	CMP.B	#10,D0		;IS IT END OF LINE?
	BEQ.S	8$		;YES...STOP HERE
	DECB	LBCNT
	BNE.S	5$
8$:	MOVE.L	LINPTR,D0	;CALC BYTES IN LINBUF
	SUB.L	#LINBUF,D0	;LEAVE IN D0
	BNE.S	9$
	STC
9$:	RTS

GET_AD_CHAR:
	MOVE.L	FILEHANDLE,D1
	MOVE.L	#INPBUF.,D2
	MOVEQ	#1,D3
	CALLSYS	Read,DosBase
	TST.L	D0
	BEQ.S	8$
	MOVE.B	INPBUF.,D0
	RTS
8$:	STC
	RTS

WRITE_LINE:
	MOVE.L	STDOUT,D1
	MOVE.L	#LINBUF,D2
	MOVE.L	D0,D3
	CALLSYS	Write,DosBase
	INCB	LINCNT
	RTS

WAIT_EOF:
	LEA	EOF.,A0		;EOF MSG
	BSR.S	PRINT_WIN
	BRA.S	WAIT_COM

WAIT_MORE:
	LEA	PMORE.,A0	;PRESS SPACE FOR MORE
	BSR.S	PRINT_WIN
	CLR.B	LINCNT
;	IFZ	MS_FLAG,WAIT_COM
;	JSR	MOTOR_OFF	;else turn off motor

WAIT_COM:
	READFILE STDOUT,#INPBUFF,#10
	LEA	CLEAN.,A0
	BSR.S	PRINT_WIN
	CMP.B	#27,INPBUFF	;ESCAPE?
	BNE.S	9$		;NO...'MORE'
	STC			;EOF
	RTS
9$:	CLC
	RTS

* WRITES TEXT STRING WITH LEADING COUNT IN A0 TO SPECIAL WINDOW.

PRINT_WIN:
	ZAP	D3
	MOVE.B	(A0)+,D3	;GET MSG LEN
	MOVE.L	A0,D2		;PTR TO STRING
	MOVE.L	STDOUT,D1
	CALLSYS	Write,DosBase
	RTS

* DELETE FILE FROM DISK

DELFIL:
	CLR.B	WILD_FLAG
	MOVE.	INPBUF.,A.		;GET_DRIVE WORKS WITH A.
	IFZ	A.,BAD_ARGS		;NEED DRIVE AND FILE
	BSR	GET_DRIVE		;NEXT 4 CHARS MUST BE DRIVE CODE
	BEQ	3$			;MS-DOS DRIVE CODE
	CALL	FIX_AD_NAME		;SCAN AD FILENAME INTO A.
	MOVE.	A.,A_FNAME.		;THIS IS THE FILE NAME
	JSR	FIND_FIRST_AD		;TRY TO FIND AND OPEN THE FILE
	ERROR	NO_FILE			;CANT FIND IT
1$:;	MOVE.	NAME.,A_FNAME.
	JSR	CLOSE_AD_FILE
	PROMPT.	Deleting.
	DISP.	NAME.
	JSR	DELETE_AD_FILE
2$:	IFZ	WILD_FLAG,GETCMD	;UNLOCK
	JSR	FIND_NEXT_AD		;TRY FOR ANOTHER FILE
	ERROR	GETCMD
	BRA.S	1$

* COME HERE TO DELETE AN MS-DOS FILE.

3$:	BSR	FOLLOW_PATH		;BUILD AND SEARCH PATH, FIND FILE
	ERROR	NO_FILE	 		;DIDN'T FIND IT
4$:	CALL	CHECK_SUBDIR		;SUBDIRECTORY?
	ERROR	5$			;yes...ignore it
	JSR	OPEN_FILE		;OPEN IT AND GET READY TO READ
	PROMPT.	Deleting.
	DISP.	NAME.
	JSR	DELETE_FILE
5$:	IFZ	WILD_FLAG,GETCMD
	JSR	FIND_NEXT		;TRY FOR ANOTHER FILE
	NOERROR	4$
	BRA	GETCMD

* COPIES A FILE FROM ONE FORMAT TO THE OTHER.

	IFNE	DEMO-1

CPYFIL:
	MOVEQ	#0,D0
	MOVE.B	D0,ASCII_FLAG
	MOVE.B	D0,REPLACE_FLAG
	MOVE.B	D0,WILD_FLAG
	MOVE.B	D0,LC_FLAG
	MOVE.B	D0,WSFlg
	CALL	SCAN_OPTIONS		;FIND AND REMOVE OPTIONS

* FIRST CHECK OUT SOURCE DRIVE, FILE, ETC.

	IFZ	INPBUF.,BAD_ARGS	;COPY COMMAND FORMAT ERROR
	MOVE.	INPBUF.,TMP.		;LEAVE INPBUF. INTACT FOR A-TO-M
	SCAN.	TMP.,A.
	BSR	GET_DRIVE		;TRY TO EXTRACT SOURCE DRIVE
	ERROR	CPY_A_M	 		;NO DRIVE...ASSUME AMIGADOS TO MS-DOS
	BNE	CPY_A_M	 		;AMIGA DOS DRIVE CODE--AMIGADOS TO MS-DOS

* COPY FROM MS-DOS TO AMIGA-DOS

	SCAN.	INPBUF.,A.		;M-TO-A, GET SOURCE STRING
	BSR	FOLLOW_PATH		;BUILD AND SEARCH PATH, FIND FILE
21$:	ERROR	NO_FILE	 		;CANT FIND FILE
	CALL	CHECK_SUBDIR		;SUBDIRECTORY?
	NOERROR 22$			;NO
	CALL	FIND_NEXT		;ELSE TRY FOR NEXT FILE
	BRA.S	21$
22$:	CALL	OPEN_FILE		;NOW TRY TO OPEN IT

*	NOW CHECK OUT DESTINATION DRIVE, FILE, ETC.

2$:	CALL	FIX_AD_NAME		;CHECK FOR AD QUOTED FILENAME, MOVE TO A.
	CLR.B	AD_PREFIX.		;START WITH NO PREFIX
	IFZ	A.,3$			;NO DEST SPECIFIED...USE DEFAULTS
	MOVE.	A.,AD_PREFIX.		;DRIVE AND POSSIBLE DIRECTORY
	BSR	GET_DRIVE		;SEE IF WE GOT A DRIVE CODE
	ERROR	4$			;NO DRIVE...ASSUME A. HAS IT ALL
	BEQ	DUP_DRV	 		;OOPS...CANT SPECIFY MS-DOS DRIVE AGAIN
	RIGHT.	A.,#1,TMP.		;GET LAST CHAR
	MOVE.B	TMP.+1,D0
	CMP.B	#':',D0			;DRIVE ONLY?
	BEQ.S	3$			;YES...NEED FILE NAME
	CMP.B	#'/',D0			;DRIVE AND DIRECTORY?
	BEQ.S	3$			;YES
4$:	IFZ	WILD_FLAG,5$		;NO WILD CARDS...DONT USE SOURCE NAME
3$:	MOVE.	AD_PREFIX.,A.		;ELSE USE PREFIX TO BUILD FULL NAME
	IFZ	A.,1$			;DONT PUT '/' ON EMPTY PREFIX
	RIGHT.	A.,#1,TMP.		;GET TRAILING CHAR
	MOVE.B	TMP.+1,D0		;CHECK IT OUT
	CMP.B	#':',D0
	BEQ.S	1$			;DONT NEED (OR WANT) SLASH AFTER COLON
	CMP.B	#'/',D0
	BEQ.S	1$			;OR TWO SLASHES, FOR THAT MATTER
	ACHAR.	#'/',A.
1$:	APPEND. NAME.,A.		;ADD NAME FROM MS-DOS FILE
5$:	MOVE.	A.,A_FNAME.		;THIS IS FINAL NAME TO USE
	CALL	OPEN_AD_FILE		;DOES IT ALREADY EXIST?
	ERROR	20$			;NO
	MOVE.	A_FNAME.,TMP.
	CALL	DUP_QUERY		;YES...ASK WHAT TO DO
	ERROR	7$			;OP SAYS BAIL OUT
	JSR	CLOSE_AD_FILE		;ELSE, UNLOCK IT
20$:	CALL	CREATE_AD_FILE		;OPEN NEW AMIGADOS FILE
	ERROR	OPEN_ERR		;OOPS...SOMETHING IS WRONG
	IFZ	WILD_FLAG,6$		;NO WILD CARD OP
	PROMPT. CPYING.
	DISP.	NAME.
6$:	JSR	READ_CLUSTER		;HERE WE GO...READ SOMETHING IN
	ERROR	10$			;ERROR READING DISK
	TST.W	BytCnt			;GOT ANYTHING?
	BEQ.S	7$			;NO...TREAT AS EOF
	IFZ	ASCII_FLAG,8$		;NO CONVERSION
	JSR	STRIP_CR		;ELSE GET RID OF CR'S
8$:	JSR	WRITE_AD_FILE		;WRITE IT OUT TO AMIGA FILE
	ERROR	10$			;WRITE FAILURE
	BRA.S	6$			;LOOP FOR ALL OF FILE
7$:	JSR	CLOSE_AD_FILE		;THATS ALL FOLKS!
	JSR	UpdateDateTime		;fix date/time stamp on ADos file
9$:	IFZ	WILD_FLAG,GETCMD
	JSR	FIND_NEXT		;TRY FOR ANOTHER FILE
	ERROR	GETCMD			;NONE
	CALL	CHECK_SUBDIR		;IS IT A SUBDIR?
	ERROR	9$			;IT IS...DONT COPY IT
	JSR	OPEN_FILE
	BRA	3$
10$:	JSR	CLOSE_AD_FILE
	BRA	GETCMD

* COPY FROM AMIGA-DOS TO MS-DOS

CPY_A_M:
	CALL	FIX_AD_NAME	;CHECK FOR AD QUOTED NAME, MOVE TO A.
	MOVE.	A.,A_FNAME.	;THIS IS THE FILE NAME
	CALL	FIND_FIRST_AD	;TRY TO FIND AND OPEN THE FILE
	ERROR	NO_FILE		;CANT FIND IT
	CLR.B	MD_PREFIX.	;START WITH NO PREFIX
	SCAN.	INPBUF.,A.	;GET DEST STRING
	IFZ	A.,10$		;NO STRING...USE EXISTING PATH + DEFAULTS
	BSR	GET_DRIVE	;CHECK FOR MS-DOS DRIVE
	ERROR	5$		;MISSING DEST DRIVE CODE
	BNE	5$		;TOO BAD...DIDN'T GIVE US A DRIVE
	LEA	A.,A0
	BSR	ClipColon	;Get rid of drive code
;	CLIP.	#4,A.		;GET RID OF DRIVE CODE
	IFZ	A.,10$		;NOTHING LEFT...USE FULL PATH AND DEFAULT
	CMP.B	#'\',A.+1	;LEADING '\'?
	BEQ.S	4$		;YES...DONT USE CURRENT PATH
10$:	MOVE.	MD_PATH.,TMP.	;NO...SET UP FULL PATH STRING
	CMP.B	#1,MD_PATH.	;SINGLE SLASH?
	BNE.S	11$		;NO
	CMP.B	#'\',MD_PATH.+1
	BEQ.S	4$		;YES...DONT ADD ANOTHER
11$:	ACHAR.	#'\',TMP.
	APPEND. A.,TMP.
	MOVE.	TMP.,A.
4$:	RIGHT.	A.,#1,TMP.	;SEE IF STRING ENDS IN '\'
	CMP.B	#'\',TMP.+1	;DOES IT?
	BNE.S	12$		;NO...OP GAVE US FULL STRING...USE IT
	MOVE.	A.,MD_PREFIX.	;ELSE MAKE THIS THE ENTIRE PREFIX
9$:;	CALL	OPEN_AD_FILE
;	ERROR	26$		;bad open
	CALL	VALIDATE_AD_NAME ;VERIFY VALID NAME OR GET ANOTHER
	MOVE.	MD_PREFIX.,A.
	APPEND. NAME.,A.	;DEFAULT TO AMIGA-DOS FILE NAME
12$:	MOVE.	A.,M_FNAME.
