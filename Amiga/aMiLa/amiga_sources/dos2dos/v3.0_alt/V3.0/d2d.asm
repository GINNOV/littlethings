	MOVE.L	initialSP,A7
	JSR	FreeAllBufs		;release mem buffers
	MOVE.L	SysBase,A6
	MOVE.L	DosBase,D0
	BEQ.S	1$
	MOVE.L	D0,A1
	CALLSYS	CloseLibrary
1$:	MOVE.L	GraphicsBase,D0
	BEQ.S	2$
	MOVE.L	D0,A1
	CALLSYS	CloseLibrary
2$:	MOVE.L	IntuitionBase,D0
	BEQ.S	3$
	MOVE.L	D0,A1
	CALLSYS	CloseLibrary
3$:	TST.L	WBenchMsg
	BEQ.S	4$
	CALLSYS	Forbid
	MOVEA.L	WBenchMsg,A1
	CALLSYS	ReplyMsg
4$:	CLR.L	D0
	RTS			;BACK TO AMIGA-DOS

