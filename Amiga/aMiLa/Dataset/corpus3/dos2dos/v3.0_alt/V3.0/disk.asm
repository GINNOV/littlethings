* HARDWARE REGISTER DEFINITIONS

DSKPTR	EQU	$DFF020
DSKLEN	EQU	$DFF024
FLAG	EQU	$BFDD00
CIAA	EQU	$BFE001
CIAB	EQU	$BFD100
INTENAR EQU	$DFF01C
INTENA	EQU	$DFF09A
INTREQ	EQU	$DFF09C
INTREQR EQU	$DFF01E
ADKCON	EQU	$DFF09E
ADKCONR EQU	$DFF010
DMACONR EQU	$DFF002
VHPOSR	EQU	$DFF006

TRKSIZ	EQU	12500		;SIZE OF TRACK BUFFER IN BYTES
SECSIZ	EQU	1100		;SIZE OF SECOR BUFFER
CRCCSIZ EQU	512		;SIZE OF CRCC TABLE
TR_ADDREQUEST	EQU	9	;timer io request

* READS D1 CONSECUTIVE LOGICAL SECTORS INTO BUFFER A0, STARTING WITH
* SECTOR IN D0.

READ_N:
	DECW	D1		;FOR DBF
1$:	PUSH	D0-D1/A0
	BSR	READ_SECTOR	;READ A SECTOR
	POP	D0-D1/A0
	ERROR	2$		;DISK ERROR
	ADDA.L	#512,A0		;BUMP BUFFER TO NEXT
	INCW	D0		;NEXT SECTOR
	DBF	D1,1$		;LOOP FOR ALL REQUESTED SECTORS
	CLC
2$:	RTS

* READ LOGICAL SECTOR.  LOGICAL SECTOR IN D0 (0 ORIGIN), BUFFER IN A0.

READ_SECTOR:
	AND.L	#$FFFF,D0
	IFZ	NotFlop,20$	
	JMP	DREAD_SECTOR
20$:	MOVE.B	#5,RETRY_COUNT
	MOVE.L	A0,DMAADR	;SAVE BUFFER ADDRESS
	BSR	CONVERT_SECTOR	;CALCULATE PHYSICAL TRACK, SIDE, SECTOR
	IFNZ	BUF_EMPTY,7$	;NOTHING IN TRACK BUFFER...FORCE READ
	MOVE.B	NEW_TRACK,D0
	CMP.B	CUR_TRACK,D0	;SAME TRACK AS CURREMT?
	BNE	1$		;NO...MUST SEEK
	MOVE.B	NEW_SIDE,D0
	CMP.B	CUR_SIDE,D0	;SAME AS CURRENT SIDE?
	BEQ	2$		;YES...JUST LOOK FOR SECTOR IN TRACK BUFFER
1$:	BSR	FLUSH_TRACK	;WRITE OUT CURRENT TRACK, IF NECESSARY
	ERROR	10$
7$:	BSR	SELECT_DRIVE	;GET DRIVE READY
	ERROR	5$
	BSR	SEEK		;STEP HEADS, IF NECESSARY
	ERROR	5$
	MOVEQ	#0,D0		;READ MODE
	BSR	DISK_GO		;READ THE TRACK
	ERROR	5$		;SOMETHING IS WRONG WITH DISK
2$:	LEA	SECTOR_TABLE,A3 ;WORK THE TABLE OF SECTORS
4$:	MOVE.W	0(A3),D0	;CHECK FOR VALID ENTRY HERE
	BEQ	5$		;BAD ENTRY...TABLE INVALID
	BMI	6$		;UNINITIALIZED SECTOR...GET SECTOR INFO
	MOVE.B	2(A3),D0	;CHECK FOR PROPER TRACK
	CMP.B	NEW_TRACK,D0
	BNE.S	8$
	MOVE.B	4(A3),D0	;GET SECTOR NUMBER
	CMP.B	NEW_SECTOR,D0	;SAME?
	BEQ	3$		;YES...DECODE IT AND WE'RE DONE
8$:	ADDA.L	#14,A3		;BUMP TO NEXT SECTOR IN LIST
	LEA	SECTBL_END,A4
	CMP.L	A3,A4		;MAKE SURE WE DONT BLOW THE SECTOR TABLE
	BHI	4$		;OKAY...PROCEED
	BRA	5$		;OOPS...BAD TRACK...RETRY
3$:	BSR	DECODE_SECTOR
	MOVE.B	#-1,D6		;INITIALIZE CRCC ACCUMULATORS
	MOVE.B	D6,D7
	MOVE.W	#517,D2		;512+6-1
	MOVE.L	SECTOR_BUF,A1
	BSR	CALC_CRCC	;CHECK DATA FOR PROPER CRCC
	OR.B	D6,D7		;ANY ERRORS?
	BNE	5$		;YES...RETRY
	CLC
	RTS			;BACK TO CALLER...ALL IS WELL
6$:	BSR	FIND_SECTOR	;SCAN THE TRACK BUFFER FOR NEXT SECTOR
	BRA	4$		;AND SEE IF IT MATCHES
5$:	DECB	RETRY_COUNT	;SECTOR TABLE ERROR
	BEQ	9$		;TRY READING DISK AGAIN
	BSR	HOME_DISK	;MOVE THE HEAD A BIT
	NOERROR 7$
9$:	DISP.	READ_ERR.	;DS-DOS READ ERROR
10$:	STC			;RETURN ERROR FLAG
	RTS

* WRITES D1 CONSECUTIVE LOGICAL SECTORS FROM BUFFER A0, STARTING WITH
* SECTOR IN D0.

WRITE_N:

	DECW	D1		;FOR DBF
1$:	PUSH	D0-D1/A0
	BSR	WRITE_SECTOR	;WRITE ONE SECTOR
	POP	D0-D1/A0
	ERROR	2$		;DISK ERROR
	ADDA.L	#512,A0		;BUMP BUFFER TO NEXT
	INCW	D0		;NEXT SECTOR
	DBF	D1,1$		;LOOP FOR ALL REQUESTED SECTORS
	CLC
2$:	RTS

* WRITE LOGICAL SECTOR.  LOGICAL SECTOR IN D0 (0 ORIGIN), BUFFER IN A0.

WRITE_SECTOR:
	AND.L	#$FFFF,D0
	IFZ	NotFlop,20$
	JMP	DWRITE_SECTOR
20$:	MOVE.B	#5,RETRY_COUNT
	MOVE.L	A0,DMAADR	;SAVE BUFFER ADDRESS
	BSR	CONVERT_SECTOR	;CALCULATE PHYSICAL TRACK, SIDE, SECTOR
	IFNZ	BUF_EMPTY,7$	;NOTHING IN TRACK BUFFER...MUST READ
	MOVE.B	NEW_TRACK,D0
	CMP.B	CUR_TRACK,D0	;SAME TRACK AS CURRENT?
	BNE	1$		;NO...MUST SEEK
	MOVE.B	NEW_SIDE,D0
	CMP.B	CUR_SIDE,D0	;SAME AS CURRENT SIDE?
	BEQ	2$		;YES...SECTOR IS IN THIS TRACK BUFFER
1$:	BSR	FLUSH_TRACK	;WRITE OUT CURRENT TRACK, IF DIRTY
	ERROR	9$
7$:	BSR	SELECT_DRIVE	;GET DRIVE READY
	BSR	SEEK		;STEP HEADS, IF NECESSARY
	MOVEQ	#0,D0		;READ MODE
	BSR	DISK_GO		;READ THE NEW TRACK
	ERROR	5$		;SOMETHING IS WRONG WITH DISK
2$:	LEA	SECTOR_TABLE,A3 ;WORK THE TABLE OF SECTORS
4$:	MOVE.W	0(A3),D0	;CHECK FOR VALID ENTRY HERE
	BEQ.S	5$		;BAD ENTRY...TABLE INVALID
	BMI.S	6$		;UNINITIALIZED SECTOR...GET SECTOR INFO
	MOVE.B	2(A3),D0	;GET TRACK
	CMP.B	NEW_TRACK,D0
	BNE.S	5$
	MOVE.B	4(A3),D0	;GET SECTOR NUMBER
	CMP.B	NEW_SECTOR,D0	;SAME?
	BEQ.S	3$		;YES...ENCODE IT AND WE'RE DONE
11$:	ADDA.L	#14,A3		;BUMP TO NEXT SECTOR IN LIST
	LEA	SECTBL_END,A4
	CMP.L	A3,A4		;MAKE SURE WE DONT BLOW THE SECTOR TABLE
	BHI.S	4$		;OKAY...PROCEED
	BRA.S	5$		;OOPS...BAD TRACK...RETRY
3$:	BSR	MOVE_SEC_TO_TRACK_BUFFER
	SETF	DIRTY_FLAG	;MARK TRACK AS DIRTY
	CLC
	RTS			;BACK TO CALLER...ALL IS WELL
6$:	BSR	FIND_SECTOR	;SCAN THE TRACK BUFFER FOR NEXT SECTOR
	BRA	4$		;AND SEE IF IT MATCHES
5$:	DECB	RETRY_COUNT	;SECTOR TABLE ERROR
	BEQ.S	8$		;RETRY LIMIT
	BSR	HOME_DISK	;RESET DRIVE
	BRA	7$
8$:	DISP.	READ_ERR.
9$:	STC			;RETURN ERROR FLAG
	RTS

* WRITES OUT CURRENT TRACK BUFFER, ONLY IF IT IS DIRTY, AND CLEARS
* DIRTY_FLAG.

FLUSH_TRACK:
	IFZ	NotFlop,20$
	JSR	DeviceFlush
	RTS
20$:	IFZ	DIRTY_FLAG,3$	;NOT DIRTY
	MOVE.B	#5,RETRY_COUNT	;SET UP RETRY LIMIT
2$:	BSR	SELECT_CUR	;SELECT CURRENT SIDE/TRACK
	ERROR	1$		;PROBLEMS
	BSR	CHECK_PROTECTION ;IS DISK WRITE_PROTECTED?
	ERROR	9$		;IT IS...DONT PROCEED
	MOVE.W	#$4000,D0	;WRITE COMMAND
	BSR	DISK_GO		;DO IT
	ERROR	1$
	CLR.B	DIRTY_FLAG
3$:	RTS			;NO ERROR
1$:	DECB	RETRY_COUNT	;SOME PROBLEM...TRY AGAIN?
	BNE	2$		;YES
	CLR.B	DIRTY_FLAG
9$:	STC			;NO
	RTS

* CHECKS SELECTED DRIVE FOR WRITE-PROTECTION STATUS, ALERTS
* OPERATOR AND SETS CY IF SO.

CHECK_PROTECTION:
	BSR	BUSY_DRIVES
	MOVE.B	SAVE_D0,CIAB	;reselect drive
	BTST	#3,CIAA		;PROTECTION ON?
	BNE	1$		;NO
	DISP.	PROT.		;WARN OPERATOR
	BSR	FREE_DRIVES
	STC
	RTS
1$:	BSR	FREE_DRIVES
	CLC
	RTS


* CONVERTS LOGICAL SECTOR IN D0 TO TRACK, SIDE, AND SECTOR.

CONVERT_SECTOR:
	MOVEQ	#0,D1		;PREPARE FOR 32-BIT DIVIDE
	MOVE.W	D0,D1		;DOS_SECTOR TO D1
	ZAP	D3
	MOVE.W	SEC_PER_CYL,D3
	DIVU	D3,D0		;CALCULATE TRACK
	MOVE.B	D0,NEW_TRACK	;SAVE NEW TRACK
	CLR.B	D0
	SWAP	D0		;REMAINDER TO LOWER WORD
	MOVE.W	SEC_PER_TRACK,D3
	DIVU	D3,D0		;CALCULATE SIDE
	MOVE.B	D0,NEW_SIDE	;SAVE IT
	SWAP	D0		;REMAINDER IS SECTOR
	ADD.W	#1,D0		;ONE ORIGIN FOR SECTOR NUMBERS
	MOVE.B	D0,NEW_SECTOR	;SAVE SECTOR
	RTS

* SELECT DRIVE, AND CALIBRATE TO TRACK 0.

HOME_DISK:
	BSR	BUSY_DRIVES
;	MOVE.B	#$7F,CIAB
	MOVE.B	DRIVE_SEL,D0		;DRIVE SELECT CODE WITH MOTOR ON
	BSET	#2,D0			;SIDE 0
	BCLR	#1,D0			;TOWARD SPINDLE (TRACK 79)
	MOVE.B	D0,CIAB
	MOVE.B	D0,SAVE_D0		;SAVE VALUE
	MOVEQ	#2,D2
1$:	BSR	STEP			;MOVE AWAY FROM TRACK 0
	DBF	D2,1$			;LOOP FOR A WHILE
2$:	BSET	#1,SAVE_D0		;NOW MOVE TOWARD EDGE
	MOVEQ	#100,D2			;MAX OF 100 STEPS
	BRA.S	3$
4$:	BSR	STEP			;STEP THE HEADS
3$:	MOVE.B	SAVE_D0,CIAB
	NOP
	BTST	#4,CIAA			;BACK TO TRACK 0?
	DBEQ	D2,4$			;NO...STEP AGAIN
	ZAP	D0
	MOVE.B	D0,CUR_TRACK		;SITTING AT HOME
	MOVE.B	D0,CUR_SECTOR
	MOVE.B	D0,CUR_SIDE
	BSR	FREE_DRIVES
	RTS


DISK_CAL:
	IFNZ	NotFlop,1$		;dont do this if not floppy
	BSR	MOTOR_ON		;TURN MOTOR ON
	ERROR	9$			;DRIVE NOT READY
	BSR	HOME_DISK		;DO THE CALIBRATE HERE
	CLR.B	CUR_TRACK		;SHOW DISK NOW AT TRACK 0
	MOVE.W	#9,SEC_PER_TRACK	;ASSUME DSDD, 9-SECTORS
	MOVE.W	#18,SEC_PER_CYL
	SETF	BUF_EMPTY		;NOTHING IN THE BUFFER, NOW
	CLR.B	DIRTY_FLAG		;JUST IN CASE...
9$:	RTS
1$:	JSR	DeviceReset		;reset external device
	RTS

* DISK READ/WRITE ROUTINES.  ENTER WITH D0=4000 FOR WRITE, D0=0 FOR READ.
* STARTS THE DISK OPERATION.

DISK_GO:
	MOVE.W	D0,DISK_MODE		;READ OR WRITE MODE
	BSR	BUSY_DRIVES
	MOVE.B	SAVE_D0,CIAB		;reselect drive
	MOVE.L	TRACK_BUF,A0		;TRACK BUFFER
	IFZ	DISK_MODE,1$		;READ...NO CORRECTION
11$:	MOVE.W	#15,D2			;16 COMBINATIONS
	LEA	SYNC_TABLE,A2
	MOVE.W	(A0),D1
13$:	CMP.W	(A2)+,D1		;MATCH?
	BEQ.S	12$			;YES...ADJUST A0
	DBF	D2,13$			;NO...TRY NEXT
	ADDQ.L	#2,A0			;ELSE TRY NEXT ENTRY
	BRA.S	11$
12$:	TST.W	D2			;MATCH ON LAST ENTRY?
	BEQ.S	1$			;YES...NO CORRECTION
	SUB.L	#1,A0			;BACK UP 1
1$:	MOVE.L	A0,DSKPTR		;SET UP DMA ADDRESS
	MOVE.W	#$2002,INTREQ		;CLEAR PENDING INTS
	DISABLE				;DISABLE INTERRUPTS
	MOVE.B	FLAG,D0			;CLEAR THE INDEX MARK FLAG
	MOVE.W	#180,D1			;1 sec timeout based on 60 frames/sec
2$:	MOVE.W	VHPOSR,D0
	AND.W	#$FF00,D0		;check vert pos
	BNE.S	21$			;not at top yet
	DECW	D1			;count 1
	BEQ	20$			;timeout...no index mark in 1 sec
22$:	MOVE.W	VHPOSR,D0		;wait till on next line
	AND.W	#$FF00,D0
	BEQ.S	22$
21$:	MOVE.B	FLAG,D0			;INDEX MARK?
	BTST	#4,D0
	BEQ.S	2$			;LOOP TILL WE GET IT
	MOVE.B	FLAG,D0
	MOVE.W	#$2002,INTREQ
	MOVE.W	#TRKSIZ/2,D1
	OR.W	#$8000,D1		;THIS IS THE START BIT
	OR.W	DISK_MODE,D1		;READ OR WRITE MODE
	MOVE.W	D1,DSKLEN		;THATS ONCE
	MOVE.W	D1,DSKLEN		;AND THAT SHOULD START IT

* LOOP TILL DSKBLK SHOWS END OF DMA TRANSFER

3$:	ENABLE
	MOVE.L	#500000,D0
6$:	MOVE.W	INTREQR,D1		;DISK DONE YET?
	BTST	#1,D1
	BNE.S	5$			;YES
	DBF	D0,6$
	SUB.L	#$10000,D0
	BPL.S	6$
20$:	ENABLE
	BSR	FREE_DRIVES
	STC
	RTS
5$:	MOVE.W	#$4000,DSKLEN		;STOP ANYMORE DISK I/O
	MOVE.W	#2,INTREQ		;CLEAR DSKBLK INT
	TST.W	DISK_MODE		;WRITE?
	BNE	4$			;YES
	LEA	SECTOR_TABLE,A3		;READ...RESET SECTOR TABLE...
	MOVE.W	#-1,0(A3)		;...WHOSE CONTENTS ARE NOW INVALID
4$:	BSR	FREE_DRIVES
	CLR.B	DIRTY_FLAG		;TRACK BUFFER NOW 'CLEAN'
	CLR.B	BUF_EMPTY		;BUFFER NOT EMPTY NOW
	RTS

* SELECTS DRIVE AND SIDE, AND TURNS ON MOTOR IF NECESSARY.

SELECT_CUR:
	MOVE.B	CUR_SIDE,D1		;TO SELECT CURRENT SIDE/TRACK
	BRA.S	SEL1

SELECT_DRIVE:
	MOVE.B	NEW_SIDE,D1		;GET SIDE
SEL1:
	MOVE.B	DRIVE_SEL,D0		;GET DRIVE SELECT BIT CODE
	BSET	#2,D0			;SET SIDE 0
	IFZ	D1,1$			;SIDE 0
	BCLR	#2,D0			;ELSE SET SIDE 1 BIT
1$:	MOVE.B	D0,SAVE_D0
	BSR	MOTOR_ON		;make sure motor is on
	RTS

* SEEKS TO PROPER TRACK, IF NECESSARY.  ASSUMES THAT DRIVE ALREADY
* SELECTED, MOTOR ON, AND INTERRUPTS OFF.

SEEK:
	BSR	BUSY_DRIVES
	ZAP	D2
	MOVE.B	NEW_TRACK,D2		;DO WE NEED TO SEEK?
	CMP.B	CUR_TRACK,D2		;FIGURE OUT HOW MANY STEPS ARE NEEDED
	BEQ.S	2$			;NONE NEEDED
	BHI.S	1$			;
	BSET	#1,SAVE_D0		;MOVE TOWARD TRACK 0
	MOVE.B	CUR_TRACK,D2		;AND CALCULATE STEPS
	SUB.B	NEW_TRACK,D2
	BRA.S	3$
1$:	BCLR	#1,SAVE_D0		;MOVE TOWARD SPINDLE
	MOVE.B	NEW_TRACK,D2		;CALC STEPS
	SUB.B	CUR_TRACK,D2
3$:	IFZ	DOUBLE_STEP,4$		;NO DOUBLE STEPPING
	ADD.B	D2,D2			;ELSE FORCE DOUBLE STEP
4$:	SUBQ.L	#1,D2			;ADJUST FOR DBF
6$:	BSR.S	STEP			;DO IT
	DBF	D2,6$			;LOOP TILL WE GET THERE
2$:	BSR	FREE_DRIVES
	MOVE.L	#23000,D0		;HEAD SETTLING DELAY=23MS
	BSR	DELAY
	MOVE.B	NEW_TRACK,CUR_TRACK	;NOW MAKE NEW TRACK CURRENT TRACK
	MOVE.B	NEW_SIDE,CUR_SIDE
	MOVE.B	NEW_SECTOR,CUR_SECTOR
	RTS

* STEP THE HEADS

STEP:
	MOVE.B	SAVE_D0,D0		;SAVED DISK SELECT, SIDE, DIRECTION
	LEA	CIAB,A1
;	MOVE.B	#$7F,(A1)		;prep the hardware
	MOVE.B	D0,D1
	BCLR	#0,D0			;STEP BIT
	MOVE.B	D0,(A1)
	NOP
	NOP
	MOVE.B	D1,(A1)
	BSR	FREE_DRIVES
	MOVE.L	#6000,D0		;APPROX 6 MS
	IFZ	IS_3.5,1$
	MOVE.L	#3000,D0		;APPROX 3 MS
1$:	BSR.S	DELAY			;WAIT
	BSR	BUSY_DRIVES
;	MOVE.B	#$7F,CIAB		;init the hardware
	RTS

LoopDelay:
	DBF	D1,LoopDelay
	SUB.L	#$10000,D1
	BPL.S	LoopDelay
	RTS

* TIME DELAY USING EXEC TIMER.  DELAY IN D0, UNITS OF USECS.

DELAY:	PUSH	D2
	MOVE.L	D0,TB_USEC		;SAVE DELAY VALUE IN USECS
	CLR.L	TB_SECS
	LEA	TIMER_BLOCK,A1
	MOVE.W	#TR_ADDREQUEST,TB_CMD	;SIMPLE TIMER REQUEST
	CLR.L	TB_SECS			;SET SECONDS TO 0
	CALLSYS	DoIO,SysBase
	POP	D2
        RTS

* FORMATS A SINGLE TRACK, DEFINED IN D0.

FORMAT_TRACK:
	LEA	FORMAT_TABLE,A0
	MOVE.L	TRACK_BUF,A1
	MOVE.W	#$91,D0
1$:	MOVE.B	(A0)+,(A1)+
	DBF	D0,1$
	MOVE.W	SEC_PER_TRACK,D0	;EMPTY SECTOR DATA CHAR
	DECW	D0
	LEA	SECTOR_TABLE,A3
	CLR.B	NEW_SECTOR		;START FROM SECTOR 0
FORMAT_LOOP:
	PUSH	D0
	MOVE.B	#-1,D6
	MOVE.B	D6,D7
	MOVE.W	#$B,D1
	MOVE.B	#0,D0
	BSR.L	STORE_D0_D1_TIMES
	MOVE.L	A1,D5
	MOVE.L	A1,D1
	MOVE.L	TRACK_BUF,A0
	SUB.L	A0,D1
	MOVE.W	D1,0(A3)
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-2,(A1)+
	MOVE.B	NEW_TRACK,(A1)+		;CYL
	MOVE.B	NEW_SIDE,(A1)+		;SIDE
	INCB	NEW_SECTOR
	MOVE.B	NEW_SECTOR,(A1)+	;RECORD (SECTOR)
	MOVE.B	#2,(A1)+		;N=2 (512 BYTES)
	MOVE.W	#7,D2
	MOVEA.L D5,A1
	BSR.L	CALC_CRCC
	MOVE.B	D6,(A1)+		;STORE CRCC CHARS
	MOVE.B	D7,(A1)+
	MOVE.W	#$15,D1
	MOVE.B	#$4E,D0
	BSR.L	STORE_D0_D1_TIMES
	MOVE.W	#$B,D1
	MOVE.B	#0,D0
	BSR.L	STORE_D0_D1_TIMES
	MOVE.L	A1,D5
	MOVE.L	A1,D1
	MOVE.L	TRACK_BUF,A0
	SUB.L	A0,D1
	MOVE.W	D1,8(A3)
	ADDA.L	#$E,A3
	MOVE.B	#-1,D6
	MOVE.B	D6,D7
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-$5F,(A1)+
	MOVE.B	#-5,(A1)+
	MOVE.W	#511,D1
	MOVE.B	#$F6,D0			;FORMAT DATA CHAR
	PUSH	D1
1$:	MOVE.B	D0,(A1)+
	DBF	D1,1$
	POP	D2
	ADDQ.W	#4,D2
	MOVEA.L D5,A1
	BSR.L	CALC_CRCC
	MOVE.B	D6,(A1)+
	MOVE.B	D7,(A1)+
	MOVE.W	#80,D1			;SECTOR GAP SIZE
	SUBQ.W	#1,D1
	MOVE.B	#$4E,D0
	BSR.L	STORE_D0_D1_TIMES
	POP	D0
	DBF	D0,FORMAT_LOOP
	CLR.W	0(A3)			;MARK END OF TABLE
	MOVE.L	TRACK_BUF,A0
	MOVE.L	#TRKSIZ/2,D1
	ADD.L	A0,D1
	SUB.L	A1,D1
	MOVE.B	#$4E,D0			;FILL REST OF TRACK BUFFER
	BSR.L	STORE_D0_D1_TIMES
	MOVE.L	#TRKSIZ/2,D2
	MOVE.L	TRACK_BUF,A0
	ADDA.W	D2,A0
	MOVEA.L A0,A1
	ADDA.W	D2,A1
	MOVE.L	D2,D5
	ADD.W	D5,D5
	MOVE.L	D5,D6
	SUBQ.W	#1,D2
	BSR.L	MOVE_XLATE
	BSR	GRAB_BLITTER
	MOVE.L	TRACK_BUF,A0
	BSR.L	BLITTER_ENCODE
	BSR	FREE_BLITTER
	MOVE.W	#$B8,D0
	MOVE.W	#$5224,0(A0,D0.W)
	MOVE.W	#$5224,2(A0,D0.W)
	MOVE.W	#$5224,4(A0,D0.W)
	LEA	SECTOR_TABLE,A3
3$:	MOVE.W	0(A3),D0
	BEQ.L	2$			;END OF SECTOR TABLE
