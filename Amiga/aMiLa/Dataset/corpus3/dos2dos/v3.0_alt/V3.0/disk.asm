DISK_INIT:
	TST.L	TRACK_BUF		;buffer already allocated?
	BNE	10$
	MOVE.B	#$10,FLAG		;TURN OFF ICR ENABLE MASK
	MOVE.W	#$600,ADKCON		;clear word & GCR sync
	MOVE.W	#$9100,ADKCON		;set MFM precomp and 2usec clock
	MOVE.L	#TRKSIZ+2+SECSIZ+CRCCSIZ,D0 ;GRAB A BUNCH
	MOVEQ	#2,D1			;SPECIFY CHIP MEMORY
	CALLSYS	AllocMem,SysBase	;GRAB A HUNK OF CHIP MEMORY
	TST.L	D0			;GOT ANY?
	BNE.S	4$			;got some
	DISP.	CHIP_MEM.		;not enough memory
	BRA	9$
4$:	ADDQ.L	#2,D0			;ALLOW ROOM FOR ERROR
	MOVE.L	D0,TRACK_BUF		;POINTER TO TRACK BUFFER
	ADD.L	#TRKSIZ,D0
	MOVE.L	D0,SECTOR_BUF
	ADD.L	#SECSIZ,D0
	MOVE.L	D0,CRCC_BUF
	MOVE.L	D0,A6
	MOVEQ	#0,D7
1$:	MOVEQ	#0,D6
	MOVE.B	D7,D6
	LSL.W	#8,D6
	MOVEQ	#7,D0
2$:	LSL.W	#1,D6
	BCC.S	3$
	EORI.W	#$1021,D6
3$:	DBF	D0,2$
	MOVE.B	D6,$100(A6)
	LSR.W	#8,D6
	MOVE.B	D6,(A6)+
	INCB	D7
	BNE.S	1$
;	ZAPA	A1
;	CALLSYS	FindTask,SysBase	;GET D2D TASK POINTER
;	MOVE.L	D0,D2D_TASK		;SAVE FOR SEIZING DISK
	MOVE.L	D2D_TASK,MP_TASK	;INIT MSG PORT
	BEQ.S	9$			;OOPS...PROBLEM
	LEA	TIMER.,A0
	ZAP	D0			;USEC
	LEA	TIMER_BLOCK,A1
	ZAP	D1
	CALLSYS	OpenDevice,SysBase	;OPEN THE TIMER
	BEQ.S	10$			;GOT TIMER
	DISP.	NoTimer.
9$:	STC
	RTS
10$:	CLC
	RTS

DISK_EXIT:
	MOVE.L	TRACK_BUF,D0
	BEQ.S	9$
	MOVE.L	D0,A1			;BASE OF ALLOCATED MEMORY
	SUBQ.L	#2,A1
	MOVE.L	#TRKSIZ+2+SECSIZ+CRCCSIZ,D0
	CALLSYS	FreeMem,SysBase		;RETURN TO POOL
	CLR.L	TRACK_BUF
	LEA	TIMER_BLOCK,A1		;FREE THE TIMER
	CALLSYS	CloseDevice
9$:	RTS

MOTOR_OFF:
	IFZ	MOTOR_FLAG,MEND		;MOTOR OFF?
	BSR	BUSY_DRIVES		;WAIT TILL DRIVES NOT BUSY
MOFF:	MOVE.B	#-1,CIAB		;NOW TURN MOTOR OFF
	MOVE.B	#-1,CIAB
	MOVE.B	DRIVE_SEL,D0		;GET DRIVE SELECT CODE
	BSET	#7,D0			;SET MOTOR OFF BIT
	MOVE.B	D0,CIAB			;TURN IT OFF
	CLR.B	MOTOR_FLAG		;MOTOR OFF NOW
	BSR	FREE_DRIVES
MEND:	RTS


MOTOR_ON:
	PUSH	D2
	IFNZ	MOTOR_FLAG,9$		;MOTOR ALREADY ON
	BSR	BUSY_DRIVES		;NO...TURN IT ON
;;	MOVE.B	#$7F,CIAB		;TURN ON MOTOR BIT
	MOVE.B	DRIVE_SEL,CIAB		;DRIVE SELECT CODE
	MOVEQ	#20-1,D2
1$:	MOVE.L	#100000,D0		; 0.1 sec
	BSR	DELAY			;WAIT FOR A WHILE
;;	MOVE.B	#-1,CIAB
;;	MOVE.B	#$7F,CIAB		;TURN ON MOTOR BIT
;;	MOVE.B	DRIVE_SEL,CIAB
	BTST	#5,CIAA			;drive ready?
	BEQ.S	2$			;yes
	DBF	D2,1$			;not yet...try again
	BSR	MOFF
	DISP.	DRV_NR.
	STC
	BRA.S	9$
2$:	BSR	FREE_DRIVES
	SETF	MOTOR_FLAG		;MOTOR IS ON NOW
9$:	POP	D2
	RTS

