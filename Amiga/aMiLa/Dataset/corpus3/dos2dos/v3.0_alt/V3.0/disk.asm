* MOVES SECTOR DATA FROM SECTOR BUFFER, ENCODES IT AND MOVES TO TRACK
* BUFFER.  SECTOR DATA POINTER IN A2.  PTR TO SECTOR TABLE ENTRY IN A3.

MOVE_SEC_TO_TRACK_BUFFER:
	MOVE.L	SECTOR_BUF,A1	;MOVE TEXT FROM SECTOR BUFFER
	ADDQ.L	#4,A1
	MOVE.L	DMAADR,A2	;SECTOR DATA BUFFER
	MOVE.W	#511,D2
