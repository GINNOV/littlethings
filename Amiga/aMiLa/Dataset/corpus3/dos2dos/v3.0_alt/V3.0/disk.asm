	BSR	FREE_BLITTER
	RTS

* SEARCHES THE TRACK BUFFER LOOKING FOR ENCODED SECTOR ID DATA.  THEN PUTS
* SECTOR ID AND OFFSET TO DATA INTO SECTOR ENTRY IN SECTOR_TABLE.
* CAN BE CALLED UP TO 9 TIMES PER TRACK.
* A3 POINTS TO CURRENT ENTRY IN SECTOR TABLE.

FIND_SECTOR:
	MOVEQ	#0,D6
	MOVEQ	#0,D7
	MOVEQ	#0,D1
	MOVE.W	#TRKSIZ-1,D0
	SUB.W	-6(A3),D0		;ADJUST FOR STARTING OFFSET
	MOVE.L	TRACK_BUF,A0
	ADDA.W	-6(A3),A0		;START AT PREVIOUS SECTOR, IF ANY
	BSR	SYNCHRONIZE
	TST.W	D0
1$:	BMI.L	8$
2$:	MOVE.W	#6,D3			;MATCH ON 7 BYTES
	MOVEM.L D0/A0,-(A7)
3$:	MOVE.B	(A2)+,D2
	CMP.B	(A0)+,D2
	BNE.L	15$			;NO MATCH...TRY AGAIN
	SUBQ.W	#1,D0
	BMI.L	9$			;END OF TRACK DATA...NOMATCH
	DBF	D3,3$
	TST.B	D1
	BEQ.S	4$			;NO SHIFT NECESSARY
	MOVE.W	#-$100,D3
	LSR.W	D1,D3
	MOVE.B	(A0),D2
	AND.B	D3,D2
	CMP.B	(A2)+,D2
	BNE.L	15$
4$:	MOVE.L	TRACK_BUF,A1
	MOVE.L	A0,D2
	SUB.L	A1,D2
	MOVE.W	D2,0(A3)
	MOVE.W	D2,8(A3)
	CLR.B	$C(A3)
	MOVE.W	#-1,$E(A3)
	CLR.W	$16(A3)
	MOVE.L	SECTOR_BUF,A1		;DESTINATION FOR SECTOR DATA
	MOVEM.L A0-A1,-(A7)
	BSR	COPY_SECTOR_ID
	MOVEM.L (A7)+,A0-A1
	MOVEM.L A0-A2,-(A7)
	MOVE.W	#5,D2
	MOVEA.L A1,A0
	LEA	2(A3),A1
	BSR	COMBINE_NYBBLES
	MOVEM.L (A7)+,A0-A2
	MOVEM.L (A7)+,D0/A0
5$:	BSR	SYNCHRONIZE
	TST.W	D0
	BMI.L	11$
	MOVEM.L D0/A0,-(A7)
	MOVE.W	#5,D3			;6-BYTE RESULT
6$:	MOVE.B	(A2)+,D2
	CMP.B	(A0)+,D2
	BNE.L	12$
	SUBQ.W	#1,D0
	BMI.L	10$			;END OF TRACK DATA
	DBF	D3,6$
	ADDQ.L	#2,A2
	MOVE.B	(A2)+,D2
	CMP.B	(A0)+,D2
	BNE.L	14$			;NO MATCH
	SUBQ.W	#1,D0
	BMI.L	10$			;END OF TRACK DATA
	TST.B	D1
	BEQ.S	7$			;NO SHIFT
	MOVE.W	#-$100,D3
	LSR.W	D1,D3
	MOVE.B	(A0)+,D2
	AND.B	D3,D2
	CMP.B	(A2)+,D2
	BNE.L	13$			;NO MATCH
	SUBQ.W	#1,D0
	BMI.L	10$			;END OF TRACK DATA
	MOVE.B	#-5,$C(A3)
7$:	MOVEM.L (A7)+,D0/A0
	SUBQ.L	#1,A0
	MOVE.L	TRACK_BUF,A1
	MOVE.L	A0,D2
	SUB.L	A1,D2
	MOVE.W	D2,8(A3)
	MOVE.W	D1,$A(A3)
	RTS
9$:	ADDQ.L	#8,A7
8$:	CLR.W	0(A3)
	CLR.W	8(A3)
	RTS
10$:	ADDQ.L	#8,A7
11$:	CLR.W	$E(A3)
	CLR.W	$16(A3)
	RTS
12$:	MOVEM.L (A7)+,D0/A0
	BRA.L	5$
13$:	SUBQ.L	#1,A0
	SUBQ.L	#1,A2
14$:	SUBQ.L	#1,A0
	ADDQ.L	#1,A2
	MOVE.B	(A2)+,D2
	CMP.B	(A0)+,D2
	BNE.L	16$
	SUBQ.W	#1,D0
	BMI.S	10$
	TST.B	D1
	BEQ.S	7$
	MOVE.W	#-$100,D3
	LSR.W	D1,D3
	MOVE.B	(A0)+,D2
	AND.B	D3,D2
	CMP.B	(A2)+,D2
	BNE.S	16$
	SUBQ.W	#1,D0
	BMI.S	10$
	MOVE.B	#-8,$C(A3)
	BRA.S	7$
