* COPIES AND SHIFTS AN ENTIRE ENCODED SECTOR.  A0=SOURCE, A1=DEST, D1=SHIFT

BLITTER_DECODE:
	BSR	GRAB_BLITTER		;WAIT TILL BLITTER IS FREE
	MOVE.W	#512,D2			;BASIC SECTOR SIZE
	ADDQ.W	#6,D2
	LSL.W	#1,D2
	MOVE.W	#0,$DFF064
	TST.B	D1			;ANY SHIFT?
	BEQ.S	BC_4			;NO
	MOVE.B	#8,D3
	SUB.B	D1,D3
	MOVE.B	D3,D1
	SUBQ.W	#2,A1
	ADDQ.W	#2,D2
	MOVE.L	A0,D3
	BTST	#0,D3
	BEQ.S	BC_2
	SUBQ.L	#1,A0
	BRA.S	BC_3
BC_2:	ADDQ.B	#8,D1
BC_3:	BRA.S	BC_5
BC_4:	MOVE.L	A0,D3
	BTST	#0,D3
	BEQ.S	BC_5
	SUBQ.L	#1,A0
	ADDQ.B	#8,D1
	SUBQ.W	#2,A1
	ADDQ.W	#2,D2
BC_5:	MOVE.L	A1,$DFF054
	MOVE.W	#0,$DFF066
	MOVE.L	A0,$DFF050
	MOVE.W	#0,$DFF042
	LSL.W	#8,D1
	LSL.W	#4,D1
	OR.W	#$9F0,D1
	MOVE.W	D1,$DFF040
	MOVE.W	D2,D1
	MOVE.W	#-1,$DFF044
	MOVE.W	#-1,$DFF046
	ADD.W	#$10,D2
	AND.W	#-$10,D2
	LSL.W	#2,D2
	OR.W	#8,D2
	MOVE.W	D2,$DFF058		;KICK THE BLITTER
	BSR	WAIT_BLITTER		;AND WAIT 'TILL ITS DONE
	BSR	FREE_BLITTER
	RTS


CALC_CRCC:
	MOVE.L	CRCC_BUF,A6
	MOVE.L	A6,D4
	MOVEQ	#0,D5
1$:	MOVE.B	(A1)+,D5
	MOVEA.L D4,A6
	EOR.B	D6,D5
	ADDA.W	D5,A6
	MOVE.B	(A6),D6
	EOR.B	D7,D6
	MOVE.B	$100(A6),D7
	DBF	D2,1$
	RTS


* SHIFTS AND STORES 12-BYTE ENCODED SECTOR ID.  A0=SOURCE PTR, A1=DEST PTR.

COPY_SECTOR_ID:
	MOVE.W	#$B,D3			;12-BYTE SECTOR ID
	SUB.W	D3,D0
	TST.W	D1			;ANY SHIFTING NECESSARY?
	BEQ.S	CT2			;NO...JUST COPY
	SUBQ.W	#1,D0			;ELSE SHIFT AND COPY
	MOVE.L	D0,-(A7)
	MOVE.B	#8,D0
	SUB.B	D1,D0
	MOVE.B	(A0)+,D2
	LSL.W	#8,D2
CT1:	MOVE.B	(A0)+,D2
	ROR.W	D0,D2
	MOVE.B	D2,(A1)+
	LSR.W	D1,D2
	DBF	D3,CT1
	MOVE.L	(A7)+,D0
	RTS
CT2:	MOVE.B	(A0)+,(A1)+		;NO SHIFT NECESSARY
	DBF	D3,CT2
	RTS

BLITTER_ENCODE:
	MOVE.W	#$5555,$DFF070
	PUSH	A0
	ADD.L	#$40,D6
	AND.L	#-$20,D6
	ADDA.L	D6,A0
	OR.W	#$20,D6
	SUBQ.L	#2,A0
	MOVE.L	A0,$DFF050
	MOVE.W	#0,$DFF064
	MOVE.W	#-1,$DFF044
	MOVE.W	#-1,$DFF046
	MOVE.L	A0,$DFF04C
	MOVE.L	A0,$DFF054
	MOVE.W	#0,$DFF062
	MOVE.W	#0,$DFF066
	MOVE.W	#$1002,$DFF042
	MOVE.W	#$DB1,$DFF040
	MOVE.W	D6,$DFF058
	BSR.S	WAIT_BLITTER
	POP	A0
	MOVE.L	A0,$DFF050
	MOVE.L	A0,$DFF04C
	MOVE.L	A0,$DFF054
	MOVE.W	#0,$DFF042
	MOVE.W	#$1D8C,$DFF040
	MOVE.W	D6,$DFF058
	BSR.S	WAIT_BLITTER
	RTS

WAIT_BLITTER:
	MOVE.W	INTREQR,D3
	BTST	#6,D3
	BEQ.S	WAIT_BLITTER
	MOVE.W	#$40,INTREQ		;CANCEL BLITTER INT REQ
	RTS

GRAB_BLITTER:
	IFNZ	BLIT_COUNT,1$		;ALREADY HAVE BLITTER
	PUSH	D0-D7/A0-A6
	MOVE.L	GraphicsBase,A6
	CALLSYS	OwnBlitter		;WAIT TILL WE OWN IT
	MOVE.W	#$4000,INTENA		;TURN OFF INTS
	MOVE.L	#50000,D1
	BSR	LoopDelay		;WAIT A WHILE...LET BLITTER FINISH
	MOVE.W	#$40,INTREQ		;CANCEL ANY BLITTER INT REQ
	POP	D0-D7/A0-A6
1$:	INCB	BLIT_COUNT		;ANOTHER CALL
	RTS

FREE_BLITTER:
	IFZ	BLIT_COUNT,1$		;BLITTER ALREADY FREE
	DECB	BLIT_COUNT		;ONE LESS OWNER
	BNE.S	1$			;NOT FINISHED YET
	PUSH	D0-D7/A0-A6		;ELSE GIVE UP THE BLITTER
	MOVE.W	#$C000,INTENA		;TURN INTS BACK ON
	MOVE.L	GraphicsBase,A6
	CALLSYS	DisownBlitter	
	POP	D0-D7/A0-A6
1$:	RTS

* SETS AMIGA-DOS DISK DRIVES BUSY FOR DURATION OF DISK OPERATION.

BUSY_DRIVES:
	PUSH	A0-A1
1$:	MOVE.L	DR_BASE,A6	;ASK AMIGA-DOS POLITELY...
	LEA	DISK_BLOCK,A1
	MOVE.L	D2D_TASK,MP_TASK
	JSR	DR_GetUnit(A6)	;...FOR THE DISK CONTROLLER
	TST.L	D0
	BNE	2$		;GOT THE DISK
3$:	LEA	MSG_PORT,A0	;else wait till free
	CALLSYS	WaitPort,SysBase ;WILL SEND REPLY TO DRU PORT
	LEA	MSG_PORT,A0
	CALLSYS	GetMsg		;UNQUEUE REPLY
	TST.L	D0
	BEQ.S	3$
	BRA.S	1$		;NOW TRY FOR IT AGAIN
2$:	MOVE.B	#$7F,CIAB	;prep the hardware
	POP	A0-A1
	RTS

* FREES AMIGA-DOS DISK DRIVES AFTER DISK OPERATION.

