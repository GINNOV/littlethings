* STRIPS CR FROM TEXT IN CLUSTER BUFFER.  ADJUSTS BytCnt TO CORRECT SIZE.

STRIP_CR:
	PUSH	A2
	LEA	MAXlate,A2
	MOVE.L	ClusterBuf,A0
	MOVE.L	A0,A1			;MOVE TO SAME BUFFER
	MOVE.W	BytCnt,D1		;NUMBER OF BYTES TO PROCESS
	MOVE.L	D1,D2			;FASTER BytCnt UPDATE
	DECW	D1
1$:	MOVE.B	(A0)+,D0		;GET A BYTE
	AND.W	#$FF,D0
	TST.B	WSFlg
	BEQ.S	5$			;don't clear high bit
	AND.W	#$7F,D0
5$:	MOVE.B	0(A2,D0.W),D0		;translate to Amiga char set
;	BEQ.S	4$			;no equivalent char
;	ANDI.B	#$7F,D0			;ZAP ANY HIGH ORDER BIT (WORDSTAR)
	CMP.B	#32,D0			;ASCII CONTROL CHAR?
	BCC.S	2$			;NO...KEEP IT
;	CMP.B	#10,D0			;LINE FEED?
;	BEQ.S	2$			;KEEP IT
;	CMP.B	#9,D0			;TAB?
;	BEQ.S	2$			;KEEP IT
	CMP.B	#13,D0			;CR?
	BNE.S	2$			;no...keep it
4$:	DECW	D2			;ELSE GET RID OF IT.  ONE LESS BYTE
	BRA.S	3$			;BUT COUNT IT FOR LOOP
2$:	MOVE.B	D0,(A1)+		;STORE translated CHAR BACK INTO BUFFER
3$:	DBF	D1,1$			;LOOP FOR WHOLE BUFFER
	MOVE.W	D2,BytCnt		;UPDATED BytCnt
	POP	A2
	RTS

* ADDS CR TO END OF EACH ASCII TEXT LINE GOING TO MS-DOS FROM AMIGA-DOS.
* READS TEXT INTO ADosBuf, AND WRITES OUT OF ClusterBuf.  RETURNS CY=1 ON ERROR.
* Translates characters, as necessary.

ADD_CR:
	CLR.W	ADosCnt			;START WITH EMPTY INPUT BUFFER
	CLR.W	BytCnt			;COUNT OF BYTES IN ClusterBuf
	MOVE.L	ClusterBuf,CLSPTR	;INIT OUTPUT POINTER
1$:	BSR	GET_AD_CHAR		;GET A CHAR IN D0
	ERROR	3$			;EOF OR ERROR
	AND.W	#$FF,D0			;index by word
	LEA	AMXlate,A0
	MOVE.B	0(A0,D0.W),D0		;translate to MS-DOS char set
;	BEQ.S	1$			;oops...no equivalent char
	CMP.B	#10,D0			;LINE FEED?
	BNE.S	2$			;NO
	MOVE.B	#13,D0
	BSR	PUT_CHAR		;ELSE INSERT CR AHEAD OF LF
	MOVE.B	#10,D0
2$:	BSR	PUT_CHAR		;STORE CHAR
	ERROR	9$
	BRA.S	1$			;LOOP
3$:	BSR	WRITE_CLUSTER		;WRITE LAST CLUSTER TO DISK
9$:	RTS

* GETS A CHAR FROM ADosBuf, BASED ON ADosCnt.  RETURNS CY=1 ON EOF OR ERROR.

GET_AD_CHAR:
	TST.W	ADosCnt			;ANY CHARS IN BUFFER?
	BNE	1$			;YES
	READFILE FILEHANDLE,ADosBuf,#ADosBufSize	;READ IN MORE TEXT
	MOVE.W	D0,ADosCnt		;COUNT WE REALLY GOT
	BEQ.S	9$			;EOF
	CMP.L	#-1,D0			;ERROR?
	BEQ.S	9$			;YES
	MOVE.L	ADosBuf,ADBPTR		;RESET POINTER TO TOP
1$:	MOVE.L	ADBPTR,A0		;POINTER TO NEXT BYTE
	MOVE.B	(A0)+,D0		;GET A BYTE
	MOVE.L	A0,ADBPTR		;SAVE UPDATED PTR
	DECW	ADosCnt			;ONE LESS CHAR
	CLC
	RTS
9$:	STC
	RTS

* STORES CHAR IN D0 INTO ClusterBuf VIA POINTER CLSPTR, AND COUNTS IN BytCnt.
* WHEN BUFFER FULL, FLUSHES TO MS-DOS FILE VIA WRITE_CLUSTER.

PUT_CHAR:
	MOVE.L	CLSPTR,A0		;GET POINTER
	MOVE.B	D0,(A0)+		;STORE CHAR
	MOVE.L	A0,CLSPTR
	INCW	BytCnt			;COUNT CHAR
	ZAP	D0
	MOVE.W	BytCnt,D0
	CMP.L	ClusterSize,D0		;BUFFER FULL?
	BCS.S	1$			;NO
	BSR	WRITE_CLUSTER		;YES...WRITE IT OUT
	ERROR	2$
	CLR.W	BytCnt			;AND RESET BUFFER CONTROLS
	MOVE.L	ClusterBuf,CLSPTR
1$:	CLC
2$:	RTS

* Updates AmigaDOS file date/time stamp to that of MS-DOS file.
* FROM EDN OCT 17, 1985 P. 168

UpdateDateTime:
	PUSH	A2-A4
	MOVE.	A_FNAME.,TMP.
	STG_Z.	TMP.
	MOVE.L	#TMP.,D1
	CALLSYS	DeviceProc,DosBase	;get proc id for file task
	TST.L	D0
	BEQ	9$			;didn't get one...some problem
	MOVE.L	D0,A3			;save process ID
	CALLSYS	IoErr
	MOVE.L	D0,PktArg2		;lock...from DeviceProc via IoErr
;	BEQ	9$			;no lock...must be a dir
	MOVE.	A_FNAME.,TMP.
	MOVE.L	#TMP.,D0
	LSR.L	#2,D0			;make BSTR out of TMP.'s address
	MOVE.L	D0,PktArg3
	MOVE.L	DirPtr,A2
	ZAP	D5
	MOVE.W	ms_Date(A2),D5		;GET DATE STAMP
	SWAB	D5			;adjust for Intel format
	MOVE.L	D5,D0
	LSR	#5,D0			;GET MONTH
	AND.L	#$F,D0
	MOVE.L	D5,D1
	AND.L	#$1F,D1			;GET DAY
	MOVE.L	D5,D2			;GET YEAR
	LSR	#8,D2
	LSR	#1,D2
	ADD	#80,D2			;ADJUST FOR 1980
1$:	CMP.W	#100,D2			;=> YEAR 2000?
	BCS.S	2$			;NO
	SUB.W	#100,D2			;ELSE CORRECT TO PROPER RANGE
	BRA.S	1$			;BUT FIRST, CHECK AGAIN
2$:	CMPI.W	#2,D0
	BLE.S	3$
	SUBQ.W	#3,D0			;M=M-3
	BRA.S	4$
3$:	ADDI.W	#9,D0			;M=M+9
	SUBQ.W	#1,D2			;Y=Y-1
4$:	MULU	#1461,D2
	LSR.L	#2,D2			;T1=INT(1461*Y)/4
	MULU	#153,D0
	ADDQ.L	#2,D0
	DIVU	#5,D0			;T2=INT((153*M+2)/5)
	ADD.W	D2,D0
	ADD.W	D1,D0			;K=T1+T2+D
	SUB.W	#MagicNumber,D0		;make into days since January 1, 1978
	EXT.L	D0
	MOVE.L	D0,DATE
	MOVE.W	ms_Time(A2),D5		;GET TIME STAMP
	SWAB	D5			;Intel format
	MOVE.L	D5,D0
	LSR	#8,D0
	LSR	#3,D0			;GET HOURS
	MULU	#60,D0			;convert to minutes
	MOVE.L	D5,D1
	LSR	#5,D1			;FORGET SECONDS
	AND	#$3F,D1			;GET MINUTES
	ADD.L	D1,D0			;total minutes since midnight
	MOVE.L	D0,TIME
	CLR.L	TICKS			;assume ticks = 0
	MOVE.L	#DATESTAMP,PktArg4
	MOVE.L	#ACTION_DATE,D0
	MOVE.L	A3,A0
	BSR	PacketIO		;update date on file
9$:	POP	A2-A4
	RTS

PacketIO:
	MOVE.L	D0,PktType		;save packet type
	MOVE.L	D2D_TASK,A4
