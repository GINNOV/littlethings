* PERFORMS MS-DOS PATH ANALYSIS AND SETS UP PROPER (SUB)DIRECTORY FROM FULL
* PATH IN M_FNAME.

SEARCH_PATH:
	BSR	DISK_LOG		;START AT MAIN DIRECTORY
	ERROR	8$
	CLR.W	FirstSubClus		;NO SUBDIR NOW
3$:	MOVE.B	M_FNAME.+1,D0
	CMP.B	#'\',D0			;SKIP LEADING "\"
	BNE.S	1$
	CLIP.	#1,M_FNAME.
1$:	BSR.S	SCAN_SUBDIR		;TRY TO GET A SUBDIR NAME
	ERROR	2$			;NOTHING...ALL DONE
	BSR	READ_SUBDIR		;ELSE FIND AND READ IN SUBDIRECTORY
	ERROR	BAD_DIR
	BRA.S	3$
2$:	CLC
8$:	RTS

* SCANS M_FNAME. FROM LEFT, TRYING TO BUILD A SUBDIRECTORY NAME IN A.

SCAN_SUBDIR:
1$:	IFZ	M_FNAME.,9$		;NOTHING LEFT
	MOVE.B	M_FNAME.+1,D0		;START WITH '\'?
	CMP.B	#'\',D0
	BNE.S	2$			;NO
	CLIP.	#1,M_FNAME.		;ELSE GET RID OF IT
	BRA.S	1$
2$:	LEA	M_FNAME.,A0
	ZAP	D1
	MOVE.B	(A0)+,D1
	DECW	D1
	LEA	TMP.,A1			;BUILD NEW SUBDIR NAME
	MOVE.L	A1,A2
	CLR.B	(A1)+			;ZAP LENGTH
4$:	MOVE.B	(A0)+,D0		;GET A CHAR
	CMP.B	#'\',D0			;END OF SUBDIR NAME?
	BEQ	3$			;YES
	MOVE.B	D0,(A1)+		;ELSE ADD CHAR TO SUBDIR NAME
	INCB	(A2)			;AND COUNT IT
	DBF	D1,4$
	CLR.B	(A2)			;OOPS...NO '\'...MUST BE FILE NAME
9$:	STC
	RTS
3$:	MOVE.	TMP.,A.			;MOVE SUBDIR NAME TO A.
	ZAP	D1
	MOVE.B	A.,D1
	CLIP.	D1,M_FNAME.		;REMOVE SUBDIR NAME
	CLC
	RTS

* READS THE MS-DOS DIRECTORY, SORTS CONTENTS AND LISTS ON SCREEN.

LIST_DIR:
	MOVE.L	#32,ENTRY_LEN		;LENGTH OF MS-DOS ENTRY
	MOVE.W	#11,NAME_LEN		;11-BYTE NAME LENGTH
	MOVE.L	DirectoryBuf,A0
	MOVE.W	ENTRIES_PER_DIR,D0
	BSR	SORT_DIR		;SORT DIRECTORY
	BSR	DISP_DIR		;LIST DIRECTORY CONTENTS
	CLC
	RTS

LIST_AD_DIR:
	MOVE.L	#40,ENTRY_LEN		;LENGTH OF AD DIRECTORY ENTRY
	MOVE.W	#30,NAME_LEN		;30-CHAR NAMES
;	MOVE.W	#DIRSIZ/40,ENTRIES_PER_DIR ;??????????????
;	MOVE.W	ADosEntries,ENTRIES_PER_DIR
	CLR.W	ADOSDirCount		;count of names in dir
	TST.L	ADOSDirBuf
	BNE.S	5$
	MOVE.L	#ADOSDirSize,D0
	BSR	AlocBuf
	MOVE.L	D0,ADOSDirBuf
	BEQ	BAD_DIR			;no memory for buffer...bail out
5$:	MOVE.L	ADOSDirBuf,A0
	MOVE.L	A0,DirPtr		;INIT PTR TO TOP OF BUFFER
	CLR.L	(A0)			;MARK FIRST ENTRY AS EMPTY
	MOVE.	A.,PATH.
	IFNZ	PATH.,4$		;ALREADY HAVE PATH
	BSR	BUILD_AD_PATH		;ELSE BUILD IT NOW
	ERROR	9$
4$:	MOVE.L	DosBase,A6
	STG_Z.	A.			;CONVERT TO NULL-TERM STRING
	MOVE.L	#A.,D1
	MOVEQ	#-2,D2			;ACCESS-READ
	CALLSYS	Lock			;GET DIRECTORY
	MOVE.L	D0,LOCK
	BEQ	BAD_DIR			;CANT FIND THAT DIRECTORY
	MOVE.L	LOCK,D1
	MOVE.L	#FILE_INFO,D2
	CALLSYS	Examine
	TST.L	D0
	BEQ	BAD_DIR			;DIDN'T FIND DIRECTORY
	MOVE.L	FIB_TYPE,D0
	BMI	BAD_DIR			;GOT A FILE, NOT A DIRECTORY
1$:	MOVE.L	LOCK,D1
	MOVE.L	#FILE_INFO,D2
	CALLSYS	ExNext			;GET NEXT FILE IN DIRECTORY
	TST.L	D0			;END?
	BEQ.S	2$			;GOT THEM ALL...NOW SORT
	MOVE.L	FIB_TYPE,D0
	BMI.S	3$			;NORMAL FILE...DONT FIX SIZE
	MOVE.L	#-1,FIB_SIZE		;ELSE SHOW DIRECTORY BY FILE SIZE
3$:	BSR	COPY_FIB_DIR		;COPY FIB ENTRY TO DIR BUFFER
	BRA.S	1$
2$:	MOVE.L	ADOSDirBuf,A0
	MOVE.W	ADOSDirCount,D0
	BSR	SORT_DIR		;SORT THE DIRECTORY
	BSR	DISP_AD_DIR		;AND DISPLAY IT
	MOVE.L	LOCK,D1
	MOVE.L	DosBase,A6
	CALLSYS	UnLock			;UNLOCK DIRECTORY
9$:	RTS

BAD_DIR:
	DISP.	BAD_DIR.
	STC
	RTS

* EXPANDS A. FROM X.Y FORMAT WITH WILD CARDS TO 11-CHAR X??????????
* FORMAT FOR DIRECTORY SCANS.

EXPAND_MD_WILD:
	MOVE.	A.,TMP.			;COPY TO TEMP, THEN MOVE BACK
	STG_Z.	TMP.			;NULL TERMINATE FOR CONVENIENCE
	MOVE.L	#TMP.,A0
	MOVE.L	#A.,A1
	MOVE.B	#11,(A1)+		;11-BYTE RESULT
	MOVEQ	#7,D1			;8-BYTE NAME FIELD
1$:	MOVE.B	#32,D2			;FILL WITH BLANKS IF SHORTER THAN 8
	MOVE.B	(A0)+,D0		;GET A CHAR OF NAME
	BEQ.S	4$			;END OF NAME FIELD WITHOUT '.TYP'
	CMP.B	#'.',D0			;GOT A TYP?
	BEQ.S	5$			;YES
	MOVE.B	#'?',D2			;FILL WITH ? FOR WILD CARDS
	CMP.B	#'*',D0			;WILD CARD?
	BEQ.S	5$			;YES...FILL WITH '?'
	MOVE.B	D0,(A1)+		;ELSE STORE THE CHAR
	DBF	D1,1$
	BRA.S	6$
4$:	DECL	A0			;BACKUP PTR TO NULL
5$:	MOVE.B	D2,(A1)+		;STORE FILL CHAR
	DBF	D1,5$			;FOR REMAINDER OF 8-CHAR NAME
6$:	MOVEQ	#2,D1			;3-CHAR TYP
7$:	MOVE.B	#32,D2			;FILL WITH BLANKS IF SHORTER THAN 3
	MOVE.B	(A0)+,D0		;GET CHAR
	BEQ.S	8$			;END...FILL TO 11 CHARS
	CMP.B	#'.',D0			;'.'?
	BEQ	7$			;YES...IGNORE IT
	MOVE.B	#'?',D2			;FOR WILD CARD FILL
	CMP.B	#'*',D0			;WILD?
	BEQ.S	8$			;YES
	MOVE.B	D0,(A1)+		;ELSE STORE CHAR
	DBF	D1,7$			;AND LOOP
	RTS				;DONE
8$:	MOVE.B	D2,(A1)+		;STORE FILL CHAR
	DBF	D1,8$
	RTS

* CHANGE AMIGA-DOS DIRECTORY.

CHANGE_AD_DIR:
	IFNZ	A.,CHG1			;HAVE PATH ALREADY
	BSR	BUILD_AD_PATH
	RTSERR				;BAD DIR...DONT DISPLAY
	DISP.	PATH.
	RTS

CHG1:	STG_Z.	A.			;MAKE NULL-TERM STRING
	MOVE.L	#A.,D1
	MOVEQ	#-2,D2			;ACCESS_READ
	CALLSYS	Lock,DosBase		;TRY TO FIND THE DIRECTORY
	MOVE.L	D0,LOCK
	BEQ	BAD_DIR			;CANT GET A LOCK ON IT
	MOVE.L	#FILE_INFO,D2
	CALLSYS	Examine			;MAKE SURE IT IS A DIRECTORY
	TST.L	D0
	BEQ	BAD_DIR			;DIDN'T FIND IT
	MOVE.L	FIB_TYPE,D0
	BMI	BAD_DIR			;NOT A DIRECTORY
	MOVE.L	LOCK,D1
	CALLSYS	CurrentDir		;MAKE IT CURRENT DIR
	TST.L	OriginalDir
	BNE.S	1$
	MOVE.L	D0,OriginalDir		;save original dir for exit
	RTS
1$:	MOVE.L	D0,D1
	CALLSYS	UnLock			;NOW UNLOCK IT
	RTS

* BUILDS AMIGADOS PATH TO CURRENT DIRECTORY IN PATH.

BUILD_AD_PATH:
	CLR.B	A.			;START WITH NULL STRING
	MOVE.L	DosBase,A6
	MOVE.L	#A.,D1
	MOVEQ	#-2,D2			;READ ACCESS
	CALLSYS	Lock			;GET LOCK ON CURRENT DIR
	TST.L	D0
	BEQ	BAD_DIR			;NO LOCK ON CURRENT DIR
	CLR.B	PATH.
1$:	MOVE.L	D0,LOCK			;SAVE NEW LOCK
	MOVE.L	D0,D1
	MOVE.L	#FILE_INFO,D2
	CALLSYS	Examine			;EXAMINE THE DIRECTORY
	TST.L	D0
	BEQ	BAD_DIR			;PROBLEM
	Z_STG.	FIB_NAME,TMP.		;ADD PATH TO TMP.
	IFZ	PATH.,3$		;NO PATH IN PLACE
	ACHAR.	#'/',TMP.
	APPEND. PATH.,TMP.
3$:	MOVE.	TMP.,PATH.
	MOVE.L	LOCK,D1			;IN ROOT YET?
	BEQ.S	2$			;YES
	CALLSYS	ParentDir 		;NO...GET PARENT DIR
	TST.L	D0			;GOT A VALID LOCK?
	BNE.S	1$			;YES...GO AGAIN
	LEA	PATH.,A0		;SCAN FIRST "/"
	MOVE.B	(A0)+,D0		;NUMBER OF CHARS TO SCAN
	BEQ.S	2$			;NOTHING...LET IT GO AS IS
	DECW	D0
4$:	CMP.B	#'/',(A0)+		;FIRST "/"?
	BEQ.S	5$			;NO
	DBF	D0,4$
	BRA.S	2$			;DIDN'T FIND A '/'
5$:	MOVE.B	#':',-(A0)		;ELSE REPLACE '/' WITH ':'
2$:	IFNZ	PATH.,6$		;GOT SOME KIND OF NAME
	MOVE.	RAM.,PATH.		;ELSE TREAT AS RAM:
6$:	MOVE.L	LOCK,D1
	CALLSYS	UnLock			;RELEASE LOCK
	RTS

* COPIES AD FILE NAME INTO DIRECTORY, ALONG WITH SIZE AND DATE/TIME

COPY_FIB_DIR:
	MOVE.L	DirPtr,A1		;POINT TO THIS ENTRY
	MOVE.W	NAME_LEN,D0		;LENGTH TO MOVE
	DECB	D0
	LEA	FIB_NAME,A0		;START OF FILE NAME
1$:	MOVE.B	(A0)+,D1		;GET A BYTE
	BEQ	2$			;NULL...END OF NAME
	MOVE.B	D1,(A1)+		;INTO DIR BUFFER
	DBF	D0,1$			;LOOP FOR ALL OF NAME
	BRA.S	3$
2$:	MOVE.B	#' ',(A1)+		;FILL WITH BLANKS
	DBF	D0,2$
3$:	BSR	ConvADDateTime		;CONVERT AD DATE/TIME TO MS-DOS
	MOVE.W	FILE_TIME,(A1)+ 	;MOVE IN CONVERTED TIME
	MOVE.W	FILE_DATE,(A1)+ 	;DITTO DATE
	MOVE.L	FIB_BLKS,D0
	MOVE.W	D0,(A1)+		;BLOCKS ALLOCATED TO FILE
	MOVE.L	FIB_SIZE,(A1)+		;MOVE SIZE INTO LONG BOUNDARY
	CLR.L	(A1)			;ZAP NEXT ENTRY
	MOVE.L	A1,DirPtr		;NOW POINTS TO NEXT ENTRY
	ADDQ.W	#1,ADOSDirCount		;one more item in ADOS dir
	RTS

* BUILDS AND DISPLAYS AMIGA-DOS DIRECTORY

DISP_AD_DIR:
	CRLF.
	MOVE.	DIR_OF.,A.
	APPEND. PATH.,A.
	DISP.	A.
	CRLF.
	CLR.B	FILE_COUNT
	MOVE.L	ADOSDirBuf,A0
1$:	MOVE.B	(A0),D0			;ACTIVE ENTRY?
	BEQ	9$			;NO...DONE
	CMP.L	#-1,36(A0)		;directory?
	BEQ.S	2$			;yes...don't count it
	INCB	FILE_COUNT		;COUNT THE FILE
2$:	MOVE.L	36(A0),FILE_SIZE	;GET BINARY SIZE
	MOVE.W	30(A0),FILE_TIME
	MOVE.W	32(A0),FILE_DATE
	PUSH	A0			;SAVE POINTER
	MOVE.W	#30,D0
	LEA	A.,A1			;BUILD NAME HERE
	MOVE.B	D0,(A1)+		;STORE LENGTH
	JSR	MOVE_CHARS
	BSR	BLD_SIZE_DATE_TIME
	DISP.	A.			;DISPLAY AD DIR ENTRY
	POP	A0
	ADD.L	ENTRY_LEN,A0
	BRA	1$

9$:	BSR	CALC_AD_FREE_SPACE
	BSR	DISP_FREE_SPACE
	RTS

* APPENDS FILE SIZE, DATE, AND TIME TO DIRECTORY ENTRY LINE.  IF DIR ENTRY,
* PUTS <DIR> IN PLACE OF SIZE.  (DIR ENTRY SIZE = -1).

BLD_SIZE_DATE_TIME:
	APPEND. SPACES.,A.
	MOVE.L	FILE_SIZE,D0
	CMP.L	#-1,D0			;DIRECTORY?
	BNE	1$			;NO
	APPEND. DIR.,A.
	BRA.S	2$
1$:	STR.	L,FILE_SIZE,TMP.,#32	;SIZE TO STRING
	APPEND. TMP.,A.
2$:	APPEND. SPACES.,A.
	BSR	DATE_TIME
	APPEND. TMP.,A.
	RTS

* DISPLAYS THE SORTED NAMES IN THE DIRECTORY BUFFER.

DISP_DIR:
	CMP.B	#1,TMP_PATH.
	BEQ.S	3$			;LEN=1, DONT DEL CHAR
	LEA	TMP_PATH.,A0
	ZAP	D0
	MOVE.B	(A0),D0
	ADD.L	D0,A0			;POINT TO LAST CHAR
	CMP.B	#'\',(A0)		;TRAILING '\'?
	BNE	3$			;NO
	DECB	TMP_PATH.		;ELSE GET RID OF TRAILING '\'
3$:	CRLF.
	MOVE.	DIR_OF.,A.		;BUILD DIR TITLE
	APPEND. MD_DRV.,A.
	APPEND. TMP_PATH.,A.
	DISP.	A.
	CRLF.
	CLR.B	FILE_COUNT		;COUNT OF FILES IN DIRECTORY
	MOVE.L	DirectoryBuf,DirPtr		;BASE OF DIRECTORY BUFFER
1$:	MOVE.L	DirPtr,A0
	MOVE.B	(A0),D0			;ACTIVE ENTRY?
	BEQ	9$			;NO...DONE
	CMPI.B	#$E5,D0			;DELETED FILE
	BEQ	8$			;YES
	MOVE.B	ms_Attrib(A0),D0	;GET ATTRIBUTE BYTE
	ANDI.B	#$1E,D0			;SUBDIR, VOL LABEL, HIDDEN, OR SYS?
	BEQ.S	2$			;NO...USE IT
	BTST	#4,D0			;SUBDIR?
	BEQ	8$			;NO...IGNORE FILE
	MOVE.L	#-1,ms_FileSize(A0)	;SIGNAL USING FILE SIZE
	BRA.S	22$
2$:	INCB	FILE_COUNT		;count files only
22$:	PUSH	A0			;SAVE DIR POINTER
	BSR	CalcMSFileSize		;CORRECT ORDER OF BYTES
	MOVE.W	ms_Time(A0),D0
	SWAB	D0
	MOVE.W	D0,FILE_TIME
	MOVE.W	ms_Date(A0),D0
	SWAB	D0
	MOVE.W	D0,FILE_DATE
	CLR.B	A.			;start with empty string
	MOVEQ	#8,D0
	BSR	MoveUpToLimit		;move, cleanup and append filename
	MOVE.L	DirPtr,A0
	LEA	ms_Ext(A0),A0		;point to ext
	CMP.B	#' ',(A0)		;null ext?
	BEQ.S	4$			;yes
	PUSH	A0
	ACHAR.	#'.',A.			;else add 'dot'
	POP	A0
	MOVEQ	#3,D0
	BSR	MoveUpToLimit		;move, cleanup and append ext
4$:	CMP.B	#14,A.			;long enough?
	BEQ.S	5$			;yes
	ACHAR.	#32,A.			;else add a blank
	BRA.S	4$

;	MOVE.L	#A.,A1			;BUILD NAME IN A.
;	MOVE.B	#12,(A1)+		;11-CHAR NAME PLUS BLANK
;	MOVEQ	#8,D0			;8-CHAR NAME
;	JSR	MOVE_CHARS		;MOVE NAME IN
;	MOVE.B	#32,(A1)+		;NOW A BLANK
;	MOVEQ	#3,D0
;	JSR	MOVE_CHARS		;ADD FILE TYPE
;	APPEND. SPACES.,A.

5$:	BSR	BLD_SIZE_DATE_TIME
	DISP.	A.			;DISPLAY THE ENTRY
	POP	A0
8$:	ADD.L	#32,DirPtr		;POINT TO NEXT DIRECTORY ENTRY
	BRA	1$			;LOOP FOR ALL VALID NAMES

9$:	BSR	CALC_FREE_SPACE 	;CALCULATE DISK FREE SPACE
	BSR	DISP_FREE_SPACE
	RTS

* Copies up to D0 chars from A0 to TMP., truncates, and appends to A.

MoveUpToLimit:
	LEA	TMP.,A1			;build in TMP.
	MOVE.B	D0,(A1)+		;move this many
	DECW	D0
1$:	MOVE.B	(A0)+,(A1)+
	DBF	D0,1$			;loop
	STRIP_TB. TMP.			;get rid of trailing chars
	APPEND.	TMP.,A.			;add to A.
	RTS

DISP_FREE_SPACE:
	STRING. #32,#2,A.		;PUT IN LEADING BLANKS
	STR.	B,FILE_COUNT,TMP.,#32
	APPEND. TMP.,A.
	APPEND. FILES.,A.
	STR.	L,DISK_FREE,TMP.,#32
	APPEND. TMP.,A.
	APPEND. BYTES.,A.
	DISP.	A.
	RTS

* LOGS IN THE MS-DOS DISK, AND GETS READY TO ACCESS FILES.

DISK_LOG:
	JSR	DISK_CAL		;RESET DRIVE TO TRACK 0
	RTSERR
	BSR	VerifyFormat		;check format of this disk
	RTSERR
	BSR	READ_FAT		;GET FAT
	RTSERR
	BSR	READ_DIR		;READ THE ROOT DIRECTORY
	RTS

* Checks the format of the MS-DOS or ATARI disk, and sets up parameters.

VerifyFormat:
	ZAP	D0
	MOVE.L	D0,PartitionOffset	;partition offset
	MOVE.B	D0,DOUBLE_STEP		;no double-stepping
	MOVE.B	D0,ATARI_FLAG		;not Atari format disk
	MOVE.B	D0,BigFAT		;assume 12-bit FAT
	MOVE.L	BootBuf,A0
	JSR	READ_SECTOR		;read boot block
	RTSERR				;problems...bad format??
	BSR	ProcessBootBlock	;check for boot block and grab params
	NOERROR	2$
1$:	IFZ	NotFlop,3$		;it is a floppy...try to find fat

* if we get here, we think it is an MSDOS volume.  Look for a partition table

	MOVEQ	#9,D3			;try first 10 blocks...arbitrary
	ZAP	D2
	BRA.S	4$
5$:	INCL	D2
	MOVE.L	D2,D0
	MOVE.L	BootBuf,A0
	JSR	READ_SECTOR
	RTSERR
4$:	MOVE.L	BootBuf,A0
	CMP.W	#$55AA,510(A0)		;MSDOS partition table signature?
	BEQ.S	6$			;yeah!  
	DBF	D3,5$
	BRA	8$			;this isn;t an MSDOS volume
6$:	ZAP	D2
	MOVE.L	BootBuf,A0
;	LEA	$1BE(A0),A0		;point to starting sector #
	ADD.L	#223,A0
	ADD.L	#225,A0
	BSR	NextWord
	MOVE.W	D0,D2
	MOVE.B	(A0)+,D0		;get partition type
	CMP.B	#1,D0			;12-bit fat?
	BEQ.S	7$			;YES
	CMP.B	#4,D0
	BNE	8$			;no...not a partition type we support
	SETF	BigFAT
7$:	ADDQ.L	#3,A0			;point to partition offset
	BSR	NextLong		;get MSDOS 32-bit param
	ADD.L	D2,D0			;add starting sector to relative offset
	MOVE.L	D0,PartitionOffset
	ZAP	D0			;now read REAL bootblock from partition
	MOVE.L	BootBuf,A0
	JSR	READ_SECTOR
	RTSERR
	BSR	ProcessBootBlock	;it is valid?
	ERROR	8$			;no...
	BRA	2$			;okay...found that sucker	

* if we got here, boot block doesn't have proper data...try for FAT in
* block 1 and go from there...(disks prior to MSDOS 2.0).

3$:	MOVEQ	#1,D0
	MOVE.L	BootBuf,A0
	JSR	READ_SECTOR		;read first FAT sector
	RTSERR				;too bad...can't read it
	MOVE.L	BootBuf,A0
	MOVE.B	(A0),DISK_TYPE		;format byte
	BSR	SET_DRIVE_PARAMS	;load proper drive params	
	NOERROR	2$
8$:	DISP.	BadFormat.		;not proper MS-DOS/Atari format
	STC
	RTS

2$:	BSR	CalcParams
	BSR	AllocMSDOSBufs		;allocate MSDOS dynamic buffers

* Some Amiga hackers have adapted 80-track 5.25-inch disk drives to the
* Amiga.  Such drives are designed to appear to AmigaDOS as 3.5-inch 880KB
* drives, and can be read and written directly by AmigaDOS.  These drives
* can also be used by Dos-2-Dos to read and write 80-track or 40-track
* 5.25-inch diskettes.  In order for these drives to work correctly with
* 40-track diskettes, Dos-2-Dos must issue double-step commands to the
* drive.  This conflicts with 3.5-inch drives reading 360KB 3.5-inch floppy
* disks, such as those produced by Transformer and some lap portable
* computers.  Dos-2-Dos cannot tell the difference between an 80-track
* 5.25-inch drive and a normal 80-track 3.5-inch drive.  For this reason, we
* have placed two different versions of Dos-2-Dos on the distribution disk. 
* The normal version is named Dos-2-Dos and also D2D.  It NEVER double-steps
* ANY drive.  The special 80-track version, called D2D80, double-steps an
* 80-track drive if the diskette boot block indicates 40-track media.  

;	BRA.S	19$			;comment this line out for normal, in for D2D80
	IFZ	IS_3.5,19$		;NOT 3.5-INCH DRIVE OR LOOKALIKE
	MOVE.B	DISK_TYPE,D0
	CMP.B	#$FF,D0			;IS IT D-8?
	BEQ.S	18$			;NO
	CMP.B	#$FE,D0			;IS IT S-8?
	BEQ.S	18$
	CMP.B	#$FD,D0			;IS IT D-9?
	BEQ.S	18$
	CMP.B	#$FC,D0			;IS IT S-9?
	BNE.S	19$
18$:	SETF	DOUBLE_STEP		;TREAT 3.5" DRIVE AS 40-TRACK DEVICE
19$:	CLC
	RTS

* Checks for valid boot block and extracts params.

ProcessBootBlock:
	MOVE.L	BootBuf,A0
	ADD.L	#11,A0			;lets see what we have here...
	BSR	NextWord
	CMP.W	#SectorSize,D0
	BEQ.S	1$			;looks like a valid boot block...
	STC
	RTS
1$:	MOVE.B	(A0)+,D0
	EXT.W	D0
	MOVE.W	D0,SEC_PER_CLUSTER
	BSR	NextWord		;reserved sectors (inc boot block)
	MOVE.W	D0,SEC_RESERVED		;this is where the FAT starts
	MOVE.B	(A0)+,D0
	EXT.W	D0
	MOVE.W	D0,NumberOfFATS		;number of FATS on disk
	BSR	NextWord		;number of dir entries in root
	MOVE.W	D0,ENTRIES_PER_DIR
	BSR	NextWord		;total sectors per volume
	MOVE.W	D0,TotalSectors
	MOVE.B	(A0)+,DISK_TYPE		;disk format code
	BSR	NextWord		;sectors per FAT
	MOVE.W	D0,SEC_PER_FAT
	BSR	NextWord		;sectors per track
	MOVE.W	D0,SEC_PER_TRACK
	MOVE.L	D0,D1
	BSR	NextWord		;sides per disk
	MOVE.W	D0,SIDES_PER_DISK
	MULU	D0,D1			;calc sectors per cyl
	MOVE.W	D1,SEC_PER_CYL
	ZAP	D0
	MOVE.W	TotalSectors,D0
	DIVU	D1,D0
	MOVE.W	D0,CYLS_PER_DISK
	BSR	NextWord		;hidden sectors
	MOVE.W	D0,SEC_HIDDEN
	RTS

* Calculates other drive params

CalcParams:
	MOVE.W	ENTRIES_PER_DIR,D0
	LSR.W	#4,D0			;divide by 16 (512/32) to get secs/dir
	MOVE.W	D0,SEC_PER_DIR
;	MULU	#SectorSize,D0
;	MOVE.L	DirectoryBuf,A1
;	ADD.L	D0,A1
;	MOVE.L	A1,DirBufEnd
	MOVE.W	#SectorSize,D1
;	MOVE.W	SEC_PER_DIR,D0
;	MULU	D1,D0
;	MOVE.L	D0,DirBufSize
;	DIVU	#40,D0
;	MOVE.W	D0,ADosEntries		;max ados entries in DirectoryBuf
	MOVE.W	SEC_PER_FAT,D0
	MULU	D1,D0
	MOVE.L	D0,FATBufSize
	MOVE.W	TotalSectors,D3
	SUB.W	SEC_PER_DIR,D3
	MOVE.W	SEC_PER_FAT,D0
	MULU	NumberOfFATS,D0
	SUB.W	D0,D3
	MOVE.W	SEC_RESERVED,D2
	SUB.W	D2,D3			;account for reserved sectors
	DIVU	SEC_PER_CLUSTER,D3
	INCW	D3			;always add 1...magic
	MOVE.W	D3,MaxCluster		;max cluster number
	CMP.W	#4080,D3		;using 16-bit FAT? (Norton, pg.121)
	BLS.S	1$			;no
	SETF	BigFAT			;else show 16-bit FAT
1$:	ADD.W	D2,D0			;this is where DIR starts
	MOVE.W	D0,DirSector
	ADD.W	SEC_PER_DIR,D0		;size of dir
	MOVE.W	D0,DataSector		;logical sector for cluster 2
	MOVE.W	SEC_PER_CLUSTER,D0
	MULU	#SectorSize,D0
	MOVE.L	D0,ClusterSize
	RTS

* SETS UP DISK DRIVE PARAMETERS BASED ON DRIVE TYPE CODE IN DISK_TYPE
* ($F9, $FC TO $FF).

SET_DRIVE_PARAMS:
	ZAP	D0
	MOVE.B	DISK_TYPE,D0		;GET DRIVE TYPE CODE
	IFZ	ATARI_FLAG,3$		;not ATARI
	AND.B	#$F,D0			;else MAKE INTO SPECIAL CODE
3$:	LEA	TYPE_TBL,A1
	MOVEQ	#DISK_FORMATS-1,D1 	;NUMBER OF FORMATS IN TABLE
2$:	CMP.W	(A1)+,D0		;MATCH?
	BEQ.S	1$			;YES
	ADD.L	#TYPE_LEN-2,A1		;ELSE TRY NEXT ENTRY
	DBF	D1,2$			;LOOP
8$:	STC				;NO MATCH...IMPROPER DISK FORMAT
	RTS
1$:	MOVE.W	(A1)+,SIDES_PER_DISK	;NUMBER OF SIDES
	MOVE.W	(A1)+,SEC_PER_TRACK
	MOVE.W	(A1)+,SEC_PER_FAT
	MOVE.W	(A1)+,SEC_PER_DIR
	MOVE.W	(A1)+,SEC_PER_CLUSTER
	MOVE.W	(A1)+,SEC_PER_CYL
	MOVE.W	(A1)+,TotalSectors
	MOVE.W	(A1)+,CYLS_PER_DISK
	MOVE.W	SEC_PER_DIR,D0
	LSL	#4,D0			;*512/32=NUMBER OF DIRECTORY ENTRIES
	MOVE.W	D0,ENTRIES_PER_DIR
	MOVE.W	#1,SEC_RESERVED		;FAT starts at 1 on floppy
	MOVE.W	#2,NumberOfFATS		;floppies always have 2 FATS
	CLC
	RTS

NextLong:
