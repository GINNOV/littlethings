* Get a word from buffer and swap bytes to Motorola format

NextWord:
	CLR.W	D0
	MOVE.B	(A0)+,D0		;low byte first (Intel)
	SWAB	D0
	MOVE.B	(A0)+,D0		;then high byte
	SWAB	D0
	RTS


READ_DIR:
	ZAP	D0
	MOVE.W	DirSector,D0		;Dir starts here
	MOVE.L	DirectoryBuf,A0		;DIRECTORY BUFFER
	MOVE.W	SEC_PER_DIR,D1		;NUMBER OF SECTORS TO READ
	JSR	READ_N			;READ THE ROOT DIRECTORY INTO BUFFER
	RTS

WRITE_DIR:
	TST.W	FirstSubClus		;WRITING TO SUBDIR?
	BNE.S	1$			;YES
	ZAP	D0
	MOVE.W	DirSector,D0		;store DIR here
	MOVE.L	DirectoryBuf,A0		;DIRECTORY BUFFER
	MOVE.W	SEC_PER_DIR,D1		;NUMBER OF SECTORS TO READ
	JSR	WRITE_N			;WRITE THE ROOT DIRECTORY INTO BUFFER
	RTS
1$:	MOVE.W	FirstSubClus,CLUSTER	;SUBDIR MUST ALREADY EXIST
	MOVE.L	DirectoryBuf,BUFPTR	;WRITE OUT OF DirectoryBuf
2$:	MOVE.L	BUFPTR,A0
	MOVE.W	CLUSTER,D0		;USE CLUSTERS ALREADY ALLOCATED
	CMP.W	#$FFFF,D0		;END OF SUBDIR?
	BEQ.S	4$			;YES...ALL DONE
	BSR	CLUSTER_TO_SEC		;CONVERT TO LOGICAL SECTOR
	MOVE.W	SEC_PER_CLUSTER,D1
	JSR	WRITE_N			;WRITE DIR CLUSTER
	ERROR	4$
;	ZAP	D0
	MOVE.L	ClusterSize,D0
	ADD.L	D0,BUFPTR		;ADV TO NEXT CLUS
	MOVE.W	CLUSTER,D0
	BSR	GET_FAT			;GET NEXT ENTRY
	MOVE.W	D0,CLUSTER		;SAVE FOR NEXT LOOP
	BRA.S	2$
4$:	RTS

* TRIES TO FIND AND READ A SUBDIRECTORY, DEFINED BY NAME IN A.
* (SUBDIR HAS NO FILE SIZE).

READ_SUBDIR:
	BSR	EXPAND_MD_WILD		;MAKE INTO MS-DOS NAME FORMAT
	BSR	FIND_FIRST		;SEE IF IN THIS DIRECTORY
	ERROR	9$			;NO
	MOVE.L	DirPtr,A0		;POINT TO ENTRY
	BTST	#4,ms_Attrib(A0)	;IS IT A SUBDIR?
	BEQ	9$			;NO...TREAT AS ERROR
	BSR	OPEN_FILE		;GET READY TO READ
	MOVE.W	CLUSTER,FirstSubClus	;SAVE STARTING CLUSTER
	MOVE.L	DirectoryBuf,DirPtr	;RESET DIRECTORY POINTER
1$:	MOVE.W	CLUSTER,D0
	CMP.W	#$FFFF,D0		;END OF FILE?
	BEQ.S	2$			;YES...DONE
	MOVE.W	D0,LastSubClus		;may be last cluster of subdir
	BSR	READ_CLUSTER		;READ FULL CLUSTER.
	ERROR	9$			;READ ERROR
	MOVE.L	ClusterSize,D0		;CLUSTER SIZE
	MOVE.L	ClusterBuf,A0		;MOVE FROM CLUSTER BUFFER...
	MOVE.L	DirPtr,A1		;...INTO DIRECTORY BUFFER
	JSR	MOVE_CHARS		;MOVE IT
	MOVE.L	A1,DirPtr		;SAVE POINTER
	MOVE.L	A1,D0
	CMP.L	DirBufEnd,D0		;PAST END OF DirectoryBuf?
	BCS.S	1$			;NO, READ ANOTHER CLUSTER
2$:	MOVE.L	DirPtr,D0
	SUB.L	DirectoryBuf,D0
	LSR.L	#5,D0			;CALC NUMBER OF ENTRIES IN DIRECTORY
	MOVE.W	D0,ENTRIES_PER_DIR
	CLC
	RTS
9$:	STC
	RTS

* READS FAT #1 (ONLY) FROM DISK AND DECIDES WHAT FORMAT THE DISK REALLY IS.

READ_FAT:
	MOVE.W	SEC_RESERVED,D0
	MOVE.L	FATBuf,A0		;READ INTO FAT BUFFER
	ZAP	D1
	MOVE.W	SEC_PER_FAT,D1		;SIZE of FAT
	JSR	READ_N			;READ FAT
	RTS

WRITE_FAT:
	MOVE.L	FATBuf,A0
	MOVE.W	SEC_RESERVED,D0	
	ZAP	D1
	MOVE.W	SEC_PER_FAT,D1		;NUMBER OF SECTORS IN FAT
	PUSH	A0/D0-D1		;SAVE PARAMS
	JSR	WRITE_N			;WRITE OUT FAT ONCE
	POP	A0/D0-D1
	RTSERR
	ADD.W	D1,D0			;POINT TO SECTOR FOR 2ND FAT
	JSR	WRITE_N
	RTS

* MAKES ONE PASS THROUGH THE ENTIRE DIRECTORY, USING A SLOW, RELIABLE
* BUBBLE SORT.  LENGTH OF ENTRY IN ENTRY_LEN, LENGTH OF NAME IN NAME_LEN.
* Buffer containing list to be sorted in A0, count of entries in D0.

SORT_DIR:
	PUSH	D2/A2
	MOVE.L	A0,A2			;save ptr to base of list
	MOVE.W	D0,D2			;save count of entries to sort
2$:	MOVE.L	A2,A0			;START AT TOP OF DIRECTORY-1ST ENTRY
	MOVE.L	A0,A1
	ADD.L	ENTRY_LEN,A1		;POINT TO NEXT ENTRY
	MOVE.W	D2,D0		 	;max number of entries in DIR
	CLR.B	SWAP_FLAG
	DECW	D0
1$:	TST.B	(A0)			;CHECK FOR END OF DIRECTORY
	BEQ.S	3$			;FOUND IT...DONT SWAP
	TST.B	(A1)			;ALSO FOR COMPARISON
	BEQ.S	3$
	BSR.S	COMPARE_SWAP		;COMPARE ONE PAIR OF FILE NAMES
	ADDA.L	ENTRY_LEN,A0
	ADDA.L	ENTRY_LEN,A1		;ADVANCE TO NEXT PAIR
	DBF	D0,1$			;LOOP THROUGH ENTIRE DIRECTORY
3$:	TST.B	SWAP_FLAG		;ANYTHING MOVE?
	BNE.S	2$			;YES...GO AGAIN
	POP	D2/A2
	RTS

* COMPARES FILE NAMES POINTED TO BY A0 AND A1.  IF THEY MATCH, NOP.  IF NOT
* SWAPS THEM INTO PROPER ORDER AND SETS SWAP_FLAG.

COMPARE_SWAP:
	PUSH	A0-A1/D0-D2		;SAVE POINTERS
	MOVE.W	NAME_LEN,D0		;11-BYTE OR 30-BYTE FILENAMES
	DECB	D0
1$:	MOVE.B	(A0)+,D1		;GET A NAME BYTE
	CMP.B	#$61,D1			;LOWER CASE?
	BCS.S	6$			;NO
	AND.B	#$5F,D1			;COMPARE ONLY UPPER CASE
6$:	MOVE.B	(A1)+,D2		;GET OTHER BYTE
	CMP.B	#$61,D2			;LOWER CASE?
	BCS.S	7$			;NO
	AND.B	#$5F,D2			;YES
7$:	CMP.B	D2,D1			;SAME?
	BEQ.S	2$			;YES...TRY NEXT PAIR
	BCS.S	3$			;ORDER OK...DONT SWAP
	BRA	4$			;SWAP THE NAMES...OUT OF ORDER
2$:	DBF	D0,1$			;LOOP FOR ALL OF NAMES
	BRA	3$			;NAMES SAME...DONT SWAP
4$:	SETF	SWAP_FLAG		;SHOW AT LEAST ONE SWAP
	POP	A0-A1/D0-D2		;RESTORE POINTERS
	PUSH	A0-A1/D0-D2
	MOVE.L	ENTRY_LEN,D0		;LENGTH OF DIR ENTRIES
	DECB	D0
5$:	MOVE.B	(A0),D1			;GET A BYTE OF FIRST
	MOVE.B	(A1),(A0)+		;REPLACE WITH BYTE OF SECOND
	MOVE.B	D1,(A1)+		;AND STORE SECOND WITH BYTE OF FIRST
	DBF	D0,5$			;LOOP FOR ALL OF ENTRY
3$:	POP	A0-A1/D0-D2
	RTS

* BUILDS DATE-TIME STRING IN TMP. FROM MS-DOS FILE DATE/TIME PARAMETERS.

DATE_TIME:
	MOVE.W	FILE_DATE,D5		;GET DATE STAMP
	MOVE.L	D5,D0
	LSR	#5,D0			;GET MONTH
	AND.L	#$F,D0
	STR2.	DT.,#32			;CONVERT TO 2 ASCII CHARS
	LEA	DT.,A0
	LEA	TMP.,A1
	MOVE.	A0,A1
;	MOVE.	DT.,TMP.
	ACHAR.	#'-',TMP.		;'-'
	MOVE.L	D5,D0
	AND.L	#$1F,D0			;GET DAY
	STR2.	DT.,#'0'		;CONVERT TO 2 CHARS, 0-FILL
	APPEND. DT.,TMP.
	ACHAR.	#'-',TMP.
	MOVE.L	D5,D0			;GET YEAR
	LSR	#8,D0
	LSR	#1,D0
	ADD	#80,D0			;ADJUST FOR 1980
4$:	CMP.W	#100,D0			;=> YEAR 2000?
	BCS.S	3$			;NO
	SUB.W	#100,D0			;ELSE CORRECT TO PROPER RANGE
	BRA.S	4$			;BUT FIRST, CHECK AGAIN
3$:	STR2.	DT.,#'0'
	APPEND. DT.,TMP.
	APPEND. SPACES.,TMP.		;SPACE BEFORE TIME
	MOVE.W	FILE_TIME,D5		;GET TIME STAMP
	MOVE.L	D5,D0
	LSR	#8,D0
	LSR	#3,D0			;GET HOURS
	MOVE.B	#'a',D4			;ASSUME AM
	CMP.B	#12,D0			;IS IT?
	BCS	1$			;YES
	MOVE.B	#'p',D4			;ELSE MAKE IT PM
	SUB.B	#12,D0			;AND ADJUST FOR 12-HOUR CLOCK
1$:	TST.B	D0			;12AM?
	BNE.S	2$			;NO...NO CORRECTION NEEDED
	MOVE.B	#12,D0			;ELSE MAKE IT 12
2$:	STR2.	DT.,#32			;2-CHAR HOUR, BLANK FILL
	APPEND. DT.,TMP.
	ACHAR.	#':',TMP.
	MOVE.L	D5,D0
	LSR	#5,D0			;FORGET SECONDS
	AND	#$3F,D0			;GET MINUTES
	STR2.	DT.,#'0'		;2-CHARS, 0-FILL
	APPEND. DT.,TMP.
	ACHAR.	D4,TMP.			;AM OR PM
	RTS

* CALCULATES MS-DOS DATE/TIME PARAMS FROM AMIGA-DOS FILE_INFO BLOCK.
* FROM EDN OCT 17, 1985 P. 168

ConvADDateTime:
	MOVE.L	FIB_DAYS,D0		;days since January 1, 1978
	ADDI.L	#MagicNumber,D0		;days since March 1, 1900
	MULU	#4,D0
	SUBQ.L	#1,D0			;K2=4*K-1
	MOVE.L	D0,D2
	DIVU	#1461,D2		;Y=INT(K2/1461)
	MOVE.L	D2,D1
	SWAP	D1			;D=INT (K2 MOD 1461)
	ADDQ.W	#4,D1
	LSR.W	#2,D1			;D=INT ((D+4)/4)
	MULU	#5,D1
	SUBQ.L	#3,D1
	DIVU	#153,D1			;M=INT ((5*D-3)/153)
	MOVE.W	D1,D0
	SWAP	D1
	EXT.L	D1			;D=INT ((5*D-3) MOD 153)
	ADDQ.L	#5,D1
	DIVU	#5,D1			;D=INT ((D+5)/5)
	CMPI.W	#10,D0
	BLT.S	1$
	SUBI.W	#9,D0			;M=M-9
	ADDQ.W	#1,D2			;Y=Y+1
	BRA.S	2$
1$:	ADDQ.W	#3,D0
2$:	SUB.W	#80,D2			;ADJUST FOR MS-DOS BASE OF 1980
	SWAB	D2
	LSL.W	#1,D2
	LSL.W	#5,D0
	OR.W	D0,D2
	OR.W	D1,D2			;NOW HAVE MS-DOS DATE
	MOVE.W	D2,FILE_DATE		;STORE IT
	MOVE.L	FIB_MIN,D0		;GET MINUTES OF DAY
	DIVU	#60,D0			;HOURS IN LOW WORD, MINS IN HIGH WORD
	SWAP	D0			;REVERSE POSITION OF RESULTS
	LSL.W	#8,D0			;MOVE MINUTES UP NEXT TO HOURS
	LSL.W	#2,D0
	LSR.L	#5,D0			;NOW MOVE WHOLE MESS TO PROPER PLACE
	MOVE.W	D0,FILE_TIME
	RTS

* CALCULATES AMOUNT OF FREE SPACE LEFT ON AMIGA-DOS DISK FROM INFO.

CALC_AD_FREE_SPACE:
	MOVE.L	DosBase,A6
	MOVE.L	LOCK,D1
	MOVE.L	#DISK_INFO,D2
	CALLSYS	Info			;GET DISK INFO BLOCK
	MOVE.L	DI_NBLKS,D0		;TOTAL BLOCKS
	SUB.L	DI_USED,D0		;MINUS NUMBER USED=FREE BLOCKS
	MOVE.L	DI_BYTES,D1
	MULU	D1,D0			;TIMES BYTES PER BLOCK
	MOVE.L	D0,DISK_FREE		;NUMBER OF FREE BYTES
	RTS

* CALCULATES AMOUNT OF FREE SPACE LEFT ON MS-DOS DISK FROM FAT.

CALC_FREE_SPACE:
	MOVE.W	MaxCluster,D1		;highest cluster number in FAT
	DECW	D1
	ZAP	D3
	MOVEQ	#1,D2			;START WITH CLUSTER #2
1$:	MOVE.L	D2,D0			;CLUSTER NUMBER TO D0
	BSR	GET_FAT			;GET FAT ENTRY FOR THIS CLUSTER
	TST.W	D0			;IS IT FREE?
	BNE	2$			;NO
	INCW	D3			;YES...COUNT IT
2$:	INCW	D2			;TRY NEXT CLUSTER
	DBF	D1,1$			;LOOP
	MOVE.W	SEC_PER_CLUSTER,D0
	CMP.B	#1,D0			;512 BYTES PER CLUSTER?
	BEQ	3$			;YES
	LSL.L	#1,D3			;NO...1024
3$:	LSL.L	#8,D3
	LSL.L	#1,D3			;FREE SPACE IN BYTES
	MOVE.L	D3,DISK_FREE
	RTS

* GIVEN THE CLUSTER NUMBER IN D0, RETURNS THE CORRESPONDING FAT ENTRY IN D0.

GET_FAT:
	PUSH	D1
	MOVE.L	FATBuf,A0		;BASE OF FAT
	IFZ	BigFAT,1$		;use 12-bit FAT
	MOVE.W	0(A0,D0.W),D0		;else index as 16-bit qty
	SWAB	D0			;reverse the bytes
	BRA	3$
1$:	MOVE.L	D0,D1			;SAVE CLUSTER NUMBER
	PUSH	D1			;SAVE FOR LATER TEST
	ADD.L	D1,D1			;*2
	ADD.L	D0,D1			;+1=3
	LSR.L	#1,D1			;DIVIDE BY 2
	MOVE.B	1(A0,D1.W),D0		;TRICKY SHIT HERE...REVERSE BYTES
	LSL.W	#8,D0			;MAKE ROOM FOR OTHER BYTE
	MOVE.B	0(A0,D1.W),D0		;12-BIT FAT ENTRY PLUS EXTRA 4
	POP	D1			;GET ORIGINAL CLUSTER NUMBER
	BTST	#0,D1			;EVEN? (BLESS YOU, PETER NORTON)
	BNE.S	2$			;NO...ODD
	AND	#$FFF,D0		;LOWER 12-BITS
	BRA.S	3$
2$:	LSR.W	#4,D0			;UPPER 12-BITS
3$:	POP	D1
	CMP.W	MaxCluster,D0		;IN RANGE?
	BHI.S	9$			;NO
	RTS
9$:	MOVE.W	#$FFFF,D0		;ELSE ASSUME EOF
	RTS

* PUTS NEW FAT DATA IN D1 INTO FAT ENTRY FOR CLUSTER NUMBER IN D0.

PUT_FAT:
	PUSH	D2-D3/A0
	MOVE.L	FATBuf,A0		;POINT TO FAT
	IFZ	BigFAT,1$		;use 12-bit FAT
	SWAB	D1			;reverse the bytes
	MOVE.W	D1,0(A0,D0.W)		;direct index 16-bit FAT
	BRA	9$
1$:	ANDI.L	#$FFF,D0		;MAKE SURE RANGE IS OK
	ANDI.L	#$FFF,D1		;DITTO
	CMP.W	MaxCluster,D0		;IN RANGE?
	BHI	9$			;NO...SOMETHING BAD WRONG
	MOVE.W	#$F000,D3		;BIT MASK
	BTST	#0,D0			;CLUSTER NUMBER EVEN?
	BEQ.S	2$			;YES
	LSL.L	#4,D1			;ELSE SHIFT TO UPPER 12-BITS
	ROL	#4,D3			;SHIFT BIT MASK
2$:	MOVE.L	D0,D2
	ADD.L	D2,D2
	ADD.L	D0,D2			;*3
	LSR.L	#1,D2			;/2
	MOVE.B	1(A0,D2.W),D0		;GET CURRENT FAT ENTRY
	SWAB	D0			;TO UPPER BYTE
	MOVE.B	0(A0,D2.W),D0		;GET OTHER BYTE
	AND.W	D3,D0			;GET RID OF OLD CONTENTS
	OR.W	D1,D0			;OR IN NEW CONTENTS
	MOVE.B	D0,0(A0,D2.W)		;NOW STORE NEW CONTENTS
	SWAB	D0
	MOVE.B	D0,1(A0,D2.W)
9$:	POP	D2-D3/A0
	RTS

* CREATES NEW MS-DOS FILE.  FINDS AN UNUSED DIRECTORY ENTRY, BUILDS THE
* ENTRY.

NEW_FILE:
	BSR	GET_FREE_DIR		;FIND A FREE DIRECTORY ENTRY
	RTSERR				;OOPS...CANT FIND ONE
	MOVE.L	A0,DirPtr
	CLR.L	FILE_SIZE		;START WITH EMPTY FILE
	CLR.W	CLUSTER			;START WITH NO 'LAST CLUSTER'
	BSR	BUILD_DIR_ENTRY 	;FILL IN THE DIR ENTRY
	RTS

* PREPARES SELECTED DIRECTORY ENTRY FOR READ.

OPEN_FILE:
	MOVE.L	DirPtr,A0		;POINTER TO ACTIVE DIR ENTRY
	MOVE.W	ms_Cluster(A0),D0	;CLUSTER, BYTES REVERSED
	SWAB	D0			;CORRECT THE BYTES
	MOVE.W	D0,CLUSTER		;GET STARTING CLUSTER NUMBER
	BSR	CalcMSFileSize		;CALC FILE SIZE (BYTES) AND STORE
	CLR.W	BytCnt			;NO TEXT IN INPUT BUFFER
	RTS

* BUILDS A DIRECTORY ENTRY AT DirPtr, USING NAMES AND CLUSTER.

BUILD_DIR_ENTRY:
	MOVE.L	DirPtr,A1		;DIRECTORY ENTRY
	LEA	A.+1,A0			;MS-DOS NAME ALL READY TO GO
	MOVE.W	#11,D0			;11 CHARS IN NAME
	JSR	MOVE_CHARS		;MOVE NAME INTO DIRECTORY
	ZAP	D0
	MOVE.W	#10,D1
	JSR	STORE_D0_D1_TIMES	;ATTRIBUTE + 10 NULLS
	MOVE.L	DirPtr,A0
	MOVE.W	FILE_DATE,D0		;GET FILE DATE
	SWAB	D0
	MOVE.W	D0,ms_Date(A0)		;STORE FILE DATE
	MOVE.W	FILE_TIME,D0
	SWAB	D0
	MOVE.W	D0,ms_Time(A0)		;STORE FILE TIME
	CLR.W	ms_Cluster(A0)		;NO INITIAL CLUSTER
	BSR	PUT_FILE_SIZE		;STORE INITIAL FILE SIZE
	RTS

* READS THE NEXT CHAR FROM THE MS-DOS FILE.  RETURNS IN D0.  RETURNS CY=1
* AT EOF.

GET_CHAR:
	TST.W	BytCnt			;ANY CHARS LEFT IN INPUT BUFFER?
	BNE	1$			;YES...USE THEM
	BSR	READ_CLUSTER		;ELSE READ NEXT CLUSTER INTO BUFFER
	ERROR	9$			;READ ERROR
	TST.W	BytCnt			;DID WE REALLY GET ANYTHING?
	BEQ	9$			;NO...EOF
	JSR	MOTOR_OFF
1$:	MOVE.L	BytPtr,A0		;POINT TO NEXT BYTE
	MOVE.B	(A0)+,D0		;GET BYTE
	MOVE.L	A0,BytPtr		;SAVE UPDATED POINTER
	DECW	BytCnt			;ONE LESS BYTE
	RTS
9$:	STC
	RTS

* READS CURRENT CLUSTER INTO CLUSTER BUFFER, AND LOOKS UP NEXT CLUSTER OF
* THE FILE IN THE FAT.  RETURNS CY=1 ON DISK ERROR.  SETS UP BytCnt TO
* PROPER COUNT OR 0 AT EOF.

READ_CLUSTER:
	ZAP	D0
	CLR.W	BytCnt			;MAKE SURE NO BYTES TO PROCESS
	MOVE.W	CLUSTER,D0		;GET CURRENT CLUSTER
	BEQ	9$			;BAD CLUSTER NUMBER
	CMP.W	#$FFFF,D0		;END OF FILE?
	BEQ	9$			;YES...RETURN 0 LENGTH
	CMP.W	MaxCluster,D0		;IN RANGE?
	BHI	9$			;NO...TREAT AS EOF
	PUSH	D0
	BSR	GET_FAT			;GET NEXT FAT ENTRY FOR FILE
	MOVE.W	D0,CLUSTER		;SAVE FOR NEXT OPERATION
	MOVE.L	ClusterBuf,A0		;READ INTO HERE
	MOVE.L	A0,BytPtr		;RESET POINTER INTO TEXT
	POP	D0
	BSR	CLUSTER_TO_SEC		;CONVERT CLUSTER TO LOGICAL SECTOR
	MOVE.W	SEC_PER_CLUSTER,D1
	JSR	READ_N			;READ 1 OR 2 SEQUENTIAL SECTORS
	ERROR	10$			;READ ERROR
;	ZAP D0
	MOVE.L	ClusterSize,D0
	CMP.L	FILE_SIZE,D0		;LESS THAN A FULL CLUSTER?
	BCS.S	1$			;NO...GOT A FULL CLUSTER
	MOVE.L	FILE_SIZE,D0		;ELSE USE ACTUAL REMAINING COUNT
1$:	SUB.L	D0,FILE_SIZE		;SUBTRACT THE COUNT
	MOVE.W	D0,BytCnt		;THIS IS WHAT WE CAN WORK WITH
9$:	CLC
10$:	RTS

* WRITES CURRENT CLUSTER FROM CLUSTER BUFFER TO MS-DOS DRIVE.  WRITES
* 1 OR 2 FULL SECTORS.  WRITES TO SECTOR DEFINED BY CLUSTER.

WRITE_CLUSTER:
	ZAP	D0
	MOVE.W	BytCnt,D0		;CHECK NUMBER OF BYTES TO WRITE
	BEQ.S	8$			;NOTHING TO WRITE...IGNORE REQUEST
	ADD.L	D0,FILE_SIZE		;ADD THIS CLUSTER TO BYTE COUNT
	BSR	GET_FREE_FAT		;GET A CLUSTER FOR THIS WRITE
	ERROR	9$			;DIDN'T GET ONE...DISK FULL
	MOVE.W	CLUSTER,D1		;GET CLUSTER OF LAST WRITE (OR 0)
	EXG	D0,D1			;OLD TO D0, NEW TO D1
	MOVE.W	D1,CLUSTER		;SAVE FOR CURRENT WRITE
	TST.W	D0			;INITIAL CLUSTER?
	BNE.S	1$			;NO
	MOVE.L	DirPtr,A0		;ELSE UPDATE DIRECTORY ENTRY
	SWAB	D1			;REVERSE BYTES FOR MS-DOS
	MOVE.W	D1,ms_Cluster(A0)	;STORE INTO DIR BUFFER
	BRA.S	2$			;AND DONT TRY TO UPDATE OLD ENTRY
1$:	BSR	PUT_FAT			;LINK NEW CLUSTER INTO OLD FAT ENTRY
2$:	MOVE.W	CLUSTER,D0
	MOVE.W	#$FFFF,D1
	BSR	PUT_FAT			;MARK NEW ENTRY AS END OF FILE
	MOVE.L	ClusterBuf,A0		;WRITE FROM HERE
	MOVE.W	CLUSTER,D0		;GET CURRENT CLUSTER
	BEQ.S	9$			;BAD CLUSTER NUMBER...ABORT
	CMP.W	MaxCluster,D0		;IN RANGE?
	BHI.S	9$			;NO...BAIL OUT
	BSR	CLUSTER_TO_SEC		;CONVERT CLUSTER TO LOGICAL SECTOR
	MOVE.W	SEC_PER_CLUSTER,D1	;NUMBER OF SECTORS TO WRITE
	JSR	WRITE_N			;WRITE 1 OR 2 SEQUENTIAL SECTORS
	ERROR	9$			;WRITE ERROR
8$:	RTS
9$:	STC
	RTS

* CONVERTS CLUSTER NUMBER IN D0 TO LOGICAL SECTOR NUMBER IN D0.

CLUSTER_TO_SEC:
	AND.L	#$FFFF,D0		;just in case...
	SUB.W	#2,D0			;first 2 clusters (0,1) reserved
	MULU	SEC_PER_CLUSTER,D0
	ADD.W	DataSector,D0		;logical sector of cluster 2
	RTS

* Searches current directory for matching file name.  A. must be exactly
* 11 chars long, with '?' in wild card positions or blanks in unused
* positions.  Enter at FIND_FIRST to return first match, or FIND_NEXT
* to find next match in directory.  Returns CY=1 if no match.

FIND_FIRST:
	MOVE.	A.,M_WILD_NAME. 	;SAVE FOR POSSIBLE NEXT
	MOVE.L	DirectoryBuf,A0		;INIT TO TOP OF DIRECTORY
	BRA.S	FIND_COM
FIND_NEXT:
	MOVE.L	DirPtr,A0		;GET LAST POSITION
	ADD.L	#32,A0			;ADVANCE TO NEXT POSITION IN DIRECTORY
	CMPA.L	DirBufEnd,A0		;AT THE END OF THE DIRECTORY?
	BCS.S	FIND_COM		;YES...NO MORE FILE NAMES
NO_MATCH:
	STC
	RTS

FIND_COM:
	MOVE.L	A0,DirPtr		;SAVE CURRENT POSITION
	MOVE.B	(A0),D0			;GET FLAG BYTE
	BEQ.S	NO_MATCH		;UNUSED ENTRY...END OF DIRECTORY
	CMPI.B	#$E5,D0			;ERASED ENTRY?
	BEQ.S	FIND_NEXT		;YES
	MOVE.B	ms_Attrib(A0),D0	;GET ATTRIBUTE BYTE
	ANDI.B	#$E,D0			;HIDDEN, SYSTEM, OR VOL LABEL?
	BNE.S	FIND_NEXT		;YES...DONT USE IT
	MOVE.L	#M_WILD_NAME.+1,A1	;NAME IN WILD_NAME., SKIP OVER LENGTH
	MOVE.W	#10,D1			;11-CHAR NAME FIELD
1$:	MOVE.B	(A0)+,D2		;GET CHAR FROM DIRECTORY NAME
	MOVE.B	(A1)+,D0		;GET CHAR FROM REQUEST NAME
	CMP.B	#'?',D0			;WILD CARD?
	BEQ.S	2$			;YES...DONT COMPARE, ASSUME MATCH
	CMP.B	D0,D2			;ELSE SEE IF MATCH
	BNE.S	FIND_NEXT		;OOPS...NO MATCH...TRY NEXT DIR ENTRY
	BRA.S	3$
2$:	SETF	WILD_FLAG		;WILD-CARD CHARS IN SEARCH NAME
3$:	DBF	D1,1$			;ELSE TRY NEXT PAIR
	MOVEQ	#8,D0
	MOVE.L	DirPtr,A0
	LEA	NAME.,A1
	MOVE.B	D0,(A1)+
	JSR	MOVE_CHARS		;MOVE FILE NAME INTO NAME.
	PUSH	A0
	STRIP_TB. NAME.
;	ACHAR.	#'.',NAME.
	POP	A0
	CMP.B	#32,(A0)		;NO EXTENSION?
	BEQ.S	4$			;RIGHT...STOP NOW
	PUSH	A0
	ACHAR.	#'.',NAME.		;add in "dot"
	POP	A0
	MOVEQ	#3,D0			;ELSE ADD EXTENSION
	LEA	TMP.,A1
	MOVE.B	D0,(A1)+
	JSR	MOVE_CHARS		;GET FILE TYPE
	APPEND. TMP.,NAME.
	STRIP_TB. NAME.
4$:	CLC
	RTS				;NAME MATCH AT THIS ENTRY

* Searches Amiga directory for matching filename.  A. has full path and name.
* If A. contains wild cards, will remember for call to FIND_NEXT_AD.
* Returns CY=1 if no match.

FIND_FIRST_AD:
	ZAP	D0			;START BY ISOLATING PATH FROM NAME
	MOVE.L	D0,LOCK
	LEA	A.,A0
	MOVE.B	(A0)+,D0		;GET LENGTH
	BEQ	NO_AD_MATCH		;NOTHING...SEARCH FAILS
	ADD.L	D0,A0			;POINT PAST LAST BYTE
	DECW	D0
1$:	CMP.B	#'/',-(A0)		;PATH SEPARATOR?
	BEQ	2$			;YES
	CMP.B	#':',(A0)		;A DIFFRENT PATH SEPARATOR?
	BEQ	2$			;YES
	DBF	D0,1$			;ELSE LOOP
	CLR.B	PATH.			;NO PATH...USE CUR DIR
	BRA	3$
2$:	LEA	PATH.,A1		;MOVE PATH INTO PATH.
	INCW	D0			;ADJUST COUNT AS NECESSARY
	MOVE.B	D0,(A1)+		;LENGTH
	LEA	A.+1,A0
	PUSH	D0			;SAVE COUNT
	JSR	MOVE_CHARS		;MOVE IN STRING
	POP	D0
	CLIP.	D0,A.			;NOW GET RID OF PATH
3$:	MOVE.	A.,A_WILD_NAME. 	;SEARCH NAME
	MOVE.L	DosBase,A6
	MOVE.	PATH.,TMP.
	STG_Z.	TMP.
	MOVE.L	#TMP.,D1
	MOVEQ	#-2,D2
	CALLSYS	Lock			;TRY TO GET LOCK ON DIR
	MOVE.L	D0,LOCK			;GOT IT?
	BEQ.S	NO_AD_MATCH		;NO...BAIL OUT
	MOVE.L	D0,D1
	MOVE.L	#FILE_INFO,D2
	CALLSYS	Examine			;ELSE GET DIR ENTRY
	BRA.S	FN1

NO_AD_MATCH:
	MOVE.L	LOCK,D1
	BEQ.S	1$
	MOVE.L	DosBase,A6
	CALLSYS	UnLock
1$:	STC
	RTS

FIND_NEXT_AD:
	MOVE.L	LOCK,D1
	MOVE.L	#FILE_INFO,D2
	MOVE.L	DosBase,A6
	CALLSYS	ExNext			;GET NEXT DIR ENTRY
FN1:	TST.L	D0
	BEQ.S	NO_AD_MATCH		;END OF DIR...NO MORE
	TST.L	FIB_TYPE		;IS IT A DIR?
	BPL	FIND_NEXT_AD		;YES...TRY AGAIN
	Z_STG.	FIB_NAME,NAME.		;BUILD NAME FROM FILEINFO BLOCK
	STRIP_LB. NAME.			;CLEAN UP THE NAME
	STRIP_TB. NAME.
	UCASE.	NAME.
	LEA	A_WILD_NAME.,A0 	;POINTERS FOR WILD MATCH
	ZAP	D0
	MOVE.B	(A0)+,D0		;SET UP NAME VARIABLES
	MOVE.L	A0,WC_PTR
	MOVE.W	D0,WC_CNT
	LEA	NAME.,A0
	MOVE.B	(A0)+,D0
	MOVE.L	A0,N_PTR
	MOVE.W	D0,N_CNT
1$:	BSR	GET_WILD		;GET NEXT SEARCH NAME CHAR IN D0
	NOERROR 2$			;GOT ONE
	BSR	GET_NAME		;GET NEXT FILE NAME CHAR IN D1
	ERROR	MATCH			;OKAY...SAME LENGTH AND MATCH
	BRA	FIND_NEXT_AD		;ELSE TRY NEXT
2$:	CMP.B	#'?',D0			;WILD CARD?
	BNE	3$			;NO
	SETF	WILD_FLAG		;AHA! A WILD CARD OPERATION
	BSR	GET_NAME
	ERROR	FIND_NEXT_AD		;OOPS...FILENAME TOO SHORT
	BRA	1$
3$:	CMP.B	#'#',D0			;UNIVERSAL WILD CARD?
	BNE	5$			;NO
	SETF	WILD_FLAG
	BSR	GET_WILD		;ELSE MUST BE FOLLOWED BY '?'
	ERROR	FIND_NEXT_AD		;NO...OP MADE ERROR
	CMP.B	#'?',D0			;'#?' ?
	BNE	NO_AD_MATCH		;WILD CARD ERROR
	BSR	GET_WILD		;ELSE CHECK CHAR AFTER #?
	ERROR	MATCH			;NOTHING...TAKE WHAT WE HAVE
4$:	BSR	GET_NAME		;ELSE TRY TO ALIGN STRINGS AGAIN
	ERROR	FIND_NEXT_AD		;FILENAME TOO SHORT
	CMP.B	D0,D1			;ALIGNED?
	BNE.S	4$			;NO...TRY AGAIN
	BRA	1$			;YES...COMPARE CHAR-BY-CHAR
5$:	BSR	GET_NAME		;TRY CHAR-BY-CHAR
	ERROR	FIND_NEXT_AD		;FILENAME TOO SHORT
	CMP.B	D0,D1			;OK?
	BNE	FIND_NEXT_AD		;NO
	BRA	1$			;YES...TRY NEXT PAIR
MATCH:	Z_STG.	FIB_NAME,A.		;BUILD FULL PATHNAME
	MOVE.	PATH.,TMP.
	APPEND. A.,TMP.
	STG_Z.	TMP.
	MOVE.L	#EXISTING,D2
	MOVE.L	#TMP.,D1
	MOVE.L	DosBase,A6
	CALLSYS	Open			;TRY TO OPEN FOR READ
	MOVE.L	D0,FILEHANDLE
	BEQ	FIND_NEXT_AD		;OPEN FAILED...TRY NEXT
	BSR	ConvADDateTime		;CONVERT FILE DATE AND TIME
	RTS

* UTILITY SUBRS USED ABOVE.

GET_WILD:
	TST.W	WC_CNT			;GET NEXT CHAR FROM WILD_CARD STRING
	BEQ.S	1$
	MOVE.L	WC_PTR,A0
	MOVE.B	(A0)+,D0
	MOVE.L	A0,WC_PTR
	DECW	WC_CNT
	CLC
	RTS
1$:	STC
	RTS

GET_NAME:
	TST.W	N_CNT			;GET NEXT CHAR FROM NAME STRING
	BEQ.S	1$
	MOVE.L	N_PTR,A0
	MOVE.B	(A0)+,D1
	MOVE.L	A0,N_PTR
	DECW	N_CNT
	CLC
	RTS
1$:	STC
	RTS

* Calculates FILE SIZE FROM DIRECTORY ENTRY AND CORRECTS FOR DIFFERENT ORDER
* OF BYTES IN 68000.  A0 POINTS TO DIRECTORY ENTRY.

CalcMSFileSize:
	MOVE.L	ms_FileSize(A0),D0	;GET FILE SIZE, BYTES IN WRONG ORDER
	SWAB	D0			;FIX LOW WORD
	SWAP	D0			;SWAP WORDS
	SWAB	D0			;FIX HIGH WORD
	MOVE.L	D0,FILE_SIZE		;SAVE BYTE COUNT
	RTS

* MOVES FILE_SIZE INTO DIRECTORY ENTRY.

PUT_FILE_SIZE:
	MOVE.L	DirPtr,A0		;POINTER TO DIRECTORY ENTRY
	MOVE.L	FILE_SIZE,D0
	SWAB	D0			;REVERSE THE ORDER OF THE BYTES
	SWAP	D0
	SWAB	D0
	MOVE.L	D0,ms_FileSize(A0) 	;FINAL SIZE INTO DIR
	RTS

* PROCESS FORMAT COMMAND REQUESTS.

FORMAT_DISK:
	IFZ	NotFlop,20$		;don't format if not floppy
	DISP.	NotFlop.
	RTS
20$:	CLR.W	FirstSubClus		;make sure no subdir
	JSR	DISK_CAL		;SET TO TRACK 0, NO READ
	ERROR	9$			;DRIVE NOT READY
	BSR	SET_DRIVE_PARAMS	;SET UP PROPER DRIVE PARAMS
	ERROR	9$			;drive type must be wrong
	BSR	CalcParams
	BSR	AllocMSDOSBufs
	CLR.B	NEW_TRACK		;START WITH TRACK 0
1$:	CLR.B	NEW_SIDE		;SIDE 0
	MOVE.	FMSG3.,A.
	ZAP	D0
	MOVE.B	NEW_TRACK,D0
	STR2.	TMP.,#32
	APPEND.	TMP.,A.
	ACHAR.	#13,A.
	PROMPT.	A.
	JSR	FORMAT_TRACK		;DO ONE TRACK
	ERROR	9$			;ABORTING...DISK ERROR
	MOVE.W	SIDES_PER_DISK,D0
	CMPI.B	#1,D0			;SINGLE?
	BEQ.S	2$			;YES...DONT DO OTHER SIDE
	INCB	NEW_SIDE		;ELSE DO IT
	JSR	FORMAT_TRACK
	ERROR	9$
2$:	INCB	NEW_TRACK		;NOW ADVANCE TO NEXT TRACK
	ZAP	D0
	MOVE.B	NEW_TRACK,D0		;CHECK FOR LAST TRACK
	CMP.W	CYLS_PER_DISK,D0
	BCS	1$			;NOT YET...GO AGAIN
	MOVE.L	FATBuf,A0		;NOW INIT FAT
	MOVE.L	A0,A1
;	MOVE.W	#(FATBufSize/4)-1,D0	;CLEAR ENTIRE FAT BUFFER
	MOVE.L	FATBufSize,D0
	LSR.L	#2,D0
	DECW	D2
	ZAP	D1
3$:	MOVE.L	D1,(A1)+		;ZAP 4 BYTES AT A TIME
	DBF	D0,3$
	MOVE.B	DISK_TYPE,D0
	IFZ	ATARI_FLAG,5$		;not ATARI
	MOVE.B	ATARI_FLAG,D0
5$:	MOVE.B	D0,(A0)+		;media byte
	MOVE.B	#-1,(A0)+	 	;NOW LOAD INITIAL ENTRIES
	MOVE.B	#-1,(A0)+
	BSR	WRITE_FAT		;WRITE OUT BOTH FATS
	BSR	READ_DIR		;READ THE DIRECTORY SECTORS
	MOVE.L	DirectoryBuf,A0		;START AT THE BEGINNING
	MOVE.W	ENTRIES_PER_DIR,D1 	;THIS MANY TO CLEAR
	DECW	D1
4$:	MOVE.B	#$E5,(A0)		;EMPTY DIRECTORY ENTRY
	ADD.L	#32,A0			;POINT TO NEXT ENTRY
	DBF	D1,4$
	BSR	WRITE_DIR		;WRITE DIRECTORY BACK TO DISK
	IFZ	IS_3.5,7$		;DONT WRITE BOOT RECORD UNLESS 3.5"
	MOVE.L	BootBuf,A1		;DEST
	LEA	BOOT_REC,A0		;SOURCE
	MOVE.W	#SectorSize,D0		;MOVE ENTIRE SECTOR
	JSR	MOVE_CHARS		;COPY INTO BOOT 
	MOVE.L	BootBuf,A0		;USE EMPTY SECTOR OF FAT FOR BOOT
	ADD.L	#11,A0
	CLR.B	(A0)+			;LOW BYTE
	MOVE.B	#2,(A0)+		;HIGH BYTE OF 512 bytes per sector
	MOVE.B	#2,(A0)+		;SECTORS PER CLUSTER
	MOVE.B	#1,(A0)+		;1 RESERVED SECTOR-LOW BYTE
	CLR.B	(A0)+			;HIGH BYTE
	MOVE.W	NumberOfFATS,D0
	MOVE.B	D0,(A0)+		;COPIES OF FAT
	MOVE.B	#$70,(A0)+		;LOW BYTE OF MAX ROOT DIR ENTRIES-112
	CLR.B	(A0)+			;HIGH BYTE
	MOVE.W	SEC_PER_CYL,D0
	MULU	CYLS_PER_DISK,D0	;CALC NUMBER OF SECTORS, MAX
	MOVE.B	D0,(A0)+		;LOW BYTE OF NUMBER OF SECTORS
	SWAB	D0
	MOVE.B	D0,(A0)+		;HIGH BYTE
	MOVE.B	DISK_TYPE,D0
;	IFZ	ATARI_FLAG,5$		;NOT ATARI
;	MOVE.B	ATARI_FLAG,D0
;5$:
	MOVE.B	D0,(A0)+		;STORE FORMAT CHAR
	MOVE.W	SEC_PER_FAT,D0		;NUMBER OF SECTORS IN FAT
	MOVE.B	D0,(A0)+
	SWAB	D0
	MOVE.B	D0,(A0)+
	MOVE.W	SEC_PER_TRACK,D0
	MOVE.B	D0,(A0)+
	SWAB	D0
	MOVE.B	D0,(A0)+
	MOVE.W	SIDES_PER_DISK,D0
	MOVE.B	D0,(A0)+
	SWAB	D0
	MOVE.B	D0,(A0)+
	ZAP	D0			;boot sector is 0
	MOVE.L	BootBuf,A0		;write from this buffer
	JSR	WRITE_SECTOR		;WRITE OUT BOOT RECORD
	ERROR	9$
7$:	JSR	FLUSH_TRACK		;FORCE FINAL WRITE
9$:	RTS				;ALL DONE

* MS-DOS FILE CLOSE ROUTINE.  THIS IS ONLY CALLED ON WRITES TO MS-DOS.

CLOSE_FILE:
	BSR	PUT_FILE_SIZE		;STORE NEW FILE SIZE IN DIR
	BSR	WRITE_FAT		;WRITE OUT UPDATED FAT
	RTSERR
	BSR	WRITE_DIR		;SAME FOR DIRECTORY
	RTSERR
	JSR	FLUSH_TRACK		;WRITE OUT LAST TRACK
	RTS

* AMIGA-DOS FILE HANDLING ROUTINES

OPEN_AD_FILE:
	MOVE.	A_FNAME.,TMP.
	STG_Z.	TMP.
	MOVE.L	#TMP.,D1
	MOVEQ	#-2,D2			;ACCESS READ
	MOVE.L	DosBase,A6
	CALLSYS	Lock			;TRY TO LOCK THE FILE
	MOVE.L	D0,LOCK
	BNE	1$			;GOT IT
2$:	STC
	RTS				;ELSE RETURN AN ERROR
1$:	MOVE.L	D0,D1			;LOCK TO D1
	MOVE.L	#FILE_INFO,D2		;GET INFO BLOCK
	CALLSYS	Examine			;GET DATE TIME STAMP
	TST.L	D0
	BEQ	2$			;COULDN'T GET INFO...TREAT AS MISSING
	MOVE.L	FIB_TYPE,D0
	BPL	2$			;GOT A DIRECTORY, NOT A FILE
	BSR	ConvADDateTime		;CONVERT DATE/TIME TO INTERNAL FORM
	MOVE.L	LOCK,D1
	MOVE.L	DosBase,A6
	CALLSYS	UnLock			;NOW UNLOCK IT
	MOVE.L	#EXISTING,D2		;NOW OPEN IT FOR REAL
	BRA.S	AD_COM

CREATE_AD_FILE:
