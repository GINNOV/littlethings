* FINDS A FREE CLUSTER IN THE FAT.  RETURNS CLUSTER IN D0.  RETURNS CY=1
* IF DISK FULL.

GET_FREE_FAT:
	PUSH	D2-D3
	MOVE.W	MaxCluster,D2		;NUMBER OF ENTRIES TO CHECK
	DECW	D2
	MOVEQ	#1,D3			;BASE CLUSTER -1
1$:	MOVE.L	D3,D0			;PUT A CLUSTER NUMBER
	BSR	GET_FAT			;CHECK THIS FAT ENTRY
	TST.W	D0			;IS IT FREE?
	BEQ.S	2$			;YES...USE IT
	INCW	D3			;ELSE TRY NEXT ONE
	DBF	D2,1$			;LOOP
	DISP.	DISK_FULL.
	STC				;OOPS...DISK FULL
	BRA.S	9$
2$:	MOVE.W	D3,D0			;RETURN FREE CLUSTER IN D0
9$:	POP	D2-D3
	RTS

* FINDS NEXT FREE ENTRY IN DIRECTORY.  RETURNS POINTER IN A0 OR CY=1 IF
* DIR FULL.

GET_FREE_DIR:
	PUSH	D1
20$:	MOVE.W	ENTRIES_PER_DIR,D1	;MAX ENTRIES TO CHECK
	DECW	D1
	MOVE.L	DirectoryBuf,A0		;START AT TOP
1$:	MOVE.B	(A0),D0			;GET FIRST BYTE
	BEQ	9$			;FREE...USE IT
	CMP.B	#$E5,D0			;ERASED?
	BEQ	9$			;YES...USE IT
	ADD	#32,A0			;BUMP TO NEXT ENTRY
	DBF	D1,1$			;LOOP
	TST.W	FirstSubClus		;is this a subdir?
	BEQ	8$			;no...root dir is full
	CMP.W	#MaxEntries,ENTRIES_PER_DIR ;reached limit D2D can handle?
	BHI	8$			;yes...bail out
	MOVE.L	A0,DirPtr		;save pointer to place to clear
	BSR	GET_FREE_FAT		;allocate another cluster
	ERROR	8$			;oops...disk really is full
	MOVE.W	D0,D1			;new cluster to D1
	MOVE.W	LastSubClus,D0		;old last cluster of subdir file
	MOVE.W	D1,LastSubClus		;new last cluster of subdir file
	BSR	PUT_FAT			;update last link to new one
	MOVE.W	LastSubClus,D0
	MOVE.W	#$FFFF,D1
	BSR	PUT_FAT			;new cluster has no link
	MOVE.W	SEC_PER_CLUSTER,D0	;number of sectors added
	MULU	#SectorSize,D0		;this many bytes
	DIVU	#32,D0			;number of dir entries per cluster
	ADD.W	D0,ENTRIES_PER_DIR	
	MOVE.L	DirPtr,A0		;clear from here
	DECW	D0			;one fewer
2$:	MOVE.B	#$E5,(A0)+		;mark entry empty
	MOVEQ	#30,D1			;followed by 31 $F6's
3$:	MOVE.B	#$F6,(A0)+
	DBF	D1,3$
	DBF	D0,2$			;loop for all of new entries
	BRA	20$
8$:	DISP.	DIR_FULL.
	STC				;OOPS...DIR FULL
9$:	POP	D1
	RTS

* DELETES MS-DOS FILE.  DirPtr ASSUMED TO POINT TO ENTRY, AND FIRST
* CLUSTER IN CLUSTER.

DELETE_FILE:
	MOVE.L	DirPtr,A0		;POINT TO DIR ENTRY
	MOVE.B	#$E5,(A0)+		;MARK ENTRY AS UNUSED
	ZAP	D0
	MOVE.W	CLUSTER,D0		;GET STARTING CLUSTER
1$:	BEQ.S	2$			;CORRUPTED FILE...DONT MAKE IT WORSE
	CMP.W	#$FFFF,D0		;END OF FILE?
	BEQ.S	2$
	MOVE.L	D0,D3			;SAVE CURRENT CLUSTER
	BSR	GET_FAT			;GET NEXT CLUSTER IN D0
	EXG	D0,D3			;OLD CLUS TO D0, NEXT CLUS TO D3
	ZAP	D1
	BSR	PUT_FAT			;MARK OLD CLUS FREE
	MOVE.L	D3,D0			;NOW WORK ON NEXT CLUSTER
	BRA.S	1$
2$:	BSR	WRITE_FAT		;WRITE OUT FAT AND DIR
	ERROR	9$
	BSR	WRITE_DIR
	ERROR	9$
	JSR	FLUSH_TRACK		;FORCE OUT LAST PART OF DIR
9$:	RTS

