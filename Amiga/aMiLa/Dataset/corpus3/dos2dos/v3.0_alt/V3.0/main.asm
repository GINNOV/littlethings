	IFZ	LC_FLAG,5$		;no need to force lower case
	ZAP	D1
	LEA	TMP.,A0
	MOVE.B	(A0)+,D1		;get length of name
	DECW	D1
	BEQ.S	5$			;null name
1$:	MOVE.B	(A0),D0			;get a byte
	CMP.B	#'A',D0			;alpha?
	BLT.S	2$			;no
	CMP.B	#'Z',D0			;alpha?
	BGT.S	2$			;no
	BSET	#5,D0			;make lower case
2$:	MOVE.B	D0,(A0)+
	DBF	D1,1$			;loop
5$:	STG_Z.	TMP.			;NULL-TERMINATE THE STRING
	MOVE.L	#TMP.,D1
