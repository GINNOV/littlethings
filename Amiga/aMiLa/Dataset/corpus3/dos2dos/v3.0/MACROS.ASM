* THE FOLLOWING MACRO IMPLEMENTS CMP <EA>,<EA> BY LOADING D0 WITH PARAM2
* IF IT IS NOT ONE OF THE DATA REGS (D0-D7), OR ADDRESS REGS (A0-A7).
* WHERE PARAM2 IS An, CMPA.L IS USED (SIZE PARAM IS IGNORED).

COMP	MACRO	;SIZE,<EA>,<EA>
	IFC	'\3','D0'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D1'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D2'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D3'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D4'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D5'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D6'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','D7'
	CMP.\1	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A0'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A1'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A2'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A3'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A4'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A5'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A6'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	IFC	'\3','A7'
	CMPA.L	\2,\3
	MEXIT
	ENDC
	MOVE.\1	\3,D0
	CMP.\1	\2,D0
	ENDM

